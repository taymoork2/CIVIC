const tasks = loadProject(canvasRoot, { manifest: `${canvasRoot}/examples/tasks/civic.project.json` })
const now = Date.UTC(2026, 9, 12, 9)

test('a fetch-handler backend runs per run with its persona, role and condition, and only writes are mutations', async (t) => {
  const service = runtimeService(tasks, () => 'source-one')
  t.after(() => service.close())
  const start = (fields = {}) => service.handle({ action: 'start', scenario: 'tasks.list', persona: 'planner', role: 'member', condition: 'normal', now, ...fields })
  const call = (run, method, path, body) => service.handle({ action: method === 'GET' ? 'query' : 'mutation', run, name: `${method}:${path}`, args: { query: '', ...(body ? { body: JSON.stringify(body), type: 'application/json' } : {}) } })
  const a = await start(), b = await start()
  assert.deepEqual(a.seed, { tasks: 2 })
  const created = await call(a.id, 'POST', '/api/tasks', { title: 'Call the plumber' })
  assert.equal(created.status, 201)
  assert.equal(JSON.parse(created.body).createdAt, new Date(now).toISOString(), 'the run clock is fixed')
  assert.equal(JSON.parse((await call(a.id, 'GET', '/api/tasks')).body).length, 3)
  assert.equal(JSON.parse((await call(b.id, 'GET', '/api/tasks')).body).length, 2, 'runs never share data')
  await service.handle({ action: 'reset', run: a.id })
  assert.equal(JSON.parse((await call(a.id, 'GET', '/api/tasks')).body).length, 2)
  assert.deepEqual((await service.handle({ action: 'state', run: a.id })).tasks.map((task) => task.title), ['Water the plants', 'Book the dentist'])
  const viewer = await start({ role: 'viewer' })
  assert.equal((await call(viewer.id, 'POST', '/api/tasks', { title: 'Nope' })).status, 403)
  const down = await start({ condition: 'api-down' })
  assert.equal((await call(down.id, 'GET', '/api/tasks')).status, 503)
  await assert.rejects(service.handle({ action: 'query', run: a.id, name: 'POST:/api/tasks', args: { query: '', body: '{}' } }), /Reads are queries and writes are mutations/)
  await assert.rejects(service.handle({ action: 'mutation', run: a.id, name: 'POST:/api/../secrets', args: {} }), /Invalid function name/)
  await assert.rejects(service.handle({ action: 'query', run: a.id, name: 'CONNECT:/api/tasks', args: {} }), /Invalid request name/)
})

test('an app with sign-in runs signed in as its persona\'s synthetic identity, or signed out, and never sees a written secret', async (t) => {
  const board = loadProject(canvasRoot, { manifest: `${canvasRoot}/examples/team-board/civic.project.json` })
  const service = runtimeService(board, () => 'source-one')
  t.after(() => service.close())
  const start = (fields = {}) => service.handle({ action: 'start', scenario: 'board.home', persona: 'lead', role: 'member', condition: 'normal', now, ...fields })
  const call = (run, method, path, body) => service.handle({ action: ['GET', 'HEAD'].includes(method) ? 'query' : 'mutation', run, name: `${method}:${path}`, args: { query: '', ...(body ? { body: JSON.stringify(body), type: 'application/json' } : {}) } })
  const lead = await start()
  assert.deepEqual({ ...lead.identity, credential: undefined }, { id: 'alex', name: 'Alex Rivera', email: 'alex@team.example', credential: undefined, signedIn: true })
  assert.match(lead.identity.credential, /^review-[\w-]{24}$/)
  assert.ok(!JSON.stringify(lead.seed).includes(lead.identity.credential), 'the seed never carries the credential')
  assert.equal(JSON.parse((await call(lead.id, 'GET', '/api/me')).body).name, 'Alex Rivera', 'the run holds a session from the app\'s own sign-in')
  assert.equal((await call(lead.id, 'POST', '/api/posts', { text: 'Lunch at noon' })).status, 201)
  await service.handle({ action: 'reset', run: lead.id })
  assert.equal((await call(lead.id, 'GET', '/api/me')).status, 200, 'a reset signs in again')
  assert.equal((await call(lead.id, 'DELETE', '/api/session')).status, 204)
  assert.equal((await call(lead.id, 'GET', '/api/me')).status, 401, 'signing out clears the session cookie')

  const reader = await start({ role: 'reader', persona: 'newcomer' })
  assert.equal((await call(reader.id, 'POST', '/api/posts', { text: 'Hi' })).status, 403)

  assert.equal((await start({ scenario: 'board.sign-in' })).identity.signedIn, false, 'a sign-in screen starts signed out')
  const out = await start({ condition: 'signed-out' })
  assert.equal(out.identity.signedIn, false)
  assert.equal((await call(out.id, 'GET', '/api/me')).status, 401)
  assert.equal((await call(out.id, 'POST', '/api/session', { email: 'alex@team.example', password: 'guess' })).status, 401)
  const signed = await call(out.id, 'POST', '/api/session', { email: 'alex@team.example', password: '[review credential]' })
  assert.equal(signed.status, 200, 'the page sends a placeholder and the run swaps in its credential')
  assert.equal((await call(out.id, 'GET', '/api/me')).status, 200)
  assert.equal((await call(lead.id, 'POST', '/api/session', { email: 'alex@team.example', password: out.identity.credential })).status, 401, 'credentials belong to one run')
})

test('a manifest\'s review identities are synthetic and its sign-in request never writes a secret', () => {
  const base = { version: 1, id: 'app', name: 'App', adapter: { kind: 'module' }, sources: ['src'], navigation: ['Main'], roles: [{ id: 'r', label: 'R' }], conditions: [{ id: 'normal', label: 'Normal' }] }
  const persona = (identity) => ({ ...base, identity: { signIn: { path: '/api/session' } }, personas: [{ id: 'p', label: 'P', identity }] })
  assert.ok(checkedProject(persona({ id: 'pat', name: 'Pat', email: 'pat@team.example' })))
  assert.ok(checkedProject(persona({ id: 'pat', name: 'Pat', email: 'pat@example.com' })))
  assert.throws(() => checkedProject(persona({ id: 'pat', name: 'Pat', email: 'pat@gmail.com' })), /reserved example domain/)
  assert.throws(() => checkedProject(persona({ id: 'pat', name: 'Pat', email: 'pat@example.com', password: 'hunter2' })), /identity is \{ id, name, email \}/)
  assert.throws(() => checkedProject({ ...persona({ id: 'pat', name: 'Pat', email: 'pat@example.com' }), identity: { signIn: { path: '/api/session', body: { user: { password: 'hunter2' } } } } }), /never a written secret/)
  assert.throws(() => checkedProject({ ...persona({ id: 'pat', name: 'Pat', email: 'pat@example.com' }), identity: { signedOut: ['nope'] } }), /declared conditions/)
  assert.throws(() => checkedProject({ ...base, personas: [{ id: 'p', label: 'P', identity: { id: 'pat', name: 'Pat', email: 'pat@corp.com' } }] }), /reserved example domain/, 'persona identities are checked even without an identity block')
})

test('one run switches between its synthetic accounts, keeps its data and clock, and journals no credential', async (t) => {
  const board = loadProject(canvasRoot, { manifest: `${canvasRoot}/examples/team-board/civic.project.json` })
  const dataDir = await mkdtemp(join(tmpdir(), 'civic-run-'))
  let service = runtimeService(board, () => 'source-one', { dataDir })
  t.after(async () => { await service.close(); await rm(dataDir, { recursive: true, force: true }) })
  const call = (run, method, path, body, actor) => service.handle({ action: ['GET', 'HEAD'].includes(method) ? 'query' : 'mutation', run, name: `${method}:${path}`, ...(actor ? { actor } : {}), args: { query: '', ...(body ? { body: JSON.stringify(body), type: 'application/json' } : {}) } })
  const run = await service.handle({ action: 'start', scenario: 'board.home', persona: 'lead', role: 'member', condition: 'normal', now })
  assert.deepEqual({ account: run.account, subject: run.subject, accounts: run.accounts, clock: run.clock }, { account: 'lead', subject: 'alex', accounts: ['lead', 'newcomer'], clock: now })
  assert.ok(!JSON.stringify(run.seed).includes(run.identity.credential), 'the seed never carries a credential')
  assert.equal((await call(run.id, 'POST', '/api/posts', { text: 'From Alex' }, 'alex')).status, 201)
  assert.deepEqual(await service.handle({ action: 'identity', run: run.id, args: { account: 'newcomer' } }), { account: 'newcomer', subject: 'sam' })
  assert.equal(JSON.parse((await call(run.id, 'GET', '/api/me')).body).name, 'Sam Lee', 'the run now acts as the other account, through the app\'s own sign-in')
  await assert.rejects(call(run.id, 'POST', '/api/posts', { text: 'Stale pane' }, 'alex'), /account changed/, 'a page still acting as the old account is refused')
  await service.handle({ action: 'time', run: run.id, args: { minutes: 30 } })
  const later = JSON.parse((await call(run.id, 'POST', '/api/posts', { text: 'From Sam' }, 'sam')).body)
  assert.deepEqual({ author: later.author, postedAt: later.postedAt }, { author: 'Sam Lee', postedAt: new Date(now + 30 * 60_000).toISOString() })
  assert.deepEqual(JSON.parse((await call(run.id, 'GET', '/api/posts')).body).slice(-2).map((post) => post.author), ['Alex Rivera', 'Sam Lee'], 'switching accounts keeps the run\'s data')
  await assert.rejects(service.handle({ action: 'identity', run: run.id, args: { account: 'invented' } }), /Unknown synthetic account/)
  await assert.rejects(service.handle({ action: 'time', run: run.id, args: { minutes: 0 } }), /1 to 1440/)
  const journal = await readFile(join(dataDir, 'runtime', `${run.id}.json`), 'utf8')
  for (const secret of [run.identity.credential, 'review-']) assert.ok(!journal.includes(secret), 'the journal carries no credential')

  // Reopening after the server restarts replays the journal: the same account, clock and posts, with fresh credentials.
  await service.close()
  service = runtimeService(board, () => 'source-one', { dataDir })
  const reopened = await service.handle({ action: 'resume', run: run.id })
  assert.deepEqual({ account: reopened.account, clock: reopened.clock }, { account: 'newcomer', clock: now + 30 * 60_000 })
  assert.notEqual(reopened.identity.credential, run.identity.credential)
  assert.deepEqual(JSON.parse((await call(run.id, 'GET', '/api/posts')).body).slice(-2).map((post) => post.text), ['From Alex', 'From Sam'])
  // A second page taking the run over keeps it open when the first page's close arrives late.
  const second = await service.handle({ action: 'resume', run: run.id })
  assert.deepEqual(await service.handle({ action: 'close', run: run.id, lease: reopened.lease }), { closed: false })
  assert.equal((await call(run.id, 'GET', '/api/me')).status, 200)
  assert.deepEqual(await service.handle({ action: 'close', run: run.id, lease: second.lease }), { closed: true })
  await assert.rejects(service.handle({ action: 'resume', run: run.id.replace(/.$/, (c) => c === 'a' ? 'b' : 'a') }), /unavailable/)
  const changed = runtimeService(board, () => 'source-two', { dataDir })
  t.after(() => changed.close())
  await assert.rejects(changed.handle({ action: 'resume', run: run.id }), /another source revision/, 'a reopened run never silently runs on changed source')

  const tasksRun = runtimeService(tasks, () => 'source-one')
  t.after(() => tasksRun.close())
  const single = await tasksRun.handle({ action: 'start', scenario: 'tasks.list', persona: 'planner', role: 'member', condition: 'normal', now })
  assert.deepEqual(single.accounts, [])
  await assert.rejects(tasksRun.handle({ action: 'identity', run: single.id, args: { account: 'planner' } }), /one synthetic account|Unknown synthetic account/)
  await tasksRun.handle({ action: 'close', run: single.id })
  await assert.rejects(tasksRun.handle({ action: 'resume', run: single.id }), /keeps no journals/)
})

