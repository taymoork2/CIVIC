import { readFile, mkdir } from 'node:fs/promises'
import { chromium } from '@playwright/test'

const app = process.argv[2] ?? 'http://127.0.0.1:3005'
const allowed = new Set(['http://127.0.0.1:3005', 'https://macbook-pro.tail221f42.ts.net'])
if (!allowed.has(app)) throw new Error('Verify only this checkout’s development or approved phone preview.')
const account = JSON.parse(await readFile(new URL('../.data/flow-test-account.json', import.meta.url), 'utf8'))
const output = new URL('../.data/flow-verification/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, locale: 'en-GB' })
  await page.goto(`${app}/sign-in?redirect=%2Flaundry`)
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Password', { exact: true }).fill(account.password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('navigation', { name: 'Primary navigation' }).waitFor()
  await page.goto(`${app}/laundry`)
  await page.getByRole('heading', { name: 'Laundry', exact: true }).waitFor()
  await page.getByText('Synthetic cotton tee', { exact: true }).first().waitFor()
  console.log((await page.locator('main').innerText()).slice(0, 3500))
  await page.screenshot({ path: new URL('laundry-live-phone.png', output).pathname, fullPage: true })
  await page.getByRole('button', { name: 'Open lights load', exact: true }).click()
  await page.getByRole('heading', { name: 'Lights load', exact: true }).waitFor()
  console.log((await page.locator('main').innerText()).slice(0, 3500))
  await page.evaluate(async () => {
    await Promise.all(document.getAnimations().filter((animation) => animation.effect?.getComputedTiming().iterations !== Infinity).map((animation) => animation.finished.catch(() => {})))
  })
  await page.screenshot({ path: new URL('wash-preparation-live-phone.png', output).pathname, fullPage: true })
  await page.goto(`${app}/drying`)
  await page.getByRole('heading', { name: 'Drying', exact: true }).waitFor()
  const help = page.getByRole('button', { name: 'Load options', exact: true })
  if (await help.getAttribute('aria-expanded') !== 'false') throw new Error('Routine guidance starts expanded.')
  await page.getByRole('button', { name: 'Load into Synthetic dryer', exact: true }).click()
  await page.getByText('Going into this dryer', { exact: true }).waitFor()
  const fitHelp = page.getByRole('button', { name: 'About load size and heat', exact: true })
  const reminder = page.getByText('Fit is an estimate, based on recorded machine size and garment volume. Check the actual drum space before starting.', { exact: true })
  if (await reminder.isVisible()) throw new Error('Routine reminder should be collapsed initially.')
  if (await page.locator('ul').filter({ hasText: 'Fit is an estimate' }).count()) throw new Error('Reminder remains inside a clothing list.')
  await page.screenshot({ path: new URL('dryer-live-phone.png', output).pathname, fullPage: true })
  await fitHelp.press('Enter')
  await reminder.waitFor({ state: 'visible' })
  await page.screenshot({ path: new URL('dryer-help-phone.png', output).pathname, fullPage: true })
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Phone screen overflows horizontally.')
  const minutes = page.getByLabel('Minutes on Synthetic dryer', { exact: true })
  await minutes.fill('20')
  const clear = await minutes.evaluate((input) => {
    const box = input.getBoundingClientRect()
    const footer = document.querySelector('[data-slot="task-footer"]').getBoundingClientRect()
    return box.top >= 0 && box.bottom <= footer.top
  })
  if (!clear) throw new Error('Minutes field is obscured by the footer after focus.')
  await page.screenshot({ path: new URL('dryer-minutes-phone.png', output).pathname })
  const originalMinutes = await minutes.elementHandle()
  for (const width of [884, 1280, 390]) {
    await page.setViewportSize({ width, height: 900 })
    if (await minutes.inputValue() !== '20') throw new Error('Resizing lost the entered minutes.')
    if (!await minutes.evaluate((input, original) => input === original && document.activeElement === input, originalMinutes)) throw new Error('Resizing replaced or unfocused the minutes input.')
    const split = await page.locator('.task-layout').evaluate((layout) => {
      const [main, summary] = Array.from(layout.children).map((child) => child.getBoundingClientRect())
      return summary.left > main.left && summary.top < main.bottom
    })
    if (split !== (width >= 884)) throw new Error('Live task columns do not match available width.')
    const placement = await page.locator('[data-slot="task-footer"]').evaluate((footer) => getComputedStyle(footer).position)
    if (placement !== (width >= 884 ? 'static' : 'fixed')) throw new Error('Live action placement did not reflow.')
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Live task overflows horizontally.')
  }
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.screenshot({ path: new URL('dryer-live-wide.png', output).pathname, fullPage: true })
  console.log('Live account sign-in, drying preparation, collapsed help and keyboard disclosure verified; no wash/dryer was started.')
  console.log('Live phone/unfolded/desktop reflow preserves entered minutes and focus; action placement verified.')
} finally { await browser.close() }
