import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, convexAs, createHousehold, finishSession, freshPage, joinWithCode, planAndStart, signUp } from './flows'

test('authenticated outcome APIs preserve corrections, isolate reporters and reject replay after access is revoked', async ({ browser }) => {
  const owner = await freshPage(browser)
  const member = await freshPage(browser)
  try {
    await signUp(owner, 'outcome-owner', 'Olivia Outcome')
    await createHousehold(owner)
    await addProductAndWasher(owner)
    await addMachines(owner, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
    await addClothes(owner, { name: 'Outcome test tee' })
    await planAndStart(owner, 1)
    await finishSession(owner)
    const { client, householdId } = await convexAs(owner)
    const { textiles } = await client.query(api.inventory.list, { householdId })
    const record = (await client.query(api.sessions.washRecordsForTextile, { textileId: textiles[0]!.textileId }))[0]!
    const args = { recordId: record._id, dimension: 'odor' as const, checkedWhen: 'after_drying' as const,
      result: 'unknown' as const, expectedRevision: 0, receiptId: 'browser-outcome-original' }
    const first = await client.mutation(api.outcomeAssessments.save, args)
    const correction = { ...args, result: 'worse' as const, expectedRevision: 1, receiptId: 'browser-outcome-correction', note: 'Synthetic later inspection' }
    await client.mutation(api.outcomeAssessments.save, correction)
    expect(await client.mutation(api.outcomeAssessments.save, args)).toEqual({ ...first, replay: true })
    expect(await client.query(api.outcomeAssessments.forRecord, { recordId: record._id })).toEqual([expect.objectContaining({ revision: 2, result: 'worse' })])
    const audit = await client.query(api.outcomeAssessments.history, { recordId: record._id, dimension: 'odor', checkedWhen: 'after_drying', paginationOpts: { cursor: null, numItems: 10 } })
    expect(audit.page.map((row) => row.result)).toEqual(['worse', 'unknown'])
    const { code } = await client.mutation(api.households.createInvite, { householdId })
    await signUp(member, 'outcome-member', 'Morgan Outcome')
    await joinWithCode(member, code)
    const { client: other } = await convexAs(member)
    expect(await other.query(api.outcomeAssessments.forRecord, { recordId: record._id })).toEqual([])
    await other.mutation(api.outcomeAssessments.save, { ...args, result: 'improved' })
    expect((await client.query(api.outcomeAssessments.forRecord, { recordId: record._id }))[0]?.result).toBe('worse')
    const overall = { recordId: record._id, dimension: 'overall' as const, checkedWhen: 'after_wearing' as const, result: 'improved' as const, expectedRevision: 0, receiptId: 'browser-overall-result' }
    await client.mutation(api.outcomeAssessments.save, overall)
    await other.mutation(api.outcomeAssessments.save, { ...overall, result: 'unchanged' })
    expect((await client.query(api.sessions.washRecordsForTextile, { textileId: textiles[0]!.textileId }))[0]?.assessments.find((slot) => slot.dimension === 'overall')?.result).toBe('improved')
    expect((await other.query(api.sessions.garmentRecord, { textileId: textiles[0]!.textileId })).washes[0]?.assessments?.find((slot) => slot.dimension === 'overall')?.result).toBe('unchanged')
    await other.mutation(api.outcomeAssessments.save, { ...overall, result: null, expectedRevision: 1, receiptId: 'browser-member-overall-clear' })
    expect((await other.query(api.sessions.washRecordsForTextile, { textileId: textiles[0]!.textileId }))[0]?.assessments.find((slot) => slot.dimension === 'overall')?.result).toBeNull()
    expect((await client.query(api.sessions.garmentRecord, { textileId: textiles[0]!.textileId })).washes[0]?.assessments?.find((slot) => slot.dimension === 'overall')?.result).toBe('improved')
    const membership = (await client.query(api.households.members, { householdId })).find((person) => person.displayName === 'Morgan Outcome')!
    await client.mutation(api.households.removeMember, { membershipId: membership.membershipId })
    await expect(other.mutation(api.outcomeAssessments.save, { ...args, result: 'improved' })).rejects.toThrow('Forbidden')
    await expect(other.query(api.outcomeAssessments.forRecord, { recordId: record._id })).rejects.toThrow('Forbidden')
    expect(await client.query(api.sessions.washRecordsForTextile, { textileId: textiles[0]!.textileId })).toHaveLength(1)
  } finally {
    await owner.context().close()
    await member.context().close()
  }
})

test('the private editor keeps drafts across concurrent corrections and clears results with an audit', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 900 })
    await signUp(page, 'outcome-editor', 'Elliot Editor')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
    await addClothes(page, { name: 'Assessment editor tee' })
    await planAndStart(page, 1)
    await finishSession(page)
    const { client, householdId } = await convexAs(page)
    const textileId = (await client.query(api.inventory.list, { householdId })).textiles[0]!.textileId
    const recordId = (await client.query(api.sessions.washRecordsForTextile, { textileId }))[0]!._id
    const openHistory = async () => {
      await page.getByRole('button', { name: 'Back to Laundry', exact: true }).click()
      await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
      await page.getByRole('button', { name: /^Assessment editor tee,/ }).click()
      await page.getByRole('tab', { name: 'History', exact: true }).click()
      await page.getByText('How did a wash turn out?', { exact: true }).click()
    }
    await openHistory()
    await page.getByLabel('What are you checking?', { exact: true }).selectOption('odor')
    await page.getByLabel('When did you check?', { exact: true }).selectOption('after_drying')
    await expect(page.getByText('No assessment yet.', { exact: true })).toBeVisible()
    const pencil = page.getByRole('button', { name: 'Edit item details', exact: true, includeHidden: true })
    await expect(pencil).toBeEnabled()
    await page.getByRole('button', { name: 'Record result', exact: true }).click()
    const editor = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Assess wash', exact: true }) })
    await expect(editor.getByLabel('What changed?', { exact: true })).toHaveValue('')
    await expect(pencil).toBeVisible()
    await expect(pencil).toBeDisabled()
    await expect(editor.getByRole('button', { name: 'Save assessment', exact: true })).toBeDisabled()
    await editor.getByLabel('What changed?', { exact: true }).selectOption('unknown')
    await page.context().setOffline(true)
    await editor.getByRole('button', { name: 'Save assessment', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.keyboard.press('Escape')
    await expect(editor.getByText('Saving changes…', { exact: true })).toBeVisible()
    await expect(editor.getByRole('button', { name: 'Discard', exact: true })).toHaveCount(0)
    await page.context().setOffline(false)
    await expect(editor.getByText('Assessment saved.', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(editor).toHaveCount(0)
    await expect(pencil).toBeEnabled()
    await page.getByRole('button', { name: 'Correct result', exact: true }).click()
    await editor.getByLabel('What changed?', { exact: true }).selectOption('improved')
    await editor.getByLabel('Notes (optional)', { exact: true }).fill('Keep my unsaved observation')
    await page.keyboard.press('Escape')
    await expect(editor.getByText('Discard your changes?', { exact: true })).toBeVisible()
    await editor.getByRole('button', { name: 'Keep editing', exact: true }).click()
    for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['phone-dark', 390, 1, 'dark'], ['narrow-light-large', 320, 2, 'light'], ['narrow-dark-large', 320, 2, 'dark'], ['wide', 1024, 1, 'light'], ['wide-dark', 1024, 1, 'dark']] as const) {
      await page.setViewportSize({ width, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
      expect(await editor.evaluate((element) => element.scrollWidth <= element.clientWidth + 1), name).toBe(true)
      await editor.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
      await page.screenshot({ path: testInfo.outputPath(`assessment-editor-${name}.png`) })
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await client.mutation(api.outcomeAssessments.save, { recordId, dimension: 'odor', checkedWhen: 'after_drying', result: 'worse', note: 'Later inspection in another client', expectedRevision: 1, receiptId: 'editor-concurrent-correction' })
    await expect(editor.getByText('This result changed elsewhere. Your draft has been kept.', { exact: true })).toBeVisible()
    await expect(editor.getByLabel('What changed?', { exact: true })).toHaveValue('improved')
    await expect(editor.getByLabel('Notes (optional)', { exact: true })).toHaveValue('Keep my unsaved observation')
    await expect(editor.getByRole('button', { name: 'Save assessment', exact: true })).toBeDisabled()
    await editor.getByRole('button', { name: 'Discard draft and use latest result', exact: true }).click()
    await expect(editor.getByLabel('What changed?', { exact: true })).toHaveValue('worse')
    await editor.getByLabel('What changed?', { exact: true }).selectOption('improved')
    await editor.getByRole('checkbox', { name: 'I’ve checked this result', exact: true }).check()
    await editor.getByRole('button', { name: 'Save assessment', exact: true }).click()
    await expect(editor.getByText('Assessment saved.', { exact: true })).toBeVisible()
    await editor.getByRole('button', { name: 'Clear result', exact: true }).click()
    await expect(editor.getByRole('button', { name: 'Confirm clear result', exact: true })).toBeDisabled()
    await editor.getByRole('checkbox', { name: 'I’ve checked this result', exact: true }).check()
    await editor.getByRole('button', { name: 'Confirm clear result', exact: true }).click()
    await expect(editor.getByText('Result cleared. Correction history is retained.', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(editor).toHaveCount(0)
    await page.getByRole('button', { name: 'Show correction history', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Your correction history' })).toContainText('Revision 4')
    const slots = await client.query(api.outcomeAssessments.forRecord, { recordId })
    expect(slots).toEqual([expect.objectContaining({ result: null, revision: 4 })])
    for (let revision = 4; revision < 16; revision++) {
      await client.mutation(api.outcomeAssessments.save, { recordId, dimension: 'odor', checkedWhen: 'after_drying', result: revision % 2 === 0 ? 'unknown' : null, expectedRevision: revision, receiptId: `editor-history-page-${revision}` })
    }
    // Reopening starts a fresh bounded page; a live exhausted page preserves its cursor range.
    await page.getByRole('button', { name: 'Hide correction history', exact: true }).click()
    await page.getByRole('button', { name: 'Show correction history', exact: true }).click()
    const history = page.getByRole('region', { name: 'Your correction history' })
    await expect(history.getByRole('button', { name: 'Older corrections', exact: true })).toBeVisible()
    await history.getByRole('button', { name: 'Older corrections', exact: true }).click()
    await expect(history).toContainText('Revision 1 ·')
    await expect(history.getByRole('listitem')).toHaveCount(16)
    await page.getByRole('button', { name: 'Record result', exact: true }).click()
    await editor.getByLabel('What changed?', { exact: true }).selectOption('unknown')
    await editor.getByLabel('Notes (optional)', { exact: true }).fill('Draft for the older wash')
    const otherPage = await page.context().newPage()
    try {
      await client.mutation(api.inventory.updateTextile, { textileId, status: 'dirty' })
      await otherPage.goto('/laundry')
      await planAndStart(otherPage, 1)
      await finishSession(otherPage)
      await expect(editor.getByLabel('Notes (optional)', { exact: true })).toHaveValue('Draft for the older wash')
      await expect(editor.getByLabel('What changed?', { exact: true })).toHaveValue('unknown')
      await expect(page.getByLabel('Which wash?', { exact: true })).toHaveValue(recordId)
    } finally { await otherPage.close() }
    await page.bringToFront()
    await editor.getByLabel('Notes (optional)', { exact: true }).click()
    await page.keyboard.press('Escape')
    await editor.getByRole('button', { name: 'Discard', exact: true }).click()
    await expect(editor).toHaveCount(0)
    await page.reload()
    await page.getByRole('tab', { name: 'History', exact: true }).click()
    await page.getByText('How did a wash turn out?', { exact: true }).click()
    await page.getByLabel('What are you checking?', { exact: true }).selectOption('odor')
    await page.getByLabel('When did you check?', { exact: true }).selectOption('after_drying')
    await expect(page.getByText('No assessment yet.', { exact: true })).toBeVisible()
    await page.getByLabel('Which wash?', { exact: true }).selectOption(recordId)
    await expect(page.getByText('Your result was cleared.', { exact: true })).toBeVisible()
    expect(await client.query(api.sessions.washRecordsForTextile, { textileId })).toHaveLength(2)
  } finally { await page.context().close() }
})
