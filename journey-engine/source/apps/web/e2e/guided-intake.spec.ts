import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, openHousehold, signUp, topDialog } from './flows'

test('guided basics preserve Back, skip irrelevant questions and save unknown facts honestly', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'guided-basics', 'Guided Test')
  await createHousehold(page, 'At home')
  await openHousehold(page, 'Machines')
  await page.getByRole('button', { name: /^Add your washer and dryer/ }).click()
  await page.getByRole('button', { name: /^Add (an|another) appliance/ }).click()
  const sheet = topDialog(page)
  const next = sheet.getByRole('button', { name: 'Next', exact: true })
  await expect(next).toBeDisabled()
  await expect(sheet.getByRole('group', { name: 'Where is it?' })).toHaveCount(0)
  const washer = sheet.getByRole('button', { name: 'Washer', exact: true })
  const dryer = sheet.getByRole('button', { name: 'Dryer', exact: true })
  await sheet.evaluate(async (element) => { await Promise.all(element.getAnimations({ subtree: true }).map((animation) => animation.finished.catch(() => undefined))) })
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    const left = await washer.boundingBox()
    const right = await dryer.boundingBox()
    expect(left!.height).toBeGreaterThanOrEqual(76)
    expect(right!.y).toBe(left!.y)
    expect(right!.x).toBeGreaterThan(left!.x + left!.width)
    expect(await washer.locator('svg').evaluate(el => el.getBoundingClientRect().width)).toBe(32)
    await page.screenshot({ path: test.info().outputPath(`appliance-type-${theme}.png`) })
  }
  await page.emulateMedia({ colorScheme: 'light' })
  await sheet.getByRole('button', { name: 'Something else?', exact: true }).click()
  const hanging = sheet.getByRole('button', { name: 'Heated hanging dryer', exact: true })
  await hanging.click()
  await next.click()
  await expect(sheet.getByLabel('Number or label as printed')).toBeVisible()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(hanging).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await expect(hanging).toBeVisible()
  await page.evaluate(() => document.documentElement.style.fontSize = '')
  await page.setViewportSize({ width: 393, height: 852 })
  await washer.focus()
  await washer.press('Space')
  await expect(washer).toHaveAttribute('aria-pressed', 'true')
  await expect(dryer).toHaveAttribute('aria-pressed', 'false')
  await next.click()
  await expect(next).toBeDisabled()
  await sheet.getByRole('button', { name: 'Front', exact: true }).click()
  await next.click()
  await expect(sheet.getByLabel('Price per start')).toHaveCount(0)
  await sheet.getByLabel('Number or label as printed').fill('Home washer')
  await sheet.getByRole('button', { name: 'More: How many like it?' }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Front', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await next.click()
  await expect(sheet.getByLabel('Number or label as printed')).toHaveValue('Home washer')
  await next.click()
  await page.screenshot({ path: test.info().outputPath('appliance-review-light.png') })
  await sheet.getByRole('button', { name: 'Save 2 washers', exact: true }).click()
  await expect(sheet.getByRole('heading', { name: 'Appliance added' })).toBeVisible()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const machines = (await client.query(api.inventory.list, { householdId })).machines
  const added = machines.filter(machine => machine.name.startsWith('Home washer'))
  expect(added).toHaveLength(2)
  expect(added.every(machine => machine.highEfficiency === null && Object.keys(machine.cycleMinutes).length === 0)).toBe(true)

  await openHousehold(page, 'Products')
  await page.getByRole('button', { name: 'Add a product', exact: true }).click()
  await expect(next).toBeDisabled()
  await sheet.getByRole('button', { name: 'Liquid', exact: true }).click()
  await next.click()
  await expect(next).toBeDisabled()
  await sheet.getByRole('button', { name: 'Detergent', exact: true }).click()
  await next.click()
  await expect(next).toBeDisabled()
  await sheet.getByLabel('Product name').fill('Basic liquid')
  await next.click()
  await expect(sheet.getByRole('button', { name: 'Not recorded yet' })).toHaveAttribute('aria-pressed', 'true')
  await sheet.getByRole('button', { name: '1', exact: true }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(sheet.getByLabel('Product name')).toHaveValue('Basic liquid')
  await next.click()
  await expect(sheet.getByRole('button', { name: '1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await sheet.getByRole('button', { name: 'Not recorded yet' }).click()
  await next.click()
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
  for (const width of [320, 1200, 393]) {
    await page.setViewportSize({ width, height: 852 })
    expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  }
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  await expect(sheet).toBeVisible()
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('product-review-dark-enlarged.png') })
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  const products = (await client.query(api.inventory.list, { householdId })).supplies
  expect(products).toHaveLength(1)
  expect(products[0]).toMatchObject({ name: 'Basic liquid', measure: null, rules: [], safety: { bleachKind: 'unknown' } })
  await page.evaluate(() => document.documentElement.style.fontSize = '')

  await page.getByRole('button', { name: 'Add a product', exact: true }).click()
  await sheet.getByRole('button', { name: 'Pods', exact: true }).click()
  await next.click()
  await expect(sheet.getByLabel('Product name')).toBeVisible()
  await sheet.getByLabel('Product name').fill('Counted pods')
  await next.click()
  await expect(sheet.getByRole('heading', { name: 'Check your product' })).toBeVisible()
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await sheet.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Save', exact: true })).toBeEnabled()
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await sheet.getByRole('button', { name: 'Discard', exact: true }).click()
  expect((await client.query(api.inventory.list, { householdId })).supplies).toHaveLength(1)
})

test('setup uses the guided fields and a basic product still needs label directions to start', async ({ page }) => {
  await signUp(page, 'guided-setup', 'Guided Setup')
  await page.getByRole('button', { name: /Create a household/ }).click()
  await page.getByRole('button', { name: 'Create household', exact: true }).click()
  await page.getByRole('button', { name: /Where you wash/ }).click()
  await page.getByRole('radio', { name: 'Shared laundry room', exact: true }).click()
  await page.getByRole('button', { name: /^Machines/ }).click()
  const sheet = topDialog(page)
  const next = sheet.getByRole('button', { name: 'Next', exact: true })
  await sheet.getByRole('button', { name: 'Washer', exact: true }).click()
  await next.click()
  await sheet.getByRole('button', { name: 'Front', exact: true }).click()
  await next.click()
  await sheet.getByLabel('Number or label as printed').fill('Setup washer')
  await next.click()
  await sheet.getByRole('button', { name: 'Save washer', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: /^Products/ }).click()
  await sheet.getByRole('button', { name: 'Liquid', exact: true }).click()
  await next.click()
  await sheet.getByRole('button', { name: 'Detergent', exact: true }).click()
  await next.click()
  await sheet.getByLabel('Product name').fill('Setup liquid')
  await next.click()
  await next.click()
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const inventory = await client.query(api.inventory.list, { householdId })
  const supply = inventory.supplies[0]!
  await client.mutation(api.inventory.updateMachine, { machineId: inventory.machines[0]!.machineId, highEfficiency: true, cycleMinutes: { normal: 40 } })
  const ids = await client.mutation(api.inventory.createTextiles, { householdId, name: 'Synthetic setup tee', quantity: 1, kind: 'shirt', status: 'dirty', color: 'White', colorGroup: 'light', bulkUnits: 1, dyeRun: 'fast' })
  await client.mutation(api.inventory.setCare, { textileId: ids[0]!, material: 'cotton', washMethod: 'machine', cycle: 'normal', maxTemperatureC: 30, restrictions: [], provenance: { source: 'Synthetic label', confidence: 'observed' } })
  const planned = await client.mutation(api.plans.recompute, { householdId, selectedTextileIds: ids, clientInputHash: 'guided-missing-directions' })
  const held = await client.query(api.plans.get, { planId: planned.planId })
  expect(held!.loadStates.every(load => !load.startable)).toBe(true)
  await page.goto(`/laundry?plan=${planned.planId}`)
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Start wash/ })).toHaveCount(0)
  await expect(client.mutation(api.inventory.saveRule, { supplyId: supply.supplyId, dose: { amount: 1, unit: 'cap', mark: '1' }, stage: 'wash', placement: 'direct_to_drum', timing: 'Synthetic label', provenance: { source: 'Synthetic label', confidence: 'observed' } })).rejects.toThrow()
  await client.mutation(api.inventory.updateSupply, { supplyId: supply.supplyId, measure: { kind: 'cap', marks: [{ label: '1' }] }, safety: { bleachKind: 'none', incompatibleSupplyIds: [], incompatibleMaterials: [] } })
  await client.mutation(api.inventory.saveRule, { supplyId: supply.supplyId, dose: { amount: 1, unit: 'cap', mark: '1' }, stage: 'wash', placement: 'direct_to_drum', timing: 'Synthetic label', provenance: { source: 'Synthetic label', confidence: 'observed' } })
  const ready = await client.mutation(api.plans.recompute, { householdId, selectedTextileIds: ids, clientInputHash: 'guided-resolved-directions' })
  expect((await client.query(api.plans.get, { planId: ready.planId }))!.loadStates[0]?.startable).toBe(true)
})
