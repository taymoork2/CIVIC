import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addProductAndWasher, closetRows, convexAs, createHousehold, openHousehold, signUp, topDialog } from './flows'

test('saved edits, quantities, trash/restore, appliances, products and people survive reload', async ({ page }) => {
  await signUp(page, 'recovery', 'Rae Recovery')
  await createHousehold(page)
  await addProductAndWasher(page)
  await addClothes(page, { name: 'Everyday tee', count: 2, target: 'closet' })
  await closetRows(page, 'Everyday tee').click()
  // The editor opens over the record from the Details tab and returns to it after Save.
  const record = page.getByRole('dialog', { name: 'Everyday tee', exact: true })
  await record.getByRole('tab', { name: 'Details', exact: true }).click()
  await record.getByRole('button', { name: /^Name:/ }).click()
  await topDialog(page).getByLabel('Name', { exact: true }).fill('Edited tee')
  await topDialog(page).getByRole('button', { name: 'Save changes', exact: true }).click()
  const editedRecord = page.getByRole('dialog', { name: 'Edited tee', exact: true })
  await editedRecord.getByRole('button', { name: /^Quantity: 2\. Edit\.$/ }).click()
  let edit = topDialog(page)
  await expect(edit.getByRole('heading', { name: 'Quantity', exact: true })).toBeVisible()
  await expect(edit.getByLabel('Name', { exact: true })).toHaveCount(0)
  await edit.getByRole('spinbutton', { name: '2 matching pieces', exact: true }).fill('3')
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(page.getByRole('dialog', { name: 'Edited tee', exact: true }).getByRole('tab', { name: 'Details', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.reload()
  // The record's URL survives the reload; close it to read the list row behind it.
  await page.getByRole('dialog', { name: 'Edited tee', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(closetRows(page, 'Edited tee')).toContainText('×3')
  await closetRows(page, 'Edited tee').click()
  await topDialog(page).getByRole('tab', { name: 'Details', exact: true }).click()
  await topDialog(page).getByRole('button', { name: /^Quantity: 3\. Edit\.$/ }).click()
  edit = topDialog(page)
  await expect(edit.getByRole('heading', { name: 'Quantity', exact: true })).toBeVisible()
  // The quantity disclosure is a button; it opens on its own when Quantity was the row edited.
  const quantity = edit.getByRole('button', { name: 'Quantity', exact: true })
  if (await quantity.getAttribute('aria-expanded') !== 'true') await quantity.click()
  await edit.getByRole('spinbutton', { name: '3 matching pieces', exact: true }).fill('0')
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click()
  // With every piece in Trash the record has nothing left to show, so both sheets close.
  await expect(page.getByRole('dialog')).toHaveCount(0)
  // The closed record leaves no item in the address, so a later restore does not reopen it.
  await expect.poll(() => new URL(page.url()).searchParams.has('item')).toBe(false)
  await page.reload()
  await expect(closetRows(page)).toHaveCount(0)
  await page.getByRole('button', { name: 'Manage closet' }).click()
  await page.getByRole('button', { name: /^Trash/ }).click()
  const trash = page.getByRole('dialog', { name: 'Trash' })
  await expect(trash.locator('li')).toHaveCount(3)
  await trash.getByRole('button', { name: 'Restore', exact: true }).first().click()
  await expect(trash.locator('li')).toHaveCount(2)
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(closetRows(page, 'Edited tee')).toBeVisible()
  const { client, householdId } = await convexAs(page)
  expect((await client.query(api.inventory.list, { householdId })).textiles).toHaveLength(1)
  await openHousehold(page, 'Appliances')
  await page.getByRole('button', { name: /^Laundry room washer\b.*\. Edit settings$/ }).click()
  // The appliance record opens first; its editor saves back onto the still-open record.
  await page.getByRole('dialog', { name: 'Laundry room washer' }).getByRole('button', { name: 'Edit settings', exact: true }).click()
  await topDialog(page).getByLabel('Number or label as printed', { exact: true }).fill('Updated washer')
  await topDialog(page).getByRole('button', { name: 'Save washer', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Updated washer' })).toBeVisible()
  await page.getByRole('dialog', { name: 'Updated washer' }).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: /^Updated washer\b.*\. Edit settings$/ })).toBeVisible()
  await openHousehold(page, 'Products')
  await page.getByRole('button', { name: /^Tide HE liquid, .*\. Open product$/ }).click()
  // Like the appliance, the product record stays open beneath its editor and after Save.
  await page.getByRole('dialog', { name: 'Tide HE liquid' }).getByRole('button', { name: 'Edit details', exact: true }).click()
  await topDialog(page).getByLabel('Product name', { exact: true }).fill('Updated detergent')
  await topDialog(page).getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Updated detergent' })).toBeVisible()
  await page.getByRole('dialog', { name: 'Updated detergent' }).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: /^Updated detergent, .*\. Open product$/ })).toBeVisible()
  await openHousehold(page, 'People')
  await page.getByRole('button', { name: /^Add clothing profile\b/ }).click()
  await page.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Robin')
  await page.getByRole('dialog').getByRole('button', { name: 'Child', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Child', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('dialog').getByRole('button', { name: 'Save person', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: /^Open Robin\. Child\b/ })).toBeVisible()
})

test('refresh, cleaner drop-off/pickup and external washing preserve care history', async ({ page }) => {
  await signUp(page, 'care-actions', 'Cass Care')
  await createHousehold(page)
  await addClothes(page, { name: 'Refresh shirt', kind: 'shirt', target: 'closet' })
  await closetRows(page, 'Refresh shirt').click()
  await page.getByRole('button', { name: 'Needs a refresh', exact: true }).click()
  await page.getByRole('button', { name: 'Wrinkles', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await closetRows(page, 'Refresh shirt').click()
  await page.getByRole('button', { name: 'Refreshed', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Steamed it', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Aired it out', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await addClothes(page, { name: 'Cleaner blazer', kind: 'suit', wash: 'Dry clean only' })
  await closetRows(page, 'Cleaner blazer').click()
  await page.getByRole('button', { name: 'Dropped off', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Dropped off', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await closetRows(page, 'Cleaner blazer').click()
  await page.getByRole('dialog').getByRole('button', { name: 'Picked up', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await addClothes(page, { name: 'Hand washed tee' })
  await closetRows(page, 'Hand washed tee').click()
  await page.getByRole('button', { name: 'Record a wash', exact: false }).click()
  await page.getByRole('button', { name: 'By hand', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  const { client, householdId } = await convexAs(page)
  const { textiles } = await client.query(api.inventory.list, { householdId })
  expect(textiles.every((textile) => textile.status === 'clean')).toBe(true)
  expect(textiles.find((textile) => textile.name === 'Hand washed tee')?.washCount).toBe(1)
})
