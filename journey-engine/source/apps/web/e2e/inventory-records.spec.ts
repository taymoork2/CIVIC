import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addMachines, convexAs, createHousehold, openHousehold, signUp, topDialog } from './flows'

test('product Edit follows the visible tab, and removal confirms without losing the record', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'inventory-records', 'Inventory Records')
  await createHousehold(page)
  await openHousehold(page, 'Products')
  await page.getByRole('button', { name: 'Add a product', exact: true }).click()
  const sheet = topDialog(page)
  await sheet.getByRole('button', { name: 'Pods', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByLabel('Product name').fill('Synthetic pods')
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const original = (await client.query(api.inventory.list, { householdId })).supplies[0]!
  await page.getByRole('main').getByRole('button', { name: /^Synthetic pods/ }).click()
  await expect(sheet.getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  const edit = sheet.getByRole('button', { name: 'Edit details', exact: true })
  await expect(sheet.locator('.sheet-head').getByRole('button', { name: 'Edit details', exact: true })).toHaveCount(1)
  await expect(sheet.locator('.sheet-body').getByRole('button', { name: 'Edit details', exact: true })).toHaveCount(0)
  await expect(edit).toBeInViewport({ ratio: 1 })
  const editBox = (await edit.boundingBox())!
  const footerBox = (await sheet.locator('.sheet-foot').boundingBox())!
  expect(editBox.y + editBox.height).toBeLessThanOrEqual(footerBox.y)
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('product-facts-light.png') })
  for (const tab of ['Contents', 'Directions', 'Facts']) {
    await sheet.getByRole('tab', { name: tab, exact: true }).click()
    await expect(sheet.locator('[data-slot="tabs-content"][hidden]')).toHaveCount(2)
    expect(await sheet.locator('[data-slot="tabs-content"][hidden]').evaluateAll(elements => elements.every(el => el.getBoundingClientRect().height === 0))).toBe(true)
    await expect(edit).toBeInViewport({ ratio: 1 })
    await edit.focus()
    await page.keyboard.press('Enter')
    await expect(edit).toHaveCount(0)
    await expect(sheet.getByRole('tab', { name: tab, exact: true })).toHaveAttribute('aria-selected', 'true')
    await sheet.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(edit).toBeInViewport({ ratio: 1 })
  }
  await page.setViewportSize({ width: 320, height: 852 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  await edit.scrollIntoViewIfNeeded()
  await expect(edit).toBeInViewport({ ratio: 1 })
  expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('product-facts-dark-enlarged.png') })
  await page.evaluate(() => document.documentElement.style.fontSize = '')
  await page.setViewportSize({ width: 1200, height: 900 })
  await edit.scrollIntoViewIfNeeded()
  await expect(edit).toBeInViewport({ ratio: 1 })
  await edit.click()
  await expect(edit).toHaveCount(0)
  await sheet.getByLabel('Product name').fill('Unsaved name')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  await sheet.getByRole('button', { name: 'Find manufacturer details', exact: true }).click()
  const source = page.getByRole('dialog', { name: 'Source details' })
  await source.getByRole('button', { name: 'Cancel', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Facts', exact: true }).click()
  await expect(sheet.getByLabel('Product name')).toHaveValue('Unsaved name')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove product', exact: true }).click()
  await expect(sheet).toContainText('Past laundry history stays')
  expect((await client.query(api.inventory.list, { householdId })).supplies[0]).toEqual(original)
  await sheet.getByRole('button', { name: 'Keep product', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Facts', exact: true }).click()
  await expect(sheet.getByLabel('Product name')).toHaveValue('Unsaved name')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove product', exact: true }).click()
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await sheet.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Facts', exact: true }).click()
  await expect(sheet.getByLabel('Product name')).toHaveValue('Unsaved name')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove product', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove product', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect((await client.query(api.inventory.list, { householdId })).supplies[0]).toEqual({ ...original, archived: true })
  await page.reload()
  await page.getByRole('button', { name: 'Removed (1)', exact: true }).click()
  await page.getByRole('main').getByRole('button', { name: /^Synthetic pods/ }).click()
  await edit.click()
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Restore product', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect((await client.query(api.inventory.list, { householdId })).supplies[0]).toEqual(original)
})

test('appliance removal confirms, keeps canceled edits and supports restoration', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'appliance-removal', 'Appliance Removal')
  await createHousehold(page)
  await addMachines(page, { kind: 'Washer', name: 'Synthetic washer', count: 1, price: '2.50', minutes: '40' })
  const { client, householdId } = await convexAs(page)
  const original = (await client.query(api.inventory.list, { householdId })).machines[0]!
  await page.getByRole('main').getByRole('button', { name: /^Synthetic washer/ }).click()
  const sheet = topDialog(page)
  await expect(sheet.getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  await expect(sheet.locator('.sheet-head').getByRole('button', { name: 'Edit settings', exact: true })).toHaveCount(1)
  await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
  const name = sheet.getByLabel('Number or label as printed')
  await name.fill('Unsaved washer')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  await sheet.getByRole('button', { name: 'Find manufacturer details', exact: true }).click()
  await page.getByRole('dialog', { name: 'Source details' }).getByRole('button', { name: 'Cancel', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Details', exact: true }).click()
  await expect(name).toHaveValue('Unsaved washer')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove appliance', exact: true }).click()
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
  await expect(sheet).toContainText('Past laundry history stays')
  expect((await client.query(api.inventory.list, { householdId })).machines[0]).toEqual(original)
  await sheet.getByRole('button', { name: 'Keep appliance', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Details', exact: true }).click()
  await expect(name).toHaveValue('Unsaved washer')
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Remove appliance', exact: true }).click()
  await page.screenshot({ path: test.info().outputPath('appliance-remove-light.png') })
  await sheet.getByRole('button', { name: 'Remove appliance', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect((await client.query(api.inventory.list, { householdId })).machines[0]).toEqual({ ...original, archived: true })
  await page.reload()
  await page.getByRole('button', { name: 'Removed (1)', exact: true }).click()
  await page.getByRole('main').getByRole('button', { name: /^Synthetic washer/ }).click()
  await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
  await sheet.getByRole('tab', { name: 'More', exact: true }).click()
  await sheet.getByRole('button', { name: 'Restore appliance', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect((await client.query(api.inventory.list, { householdId })).machines[0]).toEqual(original)
})
