import { expect, test } from '@playwright/test'
import { addBottle, createHousehold, freshPage, signUp, openAdvanced } from './flows'

// Requires the saved reviewed owner manifest, including Downy GTIN 00030772103111.
// Synthetic private pack entry proves lookup behavior, not a physical household match.
test('identifier lookup validates saved candidates and requires deliberate market and physical confirmation', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  await page.setViewportSize({ width: 390, height: 844 })
  await signUp(page, 'catalog-identifier', 'Casey Identifier')
  await createHousehold(page)
  await addBottle(page, 'Identifier lookup test pack', ['1'])
  await page.getByRole('button', { name: /Identifier lookup test pack/ }).click()
  await page.getByRole('button', { name: 'Edit details', exact: true }).click()
  await openAdvanced(page, 'More')
  await page.getByRole('button', { name: 'Find manufacturer details', exact: true }).click()
  const catalog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Source details', exact: true }) })
  const identifier = catalog.getByLabel('UPC, EAN or GTIN printed on the pack', { exact: true })
  const search = catalog.getByRole('button', { name: 'Find by identifier', exact: true })
  await expect(search).toBeDisabled()
  await identifier.fill('030772103110')
  await search.click()
  await expect(catalog.getByRole('alert')).toContainText('valid check digit')
  await identifier.fill('96385074')
  await search.click()
  await expect(catalog.getByRole('status')).toContainText('No reviewed saved manufacturer details')
  await identifier.fill('0 30772-10311 1')
  await search.click()
  await expect(catalog.getByText(/Saved identifier: 00030772103111/)).toBeVisible()
  await expect(catalog.getByRole('button', { name: /^Review Downy/ })).toHaveCount(0)
  await catalog.getByLabel('Market on your pack', { exact: true }).selectOption('US')
  const review = catalog.getByRole('button', { name: /^Review Downy/ })
  await expect(review).toHaveCount(1)
  await review.click()
  await expect(catalog.getByRole('button', { name: 'Save reference', exact: true })).toBeDisabled()
  await expect(catalog.getByLabel('Market', { exact: true })).toHaveValue('')
  await expect(catalog.getByLabel('Pack or model identifier', { exact: true })).toHaveValue('')
  await expect(catalog.getByLabel('Label revision', { exact: true })).toHaveValue('')
  await expect(catalog.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await expect(catalog).toContainText('saved care and doses stay unchanged')
  for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['narrow-dark-large', 320, 2, 'dark'], ['wide', 1024, 1, 'light']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ colorScheme: theme })
    await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
    await catalog.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
    expect(await catalog.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`catalog-identifier-${name}.png`), fullPage: true })
  }
  // Search edits immediately discard prior lookup results instead of showing an obsolete candidate.
  await identifier.fill('96385074')
  await expect(review).toHaveCount(0)
  await catalog.getByLabel('Brand printed on the item', { exact: true }).fill('No saved synthetic brand')
  await catalog.getByRole('button', { name: 'Find details', exact: true }).click()
  await expect(catalog).toContainText('Enter the label manually')
  await catalog.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Discard your changes?', exact: true }).getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(catalog).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Edit details', exact: true }).click()
  await openAdvanced(page, 'More')
  await expect(page.getByRole('button', { name: 'Find manufacturer details', exact: true })).toBeVisible()
  await page.context().close()
})
