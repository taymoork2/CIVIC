import { expect, test } from '@playwright/test'
import { addBottle, createHousehold, freshPage, signUp, openAdvanced } from './flows'

// Explicit synthetic catalog ingestion/review occurs on the isolated backend before this test.
test('manufacturer matching keeps manual product facts separate and pins a checked source revision', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  await page.setViewportSize({ width: 390, height: 844 })
  await signUp(page, 'catalog', 'Casey Catalog')
  await createHousehold(page)
  await addBottle(page, 'Synthetic HE detergent', ['1'])
  await page.getByRole('button', { name: /Synthetic HE detergent/ }).click()
  await page.getByRole('button', { name: 'Edit details', exact: true }).click()
  await openAdvanced(page, 'More')
  await page.getByRole('button', { name: 'Find manufacturer details', exact: true }).click()
  const catalog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Source details', exact: true }) })
  await catalog.getByLabel('Brand printed on the item').fill('Synthetic Catalog')
  await catalog.getByRole('button', { name: 'Find details', exact: true }).click()
  await catalog.getByLabel('Product and exact variant').selectOption({ label: 'Synthetic HE detergent · Liquid test pack · US · TEST-123' })
  await catalog.getByRole('checkbox', { name: /Lipase disclosure/ }).check()
  await catalog.getByLabel('Market', { exact: true }).fill('US')
  await catalog.getByLabel('Pack or model identifier', { exact: true }).fill('TEST-123')
  await catalog.getByLabel('Label revision', { exact: true }).fill('test-label-1')
  await catalog.getByText('Sources and review', { exact: true }).click()
  await expect(catalog).toContainText('Synthetic factual summary; not a real household pack.')
  await catalog.getByRole('button', { name: 'Save reference', exact: true }).click()
  await expect(page.getByRole('button', { name: 'View matched manufacturer details', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Synthetic HE detergent', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit details', exact: true }).click()
  await openAdvanced(page, 'More')
  await page.getByRole('button', { name: 'View matched manufacturer details', exact: true }).click()
  await expect(catalog).toContainText('Later catalog updates do not replace it.')
  await expect(catalog.getByRole('checkbox', { name: /Lipase disclosure/ })).toBeChecked()
  await catalog.getByText('Sources and review', { exact: true }).click()
  for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['narrow-dark-large', 320, 2, 'dark'], ['wide', 1024, 1, 'light']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ colorScheme: theme })
    await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
    await catalog.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
    expect(await catalog.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`catalog-${name}.png`), fullPage: true })
  }
  await catalog.getByRole('button', { name: 'Remove reference', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Find manufacturer details', exact: true })).toBeVisible()
  await page.context().close()
})
