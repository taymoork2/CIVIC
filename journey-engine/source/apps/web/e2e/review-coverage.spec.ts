import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { expect, test } from '@playwright/test'

test.use({ trace: 'off', viewport: { width: 1440, height: 1000 } })
test.skip(process.env.WASHCLOSET_REVIEW_E2E !== '1', 'Run explicitly against isolated Rehearsal.')

test('coverage prototypes preserve the app draft and persist independently', async ({ page }) => {
  await page.goto('/review?scenario=intake.towel.fabric')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const live = page.locator('iframe[title="Live towel journey"]')
  const frame = page.frameLocator('iframe[title="Live towel journey"]')
  await frame.getByLabel('Other material 1', { exact: true }).fill('Coverage retained draft')
  const initialUrl = await live.getAttribute('src')
  await page.locator('.rh-brand').getByRole('button', { name: /^Coverage/ }).click()
  const panel = page.getByRole('region', { name: 'Coverage bridge', exact: true })
  await panel.getByRole('combobox', { name: 'Show', exact: true }).selectOption('journey')
  await panel.getByRole('button', { name: /Multicolor pack with shared care/ }).click()
  await panel.getByRole('button', { name: 'Edit prototype', exact: true }).click()
  const title = `Synthetic candidate ${Date.now()}`
  await panel.getByLabel('Heading', { exact: true }).fill(title)
  await panel.getByLabel('Example input', { exact: true }).fill('Captured sample')
  await panel.getByRole('button', { name: 'Test proposal', exact: true }).click()
  await expect(panel.getByText('Captured locally: Captured sample. No app operation was performed.')).toBeVisible()
  await panel.getByRole('button', { name: 'Save prototype', exact: true }).click()
  await expect(panel.getByText('Saved locally.', { exact: true })).toBeVisible()
  await expect(frame.getByLabel('Other material 1', { exact: true })).toHaveValue('Coverage retained draft')
  await expect(live).toHaveAttribute('src', initialUrl!)
  await page.getByRole('button', { name: 'Inspect', exact: true }).click()
  await page.locator('.rh-brand').getByRole('button', { name: /^Coverage/ }).click()
  await expect(panel.getByLabel('Heading', { exact: true })).toHaveValue(title)
  const result = await (await page.request.get('/api/review/coverage')).json()
  const candidate = result.candidates.find((c: { id: string }) => c.id === 'journey.multicolor-pack')
  expect(candidate.title).toBe(title)
  expect(candidate.code).toContain(title)
  expect(result.report.targets.find((t: { id: string }) => t.id === candidate.id).verification).toBe('unverified')
  await page.screenshot({ path: resolve('../..', '.review-data/coverage-qa.png') })
  await panel.getByRole('combobox', { name: 'Show', exact: true }).selectOption('all')
  await panel.getByLabel('Heading', { exact: true }).fill('Unpublished coverage draft')
  await panel.getByRole('button', { name: /Recover from a washer problem Expected screen/ }).click()
  await expect(panel.getByRole('heading', { name: 'Discard unpublished coverage edits?' })).toBeVisible()
  await panel.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(panel.getByLabel('Heading', { exact: true })).toHaveValue('Unpublished coverage draft')
  await panel.getByRole('button', { name: /Recover from a washer problem Expected screen/ }).click()
  await panel.getByRole('button', { name: 'Discard edits and open', exact: true }).click()
  await panel.getByRole('button', { name: 'Edit repository expectation', exact: true }).click()
  const editor = panel.getByRole('textbox', { name: 'Expected screen, interaction or journey', exact: true })
  const intent = JSON.parse(await editor.inputValue())
  const expected = 'A failed retry retains the washer selection and preparation state.'
  if (!intent.acceptance.includes(expected)) intent.acceptance.push(expected)
  await editor.fill(JSON.stringify(intent, null, 2))
  await panel.getByRole('button', { name: 'Save expectation', exact: true }).click()
  await expect(panel.getByText('Repository expectation saved. Inventory will refresh automatically.')).toBeVisible()
  await expect(page.getByText('Code or expectations changed. Inventory refreshed; the open preview and draft are retained.')).toBeVisible()
  const contract = JSON.parse(await readFile(resolve('../..', 'docs/design/review-product/coverage.json'), 'utf8'))
  expect(contract.targets.find((t: { id: string }) => t.id === 'screen.machine-problem').acceptance).toContain(expected)
  await expect(frame.getByLabel('Other material 1', { exact: true })).toHaveValue('Coverage retained draft')
  await expect(live).toHaveAttribute('src', initialUrl!)
})
