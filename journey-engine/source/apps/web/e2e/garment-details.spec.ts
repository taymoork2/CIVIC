import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { careLabel, convexAs, createHousehold, signUp } from './flows'

test('garment details accept typed quantity, visible identity and filtered or new tags', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'garment-details', 'Details Test')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = page.getByRole('dialog')
  const titleTop = await sheet.getByRole('heading', { name: 'What is it?', exact: true }).evaluate((heading) => heading.getBoundingClientRect().top - heading.closest('header')!.getBoundingClientRect().top)
  await sheet.getByRole('button', { name: 'T-shirt', exact: true }).click()
  await expect.poll(() => sheet.getByRole('heading', { name: 'Whose is it?', exact: true }).evaluate((heading) => heading.getBoundingClientRect().top - heading.closest('header')!.getBoundingClientRect().top)).toBe(titleTop)
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await expect(sheet.getByRole('heading', { name: 'Item details', exact: true })).toBeVisible()
  await expect(sheet.locator('.sheet-kicker')).toHaveCount(0)
  const progress = sheet.getByRole('progressbar', { name: 'Form progress' })
  await expect(progress).toHaveAttribute('aria-valuenow', '3')
  await expect(progress).toHaveAttribute('aria-valuemax', '12')
  await expect(sheet.getByText(/How many/i)).toHaveCount(0)
  const quantity = sheet.getByLabel('Quantity', { exact: true })
  for (const value of ['', '0', '21', '2.5']) {
    await quantity.fill(value)
    await expect(sheet.getByRole('button', { name: 'Next: fabric', exact: true })).toBeDisabled()
  }
  await quantity.fill('10')
  await sheet.getByLabel('Name', { exact: true }).fill('Rangoon Tee')
  await sheet.getByLabel('Brand', { exact: true }).fill('Rangoon')
  const sizeInput = sheet.getByLabel('Size', { exact: true })
  await expect(sizeInput).toHaveValue('')
  await expect(sizeInput).toHaveAttribute('placeholder', 'Not specified')
  await expect.poll(() => quantity.evaluate((input) => {
    const size = input.closest('[role=dialog]')!.querySelector<HTMLInputElement>('input[name=size]')!
    return Math.abs(input.getBoundingClientRect().y - size.getBoundingClientRect().y)
  })).toBeLessThan(2)
  const brand = await sheet.getByLabel('Brand', { exact: true }).boundingBox()
  const size = await sizeInput.boundingBox()
  expect(brand!.y).toBeGreaterThan(size!.y + size!.height)
  await expect.poll(() => sheet.getByRole('button', { name: 'Back', exact: true }).evaluate((back) => {
    const close = back.closest('header')!.querySelector<HTMLButtonElement>('.sheet-close-icon')!
    return Math.abs(back.getBoundingClientRect().y - close.getBoundingClientRect().y)
  })).toBeLessThan(2)
  await sizeInput.fill('32 × 30')
  const tags = sheet.getByRole('textbox', { name: 'Tags', exact: true })
  await tags.fill('wor')
  await expect(sheet.getByRole('button', { name: 'Work', exact: true })).toBeVisible()
  await expect(sheet.getByRole('button', { name: 'Sleep', exact: true })).toHaveCount(0)
  await tags.fill('work')
  await tags.press('Enter')
  await expect(sheet.getByRole('button', { name: 'Work', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await tags.fill('Trip to Kyoto')
  await sheet.getByRole('button', { name: 'Add tag', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Trip to Kyoto', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await tags.fill(' trip   to Kyoto ')
  await tags.press('Enter')
  await expect(sheet.getByRole('button', { name: 'Trip to Kyoto', exact: true })).toHaveCount(1)
  await tags.fill('fuck')
  await tags.press('Enter')
  await expect(sheet.getByRole('alert')).toContainText('offensive language')
  await tags.fill('')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await expect(progress).toHaveAttribute('aria-valuenow', '4')
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(progress).toHaveAttribute('aria-valuenow', '3')
  await expect(quantity).toHaveValue('10')
  await expect(sheet.getByLabel('Brand', { exact: true })).toHaveValue('Rangoon')
  await expect(sizeInput).toHaveValue('32 × 30')
  await sizeInput.fill('M')
  await sizeInput.fill('32 × 30')
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    for (const width of [393, 320]) for (const scale of [1, 2]) {
      await page.setViewportSize({ width, height: 852 })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${scale * 16}px` }, scale)
      expect(await sheet.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
      await expect.poll(() => sheet.getByRole('button', { name: 'Back', exact: true }).evaluate((back) => {
        const close = back.closest('header')!.querySelector<HTMLButtonElement>('.sheet-close-icon')!
        return Math.abs(back.getBoundingClientRect().y - close.getBoundingClientRect().y)
      })).toBeLessThan(2)
      expect(await progress.evaluate((element) => {
        const close = element.closest('header')!.querySelector('.sheet-close-icon')!.getBoundingClientRect()
        const back = element.closest('header')!.querySelector('.sheet-back')!.getBoundingClientRect()
        const bounds = element.getBoundingClientRect()
        return Math.abs(bounds.x + bounds.width / 2 - (back.right + close.left) / 2) < 2 && bounds.top >= close.top && bounds.bottom <= close.bottom
      })).toBe(true)
    }
    await page.setViewportSize({ width: 393, height: 852 })
    await page.evaluate(() => { document.documentElement.style.fontSize = '' })
    await sheet.locator('.sheet-scroll').evaluate((scroll) => { scroll.scrollTop = 0 })
    await page.screenshot({ path: test.info().outputPath(`details-${theme}.png`) })
  }
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'White', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  await careLabel(sheet, 'Cold', 'Low heat')
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await expect(progress).toHaveAttribute('aria-valuetext', 'Step 12 of 12')
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(sheet.getByRole('status')).toContainText('10')
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const inventory = await client.query(api.inventory.list, { householdId })
  expect(inventory.textiles).toHaveLength(10)
  for (const piece of inventory.textiles) {
    expect(piece).toMatchObject({ name: 'Rangoon Tee', identity: { brand: 'Rangoon', size: '32 × 30' }, tags: ['Trip to Kyoto', 'Work'] })
  }
})

test('an unanswered discard warning waits for a choice, keeps the draft, and explicit choices still work', async ({ page }) => {
  await signUp(page, 'discard-timeout', 'Draft Test')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'T-shirt', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet.getByLabel('Name', { exact: true }).fill('Keep this draft')
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  // v11 asks in a modal confirmation that stays until a choice is made; nothing closes it on a timer.
  const ask = page.getByRole('alertdialog', { name: 'Discard your changes?', exact: true })
  await expect(ask.getByRole('button', { name: 'Keep editing', exact: true })).toBeFocused()
  await page.clock.runFor(10000)
  await expect(ask.getByRole('button', { name: 'Keep editing', exact: true })).toBeVisible()
  await ask.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(ask).toHaveCount(0)
  await expect(sheet.getByLabel('Name', { exact: true })).toHaveValue('Keep this draft')
  await expect(sheet.getByRole('heading')).toBeFocused()
  await page.clock.runFor(5000)
  await expect(sheet.getByLabel('Name', { exact: true })).toHaveValue('Keep this draft')
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await ask.getByRole('button', { name: 'Discard', exact: true }).click()
  await page.clock.runFor(300)
  await expect(sheet).toHaveCount(0)
})
