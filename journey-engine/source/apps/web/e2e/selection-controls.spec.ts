import { expect, test } from '@playwright/test'
import { createHousehold, freshPage, signUp } from './flows'

test('timer alerts toggle by keyboard and keep their preference after reload', async ({ browser }) => {
  const page = await freshPage(browser)
  try {
    await signUp(page, 'selection-controls', 'Synthetic Settings')
    await createHousehold(page)
    await page.goto('/settings')
    await expect(page.locator('[inert]')).toHaveCount(0)
    const alerts = page.getByRole('switch', { name: /^Timer alerts in the app/ })
    await expect(alerts).toBeChecked()
    await alerts.focus()
    await expect(alerts).toBeFocused()
    await alerts.press('Space')
    await expect(alerts).not.toBeChecked()
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('washcloset:prefs:appearance')!).alerts)).toBe(false)
    await page.reload()
    await expect(page.locator('[inert]')).toHaveCount(0)
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('washcloset:prefs:appearance')!).alerts)).toBe(false)
    await expect(alerts).not.toBeChecked()
    await alerts.press('Enter')
    await expect(alerts).toBeChecked()
    await page.reload()
    await expect(alerts).toBeChecked()
  } finally { await page.context().close() }
})

test('switches reflow while independent dose checks and exclusive answers keep distinct semantics', async ({ page }, testInfo) => {
  test.skip(process.env.WASHCLOSET_E2E_BUILD === 'production', 'Visual fixtures are development-only')
  for (const [width, scale, theme] of [[393, 1, 'light'], [320, 2, 'dark'], [1280, 1, 'light']] as const) {
    await page.setViewportSize({ width, height: 852 })
    await page.emulateMedia({ colorScheme: theme })
    await page.goto(`/design-preview?screen=settings-index&textScale=${scale}`)
    const alerts = page.getByRole('switch', { name: /^Timer alerts in the app/ })
    await expect(alerts).toBeChecked()
    await alerts.uncheck()
    await expect(alerts).not.toBeChecked()
    expect((await alerts.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const appearance = page.getByRole('radiogroup', { name: 'Appearance', exact: true })
    await appearance.getByRole('radio', { name: 'Dark', exact: true }).check()
    await appearance.getByRole('radio', { name: 'Light', exact: true }).check()
    await expect(appearance.getByRole('radio', { name: 'Dark', exact: true })).not.toBeChecked()
    await expect(appearance.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
    await page.screenshot({ path: testInfo.outputPath(`settings-${width}-${scale}-${theme}.png`), fullPage: true })
    await alerts.check()
    await page.screenshot({ path: testInfo.outputPath(`settings-on-${width}-${scale}-${theme}.png`), fullPage: true })
  }
  await page.setViewportSize({ width: 393, height: 852 })
  await page.goto('/design-preview?screen=dose-checks')
  await expect(page.locator('[inert]')).toHaveCount(0)
  await page.getByRole('radio', { name: '1', exact: true }).click()
  const checks = page.getByRole('checkbox')
  expect(await checks.count()).toBeGreaterThanOrEqual(2)
  const [first, second] = await checks.all()
  await first!.focus()
  await page.keyboard.press('Space')
  await second!.check()
  await expect(first!).toBeChecked()
  await expect(second!).toBeChecked()
  await page.getByRole('radio', { name: 'The label doesn’t say', exact: true }).check()
  await expect(page.getByRole('radio', { name: '1', exact: true })).not.toBeChecked()
  await expect(page.getByRole('radio', { name: 'The label doesn’t say', exact: true })).toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('dose-checks-and-radios.png'), fullPage: true })
  await page.goto('/design-preview?screen=dose-checks&state=busy')
  for (const control of await page.getByRole('checkbox').all()) await expect(control).toBeDisabled()
  for (const control of await page.getByRole('radio').all()) await expect(control).toBeDisabled()
})
