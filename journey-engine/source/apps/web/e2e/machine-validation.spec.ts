import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addMachines, convexAs, createHousehold, signUp, topDialog } from './flows'

test('optional machine evidence blocks Save and can be cleared without recording it', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await signUp(page, 'machine-validation', 'Machine Test')
  await createHousehold(page)
  await addMachines(page, { kind: 'Washer', name: 'Synthetic washers', count: 5 })
  await page.getByRole('button', { name: /^Synthetic washers/ }).click()
  const sheet = topDialog(page)
  await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Sanitizer', exact: true }).click()
  const save = sheet.getByRole('button', { name: 'Save washer', exact: true })
  await sheet.getByRole('button', { name: 'Center agitator', exact: true }).click()
  await sheet.getByLabel('Rinse contact minutes', { exact: true }).fill('16')
  await expect(save).toBeDisabled()
  const error = sheet.getByRole('alert')
  await expect(error).toHaveText('Complete the rinse contact time and source, or clear this optional record.')
  expect(await error.evaluate(el => !!el.closest('.sheet-scroll'))).toBe(true)
  expect(await sheet.locator('.sheet-foot [role=alert]').count()).toBe(0)
  await sheet.getByLabel('Where the program contact time was checked', { exact: true }).fill('Synthetic release-to-drain observation')
  await expect(save).toBeEnabled()
  await sheet.getByLabel('Where the program contact time was checked', { exact: true }).fill('')
  await expect(save).toBeDisabled()
  await error.scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('machine-validation-dark.png') })
  await sheet.getByRole('button', { name: 'Clear rinse contact time', exact: true }).click()
  await expect(save).toBeEnabled()
  await save.click()
  await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Programs', exact: true }).click()
  const normal = sheet.getByRole('group', { name: 'Normal care', exact: true })
  await normal.getByLabel('Checked program and selected options', { exact: true }).fill('Synthetic incomplete program')
  await expect(save).toBeDisabled()
  await normal.getByRole('button', { name: 'Remove checked program', exact: true }).click()
  await expect(save).toBeEnabled()
  await save.click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const { machines } = await client.query(api.inventory.list, { householdId })
  expect(machines).toHaveLength(5)
  for (const machine of machines) {
    expect(Object.keys(machine.rinseContact ?? {})).toHaveLength(0)
    expect(Object.keys(machine.washProcesses ?? {})).toHaveLength(0)
  }
  await page.getByRole('button', { name: /^Synthetic washers/ }).click()
  await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
  await sheet.getByRole('tab', { name: 'Sanitizer', exact: true }).click()
  await sheet.getByRole('button', { name: 'Center agitator', exact: true }).click()
  await expect(save).toBeDisabled()
  await sheet.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('alertdialog', { name: 'Discard your changes?', exact: true }).getByRole('button', { name: 'Discard', exact: true }).click()
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect((await client.query(api.inventory.list, { householdId })).machines).toHaveLength(5)
})
