import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, convexAs, createHousehold, freshPage, signUp } from './flows'

// Origin and destination are independent; dye stays unknown and pest treatment follows the label.
for (const [dryer, destination] of [['High heat', 'Needs washing'], ['Low heat', 'Needs washing'], ['Low heat', 'Ready to wear']] as const) test(`pre-owned clothes can be ${destination} with ${dryer}`, async ({ browser }) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 393, height: 852 })
    await signUp(page, `pre-owned-${dryer === 'High heat' ? 'high' : 'low'}-${destination === 'Ready to wear' ? 'ready' : 'wash'}`, 'Synthetic Thrift')
    await createHousehold(page)
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('link', { name: 'Closet', exact: true }).click()
    await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
    const add = page.getByRole('dialog')
    await add.getByRole('button', { name: 'T-shirt', exact: true }).click()
    await add.getByRole('button', { name: 'Next: details', exact: true }).click()
    await add.getByLabel('Name', { exact: true }).fill('Vintage tee — synthetic')
    await add.getByRole('button', { name: 'Next: fabric', exact: true }).click()
    await add.getByRole('button', { name: 'Next: color', exact: true }).click()
    await add.getByRole('radio', { name: 'Navy', exact: true }).click()
    await add.getByRole('button', { name: 'Next: where from', exact: true }).click()
    // Not pre-owned: the dye question follows. Pre-owned has none, so the origin step leads to the care label.
    await expect(add.getByRole('button', { name: 'Next: dye', exact: true })).toBeVisible()
    const preOwned = add.getByRole('checkbox', { name: 'Pre-owned (thrift, hand-me-down)', exact: true })
    await expect(preOwned).not.toBeChecked()
    await add.getByText('Pre-owned (thrift, hand-me-down)', { exact: true }).click()
    await expect(preOwned).toBeChecked()
    await preOwned.uncheck()
    await expect(add.getByRole('button', { name: 'Next: dye', exact: true })).toBeVisible()
    await expect(add.getByRole('checkbox', { name: 'Thin or damaged', exact: true })).toHaveCount(0)
    await preOwned.focus()
    await page.keyboard.press('Space')
    await expect(preOwned).toBeChecked()
    await expect(add.getByRole('button', { name: 'Next: dye', exact: true })).toHaveCount(0)
    await expect(add.getByText(/check the rinse water/)).toBeVisible()
    await expect(add.getByText('(optional)', { exact: true }).locator('..')).toContainText('Smells of…')
    await expect(add.getByText('Optional.', { exact: true })).toHaveCount(0)
    const fragile = add.getByRole('checkbox', { name: 'Thin or damaged', exact: true })
    await expect(fragile).not.toBeChecked()
    await fragile.check()
    await add.getByRole('button', { name: 'Musty', exact: true }).click()
    await add.getByRole('button', { name: 'Back', exact: true }).click()
    await add.getByRole('button', { name: 'Next: where from', exact: true }).click()
    await expect(preOwned).toBeChecked()
    await expect(fragile).toBeChecked()
    await expect(add.getByRole('button', { name: 'Musty', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await fragile.uncheck()
    for (const theme of ['light', 'dark'] as const) {
      await page.emulateMedia({ colorScheme: theme })
      await page.screenshot({ path: test.info().outputPath(`origin-393-${theme}.png`), animations: 'disabled' })
    }
    await page.setViewportSize({ width: 320, height: 800 })
    await page.screenshot({ path: test.info().outputPath('origin-320.png'), animations: 'disabled' })
    await page.setViewportSize({ width: 393, height: 852 })
    await add.getByRole('button', { name: 'Next: care label', exact: true }).click()
    await add.getByRole('group', { name: 'Washtub on the tag' }).getByRole('button', { name: 'Cold', exact: true }).click()
    await add.getByRole('button', { name: 'Next', exact: true }).click()
    await add.getByRole('radio', { name: /Tag doesn.t say/ }).click()
    await add.getByRole('button', { name: 'Next', exact: true }).click()
    await add.getByRole('radio', { name: dryer, exact: true }).click()
    await add.getByRole('button', { name: 'Next', exact: true }).click()
    await add.getByRole('radio', { name: 'No stains', exact: true }).click()
    await add.getByRole('button', { name: 'Next: review', exact: true }).click()
    await expect(add.getByRole('radio', { name: 'Ready to wear', exact: true })).toBeChecked()
    await expect(add.getByRole('radiogroup', { name: 'How dirty?', exact: true })).toHaveCount(0)
    await add.getByRole('radio', { name: 'Needs washing', exact: true }).click()
    await expect(add.getByRole('radiogroup', { name: 'How dirty?', exact: true })).toBeVisible()
    if (destination === 'Ready to wear') {
      await add.getByRole('radio', { name: destination, exact: true }).click()
      await expect(add.getByRole('radiogroup', { name: 'How dirty?', exact: true })).toHaveCount(0)
    }
    await expect(add.getByRole('heading', { name: 'Review item', exact: true })).toBeVisible()
    await expect(add.getByRole('button', { name: 'Edit drying', exact: true })).toContainText(dryer)
    for (const theme of ['light', 'dark'] as const) {
      await page.emulateMedia({ colorScheme: theme })
      await page.screenshot({ path: test.info().outputPath(`review-393-${theme}.png`), animations: 'disabled' })
    }
    await expect(add.getByRole('button', { name: 'Pest treatment options', exact: true })).toBeVisible()
    await expect(add.getByText(/Heat treatment is a kill threshold/)).not.toBeVisible()
    await add.getByRole('button', { name: 'Pest treatment options', exact: true }).click()
    const pest = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Pest treatment', exact: true }) })
    if (dryer === 'High heat') {
      await expect(add.getByText(/Heat treatment is a kill threshold/)).not.toBeVisible()
      await add.getByRole('checkbox', { name: 'Heat-treat first' }).click()
      await expect(add.getByRole('checkbox', { name: 'Heat-treat first' })).toBeChecked()
      if (process.env.WASHCLOSET_E2E_BUILD === 'production') await expect(add.getByText(/Heat treatment is a kill threshold/)).toBeVisible()
    } else {
      await expect(add.getByText('This label does not allow high-heat pest treatment. For normal drying, follow the drying instruction recorded below.')).toBeVisible()
      await expect(add.getByRole('checkbox', { name: 'Heat-treat first' })).toHaveCount(0)
      await expect(add.getByText(/Heat treatment is a kill threshold/)).not.toBeVisible()
    }
    await pest.getByRole('button', { name: 'Back to garment', exact: true }).click()
    if (dryer === 'High heat') await expect(add.getByRole('button', { name: 'Pest treatment: heat-treat first', exact: true })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath('final-393.png') })
    await page.setViewportSize({ width: 320, height: 800 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath('final-320.png') })
    await add.getByRole('button', { name: 'Save item', exact: true }).click()
    await expect(add.getByRole('status')).toContainText('added')
    await add.getByRole('button', { name: 'Done', exact: true }).click()
    const { client, householdId } = await convexAs(page)
    const { textiles } = await client.query(api.inventory.list, { householdId })
    expect(textiles).toHaveLength(1)
    expect(textiles[0]).toMatchObject({ status: destination === 'Ready to wear' ? 'clean' : 'dirty', dyeRun: 'unknown', preOwned: { smell: 'musty' }, care: { dryMethod: 'tumble_dry', dryHeat: dryer === 'High heat' ? 'high' : 'low' } })
    if (dryer === 'High heat') expect(textiles[0]!.preOwned).toHaveProperty('heatTreat', true)
    else expect(textiles[0]!.preOwned).not.toHaveProperty('heatTreat')
    expect(textiles[0]!.preOwned).not.toHaveProperty('fragile')
    expect(textiles[0]!.firstWash).toBeNull()
    if (destination === 'Ready to wear') {
      await page.reload()
      await page.getByRole('button', { name: /^Vintage tee — synthetic,/ }).click()
      await expect(page.getByRole('dialog')).not.toContainText('Wash before wearing')
      await expect(page.getByRole('dialog').getByRole('button', { name: 'Add to hamper', exact: true })).toBeEnabled()
      await page.getByRole('dialog').getByRole('button', { name: /More on the label/ }).click()
      const label = page.getByRole('dialog').last()
      await expect(label.getByRole('heading', { name: 'More on the label', exact: true })).toBeVisible()
      await expect(label.getByRole('group', { name: 'Washtub on the tag', exact: true })).toHaveCount(0)
      await label.getByRole('button', { name: 'Do not steam', exact: true }).click()
      await label.getByRole('button', { name: 'Save label answers', exact: true }).click()
      await expect(page.getByRole('dialog')).toHaveCount(1)
      const saved = (await client.query(api.inventory.list, { householdId })).textiles[0]!
      expect(saved).toMatchObject({ status: 'clean', care: { washMethod: 'machine', maxTemperatureC: 30, dryMethod: 'tumble_dry', dryHeat: 'low', steamPermission: 'not_allowed' } })
    }
  } finally { await page.context().close() }
})

test('newly purchased clothes can be saved for washing or ready to wear', async ({ page }) => {
  await signUp(page, 'new-clothes-destination', 'Synthetic New')
  await createHousehold(page)
  await addClothes(page, { name: 'New tee to wash', firstWash: true, target: 'hamper' })
  await addClothes(page, { name: 'New tee ready', firstWash: true, target: 'closet' })
  const { client, householdId } = await convexAs(page)
  const { textiles } = await client.query(api.inventory.list, { householdId })
  expect(textiles.map(({ name, status, firstWash }) => ({ name, status, firstWash }))).toEqual([
    { name: 'New tee to wash', status: 'dirty', firstWash: true },
    { name: 'New tee ready', status: 'clean', firstWash: true },
  ])
})

test('origin checkboxes and inline optional label fit narrow doubled text', async ({ page }) => {
  test.skip(process.env.WASHCLOSET_E2E_BUILD === 'production', 'Local-only visual fixture')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/design-preview?screen=closet-add-color&textScale=2')
  const add = page.getByRole('dialog')
  await add.getByRole('button', { name: 'Next: where from', exact: true }).click()
  for (const name of ['Pre-owned (thrift, hand-me-down)', 'Thin or damaged']) {
    const checkbox = add.getByRole('checkbox', { name, exact: true })
    await checkbox.scrollIntoViewIfNeeded()
    await checkbox.check()
    const box = await checkbox.locator('xpath=ancestor::label').boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(320)
    expect(box!.height).toBeGreaterThanOrEqual(44)
  }
  await expect(add.getByText('(optional)', { exact: true }).locator('..')).toContainText('Smells of…')
  await expect(add.getByText('Optional.', { exact: true })).toHaveCount(0)
  await expect(add.getByRole('button', { name: 'Next: care label', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await add.getByRole('checkbox', { name: 'Thin or damaged', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('origin-320-large.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 1200, height: 900 })
  await expect(add.getByRole('checkbox', { name: 'Thin or damaged', exact: true })).toBeChecked()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
