import { expect, test } from '@playwright/test'

test.use({ trace: 'off' })
test.skip(process.env.WASHCLOSET_REVIEW_E2E !== '1', 'Run explicitly against an isolated synthetic review server.')
test.beforeEach(async ({ page }) => {
  await page.route('**/*', async (route) => {
    if (new URL(route.request().url()).origin === new URL(process.env.WASHCLOSET_E2E_BASE_URL!).origin) await route.continue()
    else await route.abort()
  })
})
test.afterEach(async ({ page }) => { await page.unrouteAll({ behavior: 'wait' }) })

test('agent replies remain beside a saved review and follow-ups use its original session', async ({ page }) => {
  const destination = { id: 'qa-claude', label: 'QA Claude', provider: 'claude', cwd: '/synthetic/project', host: 'QA host', sessionId: '12345678-1234-4234-8234-123456789abc' }
  await page.route('**/api/review/agents', (route) => route.fulfill({ json: [destination] }))
  await page.goto('/review?scenario=intake.towel.origin')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Add a towel' }).first().click()
  await page.getByRole('button', { name: 'Comment on selection' }).click()
  await page.getByLabel('What should change?').fill('QA: retain this agent conversation.')
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  await expect(page.getByText('Review saved with its target and frozen evidence.', { exact: true })).toBeVisible()
  const rows = await (await page.request.get('/api/review/feedback')).json()
  const saved = rows.findLast((row: { message: string }) => row.message === 'QA: retain this agent conversation.')
  let conversation = { ...saved, deliveries: [] as object[] }, sends = 0
  await page.route(`**/api/review/feedback/${saved.id}/send`, async (route) => {
    const input = route.request().postDataJSON()
    expect(input.destination).toBe(destination.id)
    sends++
    if (sends === 2) { expect(input.replyTo).toBe((conversation.deliveries[0] as { id: string }).id); expect(input.message).toBe('Show which branch check passed.') }
    conversation = { ...conversation, deliveries: [...conversation.deliveries, { id: input.requestId, destination, status: 'completed', acceptedAt: Date.now(), detail: 'Turn finished; verify before resolving.', ...(input.replyTo ? { replyTo: input.replyTo, message: input.message } : {}), result: sends === 1 ? 'Branch corrected. Verification evidence is available.' : 'The pre-owned branch check passed; device acceptance remains pending.' }] }
    await route.fulfill({ status: 202, json: conversation })
  })
  await page.route('**/api/review/feedback', (route) => route.fulfill({ json: [...rows.filter((row: { id: string }) => row.id !== saved.id), conversation] }))
  await page.getByLabel('Agent destination').selectOption(destination.id)
  await page.getByRole('button', { name: 'Send saved review', exact: true }).click()
  await expect(page.getByText('Branch corrected. Verification evidence is available.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Send follow-up' })).toBeDisabled()
  await page.getByLabel('Reply to agent').fill('Show which branch check passed.')
  await page.getByRole('button', { name: 'Send follow-up' }).click()
  await expect(page.getByText('The pre-owned branch check passed; device acceptance remains pending.', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByLabel('Show reviews').selectOption('all')
  await page.getByRole('button', { name: 'QA: retain this agent conversation.', exact: false }).last().click()
  await expect(page.getByText('You: Show which branch check passed.', { exact: true })).toBeVisible()
  expect(sends).toBe(2); expect(conversation.status).toBe('new')
})

test('saved review sends to an explicit destination and survives an uncertain response without duplicating work', async ({ page }) => {
  await page.route('**/api/review/agents', (route) => route.fulfill({ json: [{ id: 'qa-agent', label: 'QA Codex', provider: 'codex', cwd: '/synthetic/project', host: 'QA host', sessionId: '12345678-1234-4234-8234-123456789abc' }] }))
  await page.goto('/review?scenario=intake.towel.origin')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Add a towel' }).first().click()
  await page.getByRole('button', { name: 'Comment on selection' }).click()
  await page.getByLabel('What should change?').fill('QA: send this saved branch to the selected agent.')
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  const send = page.getByRole('button', { name: 'Send saved review', exact: true })
  await expect(send).toBeDisabled()
  await page.getByLabel('Agent destination').selectOption('qa-agent')
  await expect(page.getByText('/synthetic/project', { exact: false })).toBeVisible()
  await expect(send).toBeEnabled()
  const rows = await (await page.request.get('/api/review/feedback')).json()
  const saved = rows.findLast((row: { message: string }) => row.message === 'QA: send this saved branch to the selected agent.')
  let sends = 0
  const delivered = { ...saved, deliveries: [{ id: 'qa-send', status: 'unknown', detail: 'Harness acknowledgement lost. Inspect its session.', destination: { id: 'qa-agent', label: 'QA Codex', provider: 'codex', host: 'QA host', cwd: '/synthetic/project', sessionId: '12345678-1234-4234-8234-123456789abc' } }] }
  await page.route('**/api/review/feedback', (route) => route.fulfill({ json: [...rows.filter((row: { id: string }) => row.id !== saved.id), delivered] }))
  await page.route(`**/api/review/feedback/${saved.id}/send`, async (route) => {
    sends++
    expect(route.request().postDataJSON().destination).toBe('qa-agent')
    // The server retained the dispatch, but the client did not get its acknowledgement.
    await route.abort()
  })
  await send.click()
  await expect(page.getByText('unknown · QA Codex', { exact: true })).toBeVisible()
  await expect(send).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByLabel('Show reviews').selectOption('all')
  await page.getByRole('button', { name: 'QA: send this saved branch to the selected agent.', exact: false }).last().click()
  await expect(page.getByText('unknown · QA Codex', { exact: true })).toBeVisible()
  await expect(send).toBeDisabled()
  expect(sends).toBe(1)
  expect(delivered.status).toBe('new')
})

