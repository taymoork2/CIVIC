test('live element annotations freeze inputs and survive navigation and reload', async ({ page }) => {
  await page.goto('/review?scenario=intake.towel.fabric')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Live towel journey"]')
  // The live app takes input once its run is ready; a fill before then would be lost.
  await expect(frame.locator('#review-root')).toHaveAttribute('data-rehearsal-ready', 'true')
  await frame.getByLabel('Other material 1', { exact: true }).fill('QA retained cotton')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Comment on selection' }).click()
  // Freezing live evidence uploads the run recording first, so the draft form appears asynchronously.
  await expect(page.getByLabel('Annotation target')).toBeVisible()
  const option = await page.getByLabel('Annotation target').locator('option').evaluateAll((options) => options.find((option) => option.textContent === 'Search fibers or fabric details · input')?.getAttribute('value'))
  expect(option).toBeTruthy()
  await page.getByLabel('Annotation target').selectOption(option!)
  await page.getByLabel('What should change?').fill('QA: improve this input label.')
  await page.locator('.app-screen-outline').getByRole('button', { name: /Color/ }).click()
  await expect(page.getByLabel('What should change?')).toHaveValue('QA: improve this input label.')
  await page.reload()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.getByLabel('What should change?')).toHaveValue('QA: improve this input label.')
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Download agent brief' })).toBeVisible()
  const saved = (await (await page.request.get('/api/review/feedback')).json()).findLast((row: { message: string }) => row.message === 'QA: improve this input label.')
  expect(saved.target).toMatchObject({ kind: 'region', screen: 'fabric', selector: option })
  expect(saved.context.state.fields).toContainEqual({ label: 'Other material 1', value: 'QA retained cotton' })
  expect(saved.evidence.kind).toBe('live')
  await page.screenshot({ path: '/tmp/rehearsal-annotation-qa-20261010/annotation-ui.png' })
})
