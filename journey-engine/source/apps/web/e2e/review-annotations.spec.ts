  const point = await other.evaluate((element) => {
    const path = element as SVGPathElement, matrix = path.getScreenCTM()!
    const point = path.getPointAtLength(path.getTotalLength() * .25)
    return { x: matrix.a * point.x + matrix.c * point.y + matrix.e, y: matrix.b * point.x + matrix.d * point.y + matrix.f }
  })
  await page.mouse.click(point.x, point.y)
  await expect(page.getByText('When: Item is newly owned', { exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/rehearsal-annotation-qa-20261010/branch-ui.png' })
