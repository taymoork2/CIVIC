test('feedback pins a keyboard target, retains a failed send, captures state and survives reload', async ({ page }, testInfo) => {
  await page.goto('/review?legacy=1&scenario=intake.pack.details&theme=dark&scale=2&width=320')
  const frame = page.frameLocator('iframe')
  await expect(frame.getByLabel('Name', { exact: true })).toBeVisible()
  await frame.getByLabel('Name', { exact: true }).fill('Synthetic review draft')
  await page.getByRole('button', { name: 'Pin feedback', exact: true }).click()
  await page.getByLabel('Keyboard feedback target').selectOption({ label: 'Name' })
  const message = `Keyboard review ${testInfo.project.name} ${Date.now()}`
  await page.getByLabel(/^Comment on/).fill(message)
  await page.route('**/api/review/feedback', async (route) => { if (route.request().method() === 'POST') await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Simulated feedback failure' }) }); else await route.continue() })
  await page.getByRole('button', { name: 'Save feedback', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Simulated feedback failure')
  await expect(page.getByLabel(/^Comment on/)).toHaveValue(message)
  await page.unroute('**/api/review/feedback')
  await page.getByRole('button', { name: 'Save feedback', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Feedback saved with screenshot and state')
  const rows = await (await page.request.get('/api/review/feedback')).json()
  const note = rows.find((row: { message: string }) => row.message === message)
  expect(note.anchor.label).toBe('Name')
  expect(note.context.state.fields.some((field: { value: string }) => field.value === 'Synthetic review draft')).toBe(true)
  expect(note.context.viewport.width).toBe(320)
  expect(note.context.state.dialogs).not.toHaveLength(0)
  expect((await page.request.get(note.screenshot)).headers()['content-type']).toBe('image/png')
  await page.reload()
  await expect(page.getByText(message, { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 393, height: 852 })
  await page.locator('iframe').screenshot({ path: testInfo.outputPath('review-phone-dark-enlarged.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

