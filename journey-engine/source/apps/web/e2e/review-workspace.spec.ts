// The towel intake saves through the app's own runtime since v7; review-towel-runtime.spec.ts covers it.
for (const fixture of ['pack']) test(`${fixture} intake keeps answers through Back, saves, and connects to the item record`, async ({ page }) => {
  await page.goto(`/review?legacy=1&scenario=intake.${fixture}.type`)
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: /^Next:/ }).click()
  await frame.getByRole('button', { name: 'Next: details', exact: true }).click()
  await expect(frame.getByLabel('Name', { exact: true })).toBeVisible()
  await frame.getByLabel('Name', { exact: true }).fill(`Reviewed ${fixture}`)
  await frame.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await frame.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(frame.getByLabel('Name', { exact: true })).toHaveValue(`Reviewed ${fixture}`)
  for (let count = 0; count < 15; count++) {
    const save = frame.getByRole('button', { name: 'Save item', exact: true })
    if (await save.count()) break
    await frame.getByRole('button', { name: /^Next/ }).click()
  }
  await frame.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(frame.getByRole('heading', { name: 'Saved', exact: true })).toBeVisible()
  await page.getByRole('button', { name: fixture === 'pack' ? 'Multicolor pack · saved item' : 'Cotton/polyester towel · saved item', exact: true }).click()
  await page.getByRole('button', { name: 'Restart preview', exact: true }).click()
  await expect(frame.getByRole('heading', { name: `Reviewed ${fixture}`, exact: true })).toBeVisible()
  const data = await page.locator('iframe').evaluate((iframe: HTMLIFrameElement) => iframe.contentWindow!.reviewPreview!.data())
  expect(data.saved[fixture]).toHaveLength(fixture === 'pack' ? 6 : 1)
  if (fixture === 'towel') expect(data.textiles.find((piece) => data.saved.towel!.includes(piece.textileId))!.care!.material).toBe('cotton 80%, polyester 20%')
  await frame.getByRole('button', { name: 'Edit item details', exact: true }).click()
  await frame.getByLabel('Name', { exact: true }).fill(`Edited ${fixture}`)
  await frame.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(frame.getByRole('heading', { name: `Edited ${fixture}`, exact: true })).toBeVisible()
})

