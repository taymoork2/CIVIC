import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, signUp } from './flows'

test('cold with like colors survives intake, care edits and reload', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'like-colors', 'Casey Colors')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  let sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'T-shirt', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet.getByLabel('Name', { exact: true }).fill('Like colors tee')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Blue', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet.getByRole('button', { name: 'What does “Could the dye run?” mean?', exact: true }).click()
  await expect(page.getByText(/Past washes don’t guarantee/)).toBeVisible()
  await expect(sheet.getByRole('radio', { name: 'Not sure', exact: true })).toBeChecked()
  await page.keyboard.press('Escape')
  await sheet.getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  const like = () => sheet.getByRole('checkbox', { name: 'Wash with like colors', exact: true })
  await expect(like()).not.toBeChecked()
  await sheet.getByRole('button', { name: 'Cold', exact: true }).click()
  await sheet.getByText('Wash with like colors', { exact: true }).click()
  await expect(like()).toBeChecked()
  await like().focus(); await page.keyboard.press('Space'); await expect(like()).not.toBeChecked()
  await page.keyboard.press('Space'); await expect(like()).toBeChecked()
  await sheet.getByRole('button', { name: 'Warm', exact: true }).click()
  await expect(like()).toBeChecked()
  await sheet.getByRole('button', { name: 'Cold', exact: true }).click()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await like().scrollIntoViewIfNeeded()
    await page.screenshot({ path: test.info().outputPath(`cold-like-colors-${theme}.png`), animations: 'disabled' })
  }
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(like()).toBeChecked()
  await sheet.getByRole('button', { name: 'Cold', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByRole('radio', { name: /Tag doesn.t say/ }).click()
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Low heat', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const care = async () => (await client.query(api.inventory.list, { householdId })).textiles[0]!.care!
  expect(await care()).toMatchObject({ maxTemperatureC: 30, restrictions: ['Wash with like colors'] })
  await page.getByRole('button', { name: /^Like colors tee,/ }).click()
  await page.getByRole('tab', { name: 'Care', exact: true }).click()
  sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: /^Washing:.*with like colors.*Edit/ }).click()
  sheet = page.getByRole('dialog')
  await expect(like()).toBeChecked()
  await sheet.getByRole('button', { name: 'Warm', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  expect(await care()).toMatchObject({ maxTemperatureC: 40, restrictions: ['Wash with like colors'] })
  await page.reload()
  await expect(page.getByRole('dialog').getByRole('heading', { name: 'Like colors tee', exact: true })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: /^Washing:.*with like colors.*Edit/ }).click()
  sheet = page.getByRole('dialog')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  await like().uncheck()
  await sheet.getByRole('button', { name: 'Cold', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  expect(await care()).toMatchObject({ maxTemperatureC: 30, restrictions: [] })
})

