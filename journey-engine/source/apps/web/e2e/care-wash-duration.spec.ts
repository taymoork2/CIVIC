import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, answerCards, convexAs, createHousehold, finishSession, freshPage, openHousehold, signUp, openAdvanced } from './flows'

// Collected here; root runs against its isolated integration runtime. All facts are synthetic.
test('documented wash-phase limits require checked label/program evidence through preparation and immutable history', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await signUp(page, 'wash-phase', 'Robin Phase')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
    await addClothes(page, { name: 'Synthetic wash-phase tee', firstWash: false })
    const { client, householdId } = await convexAs(page)
    const inventory = await client.query(api.inventory.list, { householdId })
    const textileId = inventory.textiles.find((entry) => entry.name === 'Synthetic wash-phase tee')!.textileId
    const machineId = inventory.machines.find((entry) => entry.name === 'Laundry room washer')!.machineId
    await client.mutation(api.inventory.saveRule, { supplyId: inventory.supplies[0]!.supplyId, dose: { amount: 30, unit: 'ml' }, stage: 'wash', placement: 'detergent_compartment', timing: 'before starting', provenance: { source: 'Synthetic exact pack directions', confidence: 'verified' } })
    const planned = async () => {
      const { planId } = await client.mutation(api.plans.recompute, { householdId, selectedTextileIds: [textileId], clientInputHash: 'wash-phase-browser' })
      return (await client.query(api.plans.get, { planId }))!
    }

    await page.getByRole('button', { name: /^Synthetic wash-phase tee(?:,|\s|$)/ }).click()
    await page.getByRole('tab', { name: 'Care', exact: true }).click()
    await openAdvanced(page, 'Care')
    await page.getByRole('button', { name: 'Label notes', exact: true }).click()
    const label = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Label notes', exact: true }) })
    const wording = 'Wash phase at most 10 minutes; no spin; wash with like colors'
    await label.getByLabel('Where you read it', { exact: true }).fill('Synthetic sewn label, both sides')
    await label.getByLabel('Label section', { exact: true }).selectOption('washing')
    await label.getByLabel('Additional wash settings or product requirements', { exact: true }).fill(wording)
    await label.getByLabel('Maximum soaking time on this label (minutes)', { exact: true }).fill('2')
    const line = label.locator('fieldset').filter({ has: page.locator('legend').filter({ hasText: wording }) }).last()
    await line.getByLabel('Add a supported condition', { exact: true }).selectOption('maximum_wash_minutes')
    await expect(label.getByRole('button', { name: 'Save label', exact: true })).toBeDisabled()
    await line.getByLabel('Maximum washing-phase duration (minutes)', { exact: true }).fill('10')
    for (const kind of ['no_spin', 'wash_with_like_colors']) await line.getByLabel('Add a supported condition', { exact: true }).selectOption(kind)
    await label.getByRole('button', { name: 'Save label', exact: true }).click()
    await expect(label).toHaveCount(0)
    expect((await planned()).result.loads, 'Unacknowledged whole-line interpretation stays unresolved').toHaveLength(0)
    await openAdvanced(page, 'Care')
    await page.getByRole('button', { name: 'Label notes', exact: true }).click()
    await label.getByLabel('Label section', { exact: true }).selectOption('washing')
    const checkedLine = label.locator('fieldset').filter({ has: page.locator('legend').filter({ hasText: wording }) }).last()
    const acknowledgment = checkedLine.getByRole('checkbox', { name: 'I’ve checked that these conditions cover this entire source line', exact: true })
    await acknowledgment.check()
    await checkedLine.getByLabel('Maximum washing-phase duration (minutes)', { exact: true }).fill('9')
    await expect(acknowledgment).not.toBeChecked()
    await checkedLine.getByLabel('Maximum washing-phase duration (minutes)', { exact: true }).fill('10')
    await acknowledgment.check()
    await label.getByRole('button', { name: 'Save label', exact: true }).click()
    await expect(label).toHaveCount(0)
    await page.getByRole('dialog').last().getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Edit item details', exact: true })).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect((await planned()).result.loads, 'A whole-cycle estimate cannot supply washing-phase evidence').toHaveLength(0)

    // Saving an existing appliance returns to its record; Close then dismisses the drawer.
    const savedAndClosed = async (sheet: import('@playwright/test').Locator) => {
      await expect(sheet.getByRole('button', { name: 'Edit settings', exact: true })).toBeVisible()
      await sheet.getByRole('button', { name: 'Close', exact: true }).first().click()
      await expect(sheet).toHaveCount(0)
    }
    const editProgram = async () => {
      await openHousehold(page, 'Machines')
      await page.getByRole('button', { name: /^Laundry room washer/ }).click()
      const sheet = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Laundry room washer', exact: true }) })
      await sheet.getByRole('button', { name: 'Edit settings', exact: true }).click()
      await sheet.getByRole('tab', { name: 'Programs', exact: true }).click()
      return sheet
    }
    let machine = await editProgram()
    let normal = machine.getByRole('group', { name: 'Normal care', exact: true })
    await normal.getByLabel('Checked program and selected options', { exact: true }).fill('Synthetic Normal / Short Wash / No Spin')
    await normal.getByLabel('Where these settings were checked', { exact: true }).fill('Synthetic exact model guide, phase table for selected options')
    await normal.getByLabel('Highest spin speed in any phase (rpm; 0 means none)', { exact: true }).fill('0')
    await expect(normal.getByLabel('Documented washing-phase duration (minutes)', { exact: true })).toHaveValue('')
    await machine.getByRole('button', { name: 'Save washer', exact: true }).click()
    await savedAndClosed(machine)
    expect((await planned()).result.loads).toHaveLength(0)
    machine = await editProgram()
    normal = machine.getByRole('group', { name: 'Normal care', exact: true })
    await normal.getByLabel('Documented washing-phase duration (minutes)', { exact: true }).fill('11')
    await machine.getByRole('button', { name: 'Save washer', exact: true }).click()
    await savedAndClosed(machine)
    expect((await planned()).result.loads, 'An overlong documented phase cannot meet the maximum').toHaveLength(0)
    machine = await editProgram()
    normal = machine.getByRole('group', { name: 'Normal care', exact: true })
    const phase = normal.getByLabel('Documented washing-phase duration (minutes)', { exact: true })
    await phase.fill('10')
    await normal.getByLabel('Checked program and selected options', { exact: true }).fill('Synthetic Normal / Short Wash / No Spin / Checked')
    await expect(phase).toHaveValue('')
    await phase.fill('10')
    await normal.getByLabel('Where these settings were checked', { exact: true }).fill('Synthetic revised exact model guide, phase table for selected options')
    await expect(phase).toHaveValue('')
    await phase.fill('10')
    await normal.getByLabel('Highest spin speed in any phase (rpm; 0 means none)', { exact: true }).fill('400')
    await expect(phase).toHaveValue('')
    await normal.getByLabel('Highest spin speed in any phase (rpm; 0 means none)', { exact: true }).fill('0')
    await phase.fill('0')
    await expect(machine.getByRole('button', { name: 'Save washer', exact: true })).toBeDisabled()
    await expect(machine.getByText('Record the checked program and source, or remove its incomplete settings.', { exact: true })).toBeVisible()
    expect((await client.query(api.inventory.list, { householdId })).machines.find((entry) => entry.machineId === machineId)!.washProcesses!.normal!.washMinutes).toBe(11)
    await phase.fill('10')
    await expect(normal.getByText(/Actual phase time isn’t measured/)).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('checked-washing-phase-phone.png') })
    await machine.getByRole('button', { name: 'Save washer', exact: true }).click()
    await savedAndClosed(machine)
    expect((await planned()).result.status).toBe('ready')
    await expect(page.getByRole('button', { name: /^Laundry room washer/ })).toBeVisible()
    await page.reload()
    const saved = await client.query(api.inventory.list, { householdId })
    const checked = saved.machines.find((entry) => entry.machineId === machineId)!.washProcesses!.normal!
    expect(checked.washMinutes).toBe(10)

    await page.getByRole('navigation').getByRole('link', { name: /^Laundry/ }).click()
    await page.getByRole('button', { name: 'Load options' }).click()
    await page.getByRole('button', { name: 'Sort again', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Whites load', exact: true })).toBeVisible()
    await answerCards(page)
    await page.getByRole('button', { name: 'I’m at the laundry room', exact: true }).click()
    await page.getByRole('button', { name: /^Confirm recipe for / }).click()
    await page.getByRole('button', { name: 'See what goes in', exact: true }).click()
    await page.getByRole('button', { name: 'Start preparation', exact: true }).click()
    await expect(page.locator('section.machine-step')).toBeVisible()
    await finishSession(page)
    await client.mutation(api.inventory.updateMachine, { machineId, washProcesses: { normal: { ...checked, washMinutes: 20, source: 'Synthetic later guide' } } })
    const record = (await client.query(api.sessions.washRecordsForTextile, { textileId }))[0]!
    expect(record.activityContext?.washer?.washProcesses?.normal).toEqual(checked)
    expect(record.activityContext?.washer?.cycleProfile?.cycles.normal?.durationMinutes).toBe(40)
    expect(record.activityContext?.garment?.care?.instructions).toMatchObject({ washing: [wording], maximumSoakMinutes: 2, washingRequirements: [{ wording, checked: true, requirements: [{ kind: 'maximum_wash_minutes', value: 10 }, { kind: 'no_spin' }, { kind: 'wash_with_like_colors' }] }] })
  } finally {
    await page.context().close()
  }
})
