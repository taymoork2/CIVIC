import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, signUp } from './flows'

test('wool intake protects care choices, exposes label extras and keeps Details distinct', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'wool-care', 'Synthetic Wool')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = () => page.getByRole('dialog').last()
  await sheet().getByRole('button', { name: 'Sweater', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet().getByLabel('Name', { exact: true }).fill('Checked wool sweater')
  await sheet().getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet().getByRole('checkbox', { name: 'Wool', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet().getByRole('radio', { name: 'White', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet().getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: care label', exact: true }).click()
  for (const name of ['Any temperature', 'Cold', 'Warm', 'Hot', 'Cold, permanent press']) await expect(sheet().getByRole('button', { name, exact: true })).toHaveCount(0)
  await sheet().getByRole('button', { name: 'Cold, delicate', exact: true }).click()
  for (let back = 0; back < 4; back++) await sheet().getByRole('button', { name: 'Back', exact: true }).click()
  await sheet().getByRole('checkbox', { name: 'Cotton', exact: true }).click()
  await sheet().getByRole('checkbox', { name: 'Cotton', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: care label', exact: true }).click()
  await expect(sheet().getByRole('button', { name: 'Tag doesn’t say', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(sheet().getByRole('button', { name: 'Cold, delicate', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await sheet().getByRole('button', { name: 'Cold, delicate', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  for (const name of ['Any bleach Empty triangle', 'Non-chlorine bleach only Two lines inside']) await expect(sheet().getByRole('radio', { name, exact: true })).toHaveCount(0)
  await sheet().getByRole('radio', { name: /^Do not bleach/ }).click()
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  for (const name of ['Any heat', 'Medium heat', 'High heat']) await expect(sheet().getByRole('radio', { name, exact: true })).toHaveCount(0)
  await sheet().getByRole('radio', { name: 'Low heat', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  await expect(sheet().getByRole('heading', { name: 'Any stains?', exact: true })).toBeVisible()
  await sheet().getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: review', exact: true }).click()
  await sheet().getByRole('button', { name: 'Edit more on the label', exact: true }).click()
  await expect(sheet().getByRole('heading', { name: 'More on the label', exact: true })).toBeVisible()
  await expect(sheet().getByRole('button', { name: 'Iron, high heat', exact: true })).toHaveCount(0)
  await sheet().getByRole('button', { name: 'Iron, medium heat', exact: true }).click()
  await sheet().getByRole('button', { name: 'Do not steam', exact: true }).click()
  await expect(sheet().locator('[data-symbol="do_not_steam"]')).toBeVisible()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`label-extras-${theme}.png`), animations: 'disabled' })
  }
  await sheet().getByRole('button', { name: 'Next: review', exact: true }).click()
  await expect(sheet().getByRole('button', { name: 'Edit more on the label', exact: true })).toContainText('Do not steam')
  await sheet().getByRole('button', { name: 'Save item', exact: true }).click()
  await sheet().getByRole('button', { name: /^Wash & dry preferences/ }).click()
  await expect(sheet().getByRole('heading', { name: 'Wash & dry preferences', exact: true })).toBeVisible()
  await expect(sheet().getByText('Checked wool sweater', { exact: true })).toBeVisible()
  await sheet().getByRole('tab', { name: 'Dry', exact: true }).click()
  await sheet().getByRole('checkbox', { name: 'Drying settings', exact: true }).check()
  await expect(sheet().getByLabel('Drying method', { exact: true })).toHaveValue('tumble')
  await expect(sheet().getByLabel('Tumble heat limit', { exact: true })).toHaveValue('low')
  await expect(sheet().getByLabel('Tumble heat limit').getByRole('option', { name: 'Medium heat', exact: true })).toBeDisabled()
  await sheet().getByRole('button', { name: 'Close', exact: true }).click()
  await sheet().getByRole('button', { name: 'Keep editing', exact: true }).click()
  await sheet().getByRole('button', { name: 'Close', exact: true }).click()
  await sheet().getByRole('button', { name: 'Discard', exact: true }).click()
  await sheet().getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const garment = (await client.query(api.inventory.list, { householdId })).textiles[0]!
  expect(garment.care).toMatchObject({ status: 'confirmed', material: 'wool', cycle: 'delicate', dryHeat: 'low', ironHeat: 'medium', steamPermission: 'not_allowed' })
  await page.getByRole('button', { name: /^Checked wool sweater,/ }).click()
  await expect(sheet().getByRole('button', { name: 'Advanced', exact: true })).toHaveCount(0)
  await expect(sheet().getByRole('button', { name: /^Fabric/ })).toHaveCount(0)
  await sheet().getByRole('tab', { name: 'Details', exact: true }).click()
  await expect(sheet().getByRole('button', { name: /^Fabric.*Wool/ })).toBeVisible()
  await expect(sheet().getByRole('button', { name: /^Dye/ })).toHaveCount(0)
  await expect(sheet().getByRole('list', { name: 'Garment details', exact: true }).getByRole('button', { name: 'Manufacturer reference', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('dialog').getByRole('tab', { name: 'Details', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: /^Fabric.*Wool/ })).toBeVisible()
})
