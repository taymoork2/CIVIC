import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, convexAs, createHousehold, finishSession, freshPage, planAndStart, signUp, openAdvanced } from './flows'

test('additional label wording survives reload and follows a piece through preparation, drying and history', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await signUp(page, 'care-instructions', 'Cameron Care')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
    await addClothes(page, { name: 'Label wording tee' })
    await page.getByRole('button', { name: /^Label wording tee,/ }).click()
    await page.getByRole('tab', { name: 'Care', exact: true }).click()
    await openAdvanced(page, 'Care')
    await page.getByRole('button', { name: 'Label notes', exact: true }).click()
    const label = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Label notes', exact: true }) })
    await label.getByLabel('Where you read it', { exact: true }).fill('Synthetic sewn label, checked front and reverse')
    await label.getByLabel('Symbol system or edition, if known', { exact: true }).fill('Recorded test system')
    await label.getByLabel('Before washing', { exact: true }).fill('Turn this tee inside out before washing')
    await label.getByLabel('Label section', { exact: true }).selectOption('beforeDrying')
    await label.getByLabel('Before drying', { exact: true }).fill('Reshape the sleeves while damp')
    await label.getByLabel('Label section', { exact: true }).selectOption('afterDrying')
    await label.getByLabel('When checking or removing it', { exact: true }).fill('Remove promptly and smooth before folding')
    await label.getByLabel('Label section', { exact: true }).selectOption('washing')
    await label.getByLabel('Maximum soaking time on this label (minutes)', { exact: true }).fill('2')
    await label.getByLabel('Label section', { exact: true }).selectOption('preparation')
    await expect(label.getByLabel('Before washing', { exact: true })).toHaveValue('Turn this tee inside out before washing')
    await expect(label.getByRole('textbox')).toHaveCount(3)
    for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['narrow-dark-large', 320, 2, 'dark']] as const) {
      await page.setViewportSize({ width, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
      await label.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
      expect(await label.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
      const bounds = (await label.boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(-1)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1)
      expect(bounds.y).toBeGreaterThanOrEqual(-1)
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(901)
      await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath(`label-${name}.png`) })
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await page.emulateMedia({ colorScheme: 'light' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await label.getByRole('button', { name: 'Save label', exact: true }).click()
    await page.reload()
    await page.getByRole('tab', { name: 'Care', exact: true }).click()
    await expect(page.getByText('Turn this tee inside out before washing', { exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await planAndStart(page, 1)
    await expect(page.getByText('Turn this tee inside out before washing', { exact: true })).toBeVisible()
    await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('label-preparation.png') })
    await finishSession(page)
    const { client, householdId } = await convexAs(page)
    const { textiles } = await client.query(api.inventory.list, { householdId })
    const records = await client.query(api.sessions.washRecordsForTextile, { textileId: textiles[0]!.textileId })
    expect(records[0]?.drying).toMatchObject({ outcome: 'tumble_dried', instructions: { source: 'Synthetic sewn label, checked front and reverse', beforeDrying: ['Reshape the sleeves while damp'], afterDrying: ['Remove promptly and smooth before folding'] } })
  } finally {
    await page.context().close()
  }
})
