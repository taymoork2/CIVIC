import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, freshPage, inviteNewPerson, joinWithCode, openHousehold, signUp } from './flows'

test('standalone invitations survive reload and cancel independently of managed clothing profiles', async ({ browser }) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 393, height: 852 })
    await signUp(page, 'pending-management', 'Synthetic Owner')
    await createHousehold(page)
    const code = await inviteNewPerson(page, 'Pending Sam')
    const { client, householdId } = await convexAs(page)
    expect((await client.query(api.inventory.list, { householdId })).wearers.some((person) => person.name === 'Pending Sam')).toBe(false)
    await page.getByRole('button', { name: 'Manage invite for Pending Sam', exact: true }).click()
    let drawer = page.getByRole('dialog')
    await expect(drawer.getByRole('button', { name: /^Copy code/ })).toContainText(code)
    await drawer.getByRole('button', { name: 'Close', exact: true }).click()
    await page.reload()
    await openHousehold(page, 'People')
    await expect(page.getByRole('heading', { name: 'Pending invitations', exact: true })).toBeVisible()
    const sections = await page.getByRole('heading', { level: 2 }).allTextContents()
    expect(sections).not.toContain('Whose clothes')
    expect(sections.indexOf('Household members')).toBeLessThan(sections.indexOf('Pending invitations'))
    await page.getByRole('button', { name: 'Manage invite for Pending Sam', exact: true }).click()
    drawer = page.getByRole('dialog')
    await expect(drawer.getByRole('heading', { name: 'Invite Pending Sam', exact: true })).toBeVisible()
    await expect(drawer.getByRole('button', { name: 'Make invite link', exact: true })).toBeVisible()
    await expect(drawer.getByRole('button', { name: /^Copy code/ })).toHaveCount(0)
    const cancelButton = drawer.getByRole('button', { name: 'Cancel invite', exact: true })
    await expect(drawer.getByRole('button', { name: 'Remove person', exact: true })).toHaveCount(0)
    for (const width of [393, 320]) for (const textScale of ['100%', '200%']) {
      await page.setViewportSize({ width, height: 852 })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = scale }, textScale)
      const cancelBox = (await cancelButton.boundingBox())!
      expect(cancelBox.height).toBeGreaterThanOrEqual(44)
      expect(await drawer.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    }
    await page.evaluate(() => { document.documentElement.style.fontSize = '' })
    await page.setViewportSize({ width: 393, height: 852 })
    for (const theme of ['light', 'dark'] as const) {
      await page.emulateMedia({ colorScheme: theme })
      await page.screenshot({ path: test.info().outputPath(`pending-393-${theme}.png`), animations: 'disabled' })
    }
    await page.setViewportSize({ width: 320, height: 800 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath('pending-320.png'), animations: 'disabled' })
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await expect(drawer.getByRole('heading', { name: 'Cancel this invite?', exact: true })).toBeVisible()
    await drawer.getByRole('button', { name: 'Keep invite', exact: true }).click()
    expect(await client.query(api.households.invitePreview, { code })).toMatchObject({ status: 'valid' })
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    expect(await client.query(api.households.invitePreview, { code })).toEqual({ status: 'unknown' })
    await expect(page.getByRole('button', { name: 'Manage invite for Pending Sam', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: /^Open Pending Sam\./ })).toHaveCount(0)

    // Clothing profiles are intentional and work without their own account.
    await page.getByRole('button', { name: /^Add clothing profile\b/ }).click()
    await drawer.getByRole('tab', { name: 'Person', exact: true }).click()
    await drawer.getByLabel('Name', { exact: true }).fill('Managed Sam')
    await drawer.getByRole('button', { name: 'Save person', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    const sam = (await client.query(api.inventory.list, { householdId })).wearers.find((person) => person.name === 'Managed Sam')!
    expect(sam).toMatchObject({ kind: 'child', principalKey: null })
    const [shirt] = await client.mutation(api.inventory.createTextiles, { householdId, wearerId: sam.wearerId, name: 'Synthetic preserved shirt', quantity: 1 })
    await expect(page.getByRole('button', { name: 'Link account', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: /^Open Managed Sam\./ }).click()
    await page.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    await drawer.getByRole('tab', { name: 'Person', exact: true }).click()
    await drawer.getByLabel('Name', { exact: true }).fill('Unsaved name')
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await expect(drawer.getByRole('button', { name: 'Link account', exact: true })).toBeDisabled()
    await expect(drawer.getByText('Save your changes to link an account.', { exact: true })).toBeVisible()
    await drawer.getByRole('tab', { name: 'Person', exact: true }).click()
    await drawer.getByLabel('Name', { exact: true }).fill('Managed Sam')
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await drawer.getByRole('button', { name: 'Link account', exact: true }).click()
    await drawer.getByRole('button', { name: 'Make invite link', exact: true }).click()
    await expect(drawer.getByRole('button', { name: 'Share invite link', exact: true })).toBeVisible()
    await drawer.getByRole('button', { name: 'Close', exact: true }).click()
    // Editing a profile has the same destination with or without a pending link.
    await page.getByRole('button', { name: /^Open Managed Sam\./ }).click()
    await page.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    await expect(drawer.getByLabel('Name', { exact: true })).toHaveValue('Managed Sam')
    await expect(drawer.getByRole('button', { name: 'Link account', exact: true })).toHaveCount(0)
    await drawer.getByRole('button', { name: 'Close', exact: true }).click()
    await drawer.getByRole('button', { name: 'Done', exact: true }).click()
    await page.getByRole('button', { name: 'Manage invite for Managed Sam', exact: true }).click()
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    expect((await client.query(api.inventory.list, { householdId })).textiles.find((piece) => piece.textileId === shirt)?.wearerId).toBe(sam.wearerId)
    await page.getByRole('button', { name: /^Open Managed Sam\./ }).click()
    await page.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await expect(drawer.getByRole('button', { name: 'Link account', exact: true })).toBeEnabled()
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await drawer.getByRole('button', { name: 'Remove person', exact: true }).click()
    await drawer.getByRole('button', { name: 'Keep person', exact: true }).click()
    await expect(drawer.getByLabel('Name', { exact: true })).toHaveValue('Managed Sam')
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await drawer.getByRole('button', { name: 'Remove person', exact: true }).click()
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await drawer.getByRole('button', { name: 'Remove person', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    const saved = await client.query(api.inventory.list, { householdId })
    expect(saved.wearers.some((person) => person.wearerId === sam.wearerId)).toBe(false)
    expect(saved.textiles.find((piece) => piece.textileId === shirt)).toMatchObject({ name: 'Synthetic preserved shirt', wearerId: null })

    const removeCode = await inviteNewPerson(page, 'Remove Invite')
    await page.reload()
    await openHousehold(page, 'People')
    await page.getByRole('button', { name: 'Manage invite for Remove Invite', exact: true }).click()
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await drawer.getByRole('button', { name: 'Cancel invite', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    expect(await client.query(api.households.invitePreview, { code: removeCode })).toEqual({ status: 'unknown' })
    await expect(page.getByRole('button', { name: 'Manage invite for Remove Invite', exact: true })).toHaveCount(0)
  } finally { await page.context().close() }
})

test('accepted members use Remove access and keep their clothing profile', async ({ browser }) => {
  const owner = await freshPage(browser), member = await freshPage(browser)
  try {
    await owner.setViewportSize({ width: 393, height: 852 })
    await signUp(owner, 'accepted-management-owner', 'Synthetic Owner')
    await createHousehold(owner)
    const { client, householdId } = await convexAs(owner)
    const wearerId = await client.mutation(api.inventory.createWearer, { householdId, name: 'Joined Sam', kind: 'child' })
    const [shirt] = await client.mutation(api.inventory.createTextiles, { householdId, wearerId, name: 'Sam retained shirt', quantity: 1 })
    await openHousehold(owner, 'People')
    await owner.getByRole('button', { name: /^Open Joined Sam\./ }).click()
    await owner.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    if (await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).count()) await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).click()
    await owner.getByRole('dialog').getByRole('button', { name: 'Link account', exact: true }).click()
    const link = owner.getByRole('dialog')
    await link.getByRole('button', { name: 'Make invite link', exact: true }).click()
    const code = (await link.getByRole('button', { name: /^Copy code/ }).innerText()).match(/[A-Z2-9]{4}(?:-[A-Z2-9]{4}){3}/)![0]
    await link.getByRole('button', { name: 'Close', exact: true }).click()
    await signUp(member, 'accepted-management-member', 'Synthetic Member')
    await joinWithCode(member, code)
    await openHousehold(member, 'People')
    await member.getByRole('button', { name: /^Open Joined Sam\./ }).click()
    await member.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    await expect(member.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true })).toHaveCount(0)
    if (await member.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).count()) await member.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).click()
    await member.getByRole('dialog').getByRole('button', { name: 'Leave household', exact: true }).click()
    await expect(member.getByRole('dialog').getByRole('heading', { name: 'Leave this household?', exact: true })).toBeVisible()
    await member.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(owner.getByRole('button', { name: 'Manage invite for Joined Sam', exact: true })).toHaveCount(0)
    await owner.getByRole('button', { name: /^Open Joined Sam\./ }).click()
    await owner.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    await expect(owner.getByRole('dialog').getByRole('button', { name: 'Remove person', exact: true })).toHaveCount(0)
    await expect(owner.getByRole('button', { name: 'Remove', exact: true })).toHaveCount(0)
    await owner.getByRole('dialog').getByRole('tab', { name: 'Person', exact: true }).click()
    await owner.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Unsaved Sam')
    if (await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).count()) await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).click()
    await expect(owner.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true })).toBeDisabled()
    await owner.getByRole('dialog').getByRole('tab', { name: 'Person', exact: true }).click()
    await owner.getByRole('dialog').getByLabel('Name', { exact: true }).fill('Joined Sam')
    if (await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).count()) await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).click()
    await owner.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true }).click()
    const drawer = owner.getByRole('dialog')
    await expect(drawer.getByRole('button', { name: 'Remove access', exact: true })).toBeVisible()
    await drawer.getByRole('button', { name: 'Cancel', exact: true }).click()
    await owner.getByRole('button', { name: /^Open Joined Sam\./ }).click()
    await owner.getByRole('button', { name: 'Edit clothing profile', exact: true }).click()
    if (await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).count()) await owner.getByRole('dialog').getByRole('tab', { name: 'Access', exact: true }).click()
    await owner.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true }).click()
    if (await drawer.getByRole('tab', { name: 'Access', exact: true }).count()) await drawer.getByRole('tab', { name: 'Access', exact: true }).click()
    await drawer.getByRole('button', { name: 'Remove access', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    expect(await client.query(api.households.members, { householdId })).toHaveLength(1)
    const kept = await client.query(api.inventory.list, { householdId })
    expect(kept.wearers).toContainEqual(expect.objectContaining({ wearerId, name: 'Joined Sam', principalKey: null }))
    expect(kept.textiles).toContainEqual(expect.objectContaining({ textileId: shirt, wearerId }))
    await expect(owner.getByRole('button', { name: /^Open Joined Sam\./ })).toBeVisible()
  } finally { await owner.context().close(); await member.context().close() }
})
