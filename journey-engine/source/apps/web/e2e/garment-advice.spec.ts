import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, convexAs, createHousehold, finishSession, freshPage, planAndStart, signUp, openAdvanced } from './flows'

test('help icons stay beside labels without shrinking targets or changing privacy', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 393, height: 900 })
  await signUp(page, 'help-spacing', 'Synthetic Help')
  await createHousehold(page)
  const { client, householdId } = await convexAs(page)
  await client.mutation(api.inventory.createTextiles, { householdId, name: 'Help tee', kind: 'shirt', quantity: 1, status: 'clean' })
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: /^Help tee,/ }).click()
  await page.getByRole('tab', { name: 'Details', exact: true }).click()
  await openAdvanced(page, 'More')
  const privacy = page.getByRole('switch', { name: 'Private', exact: true })
  const help = page.getByRole('button', { name: 'What does “Private” mean?', exact: true })
  for (const [width, scale, theme] of [[393, 1, 'light'], [393, 1, 'dark'], [320, 2, 'dark']] as const) {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
    await page.evaluate(scale => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
    const box = (await help.boundingBox())!
    expect(box.width).toBeGreaterThanOrEqual(44)
    expect(box.height).toBeGreaterThanOrEqual(44)
    const gap = await help.evaluate(button => {
      const range = document.createRange()
      range.selectNodeContents(button.parentElement!.firstChild!)
      return button.querySelector('svg')!.getBoundingClientRect().left - range.getBoundingClientRect().right
    })
    expect(gap).toBeGreaterThanOrEqual(0)
    expect(gap).toBeLessThanOrEqual(12 * scale)
    // ponytail: long enlarged garment headers/footers can block pointer access; keyboard access is checked separately.
    if (scale === 2) { await help.focus(); await page.keyboard.press('Enter') }
    else await help.click()
    await expect(help).toHaveAttribute('aria-expanded', 'true')
    await expect(privacy).not.toBeChecked()
    await page.keyboard.press('Escape')
    await expect(help).toBeFocused()
    await page.screenshot({ path: testInfo.outputPath(`private-help-${width}-${scale}-${theme}.png`) })
  }
  await page.setViewportSize({ width: 393, height: 900 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
  await privacy.click()
  await page.getByRole('dialog').last().getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect.poll(async () => (await client.query(api.inventory.list, { householdId })).textiles[0]?.private).toBe(true)
  await page.reload()
  await page.getByRole('tab', { name: 'Details', exact: true }).click()
  await openAdvanced(page, 'More')
  await expect(page.getByRole('switch', { name: 'Private', exact: true })).toBeChecked()
})

test('matching printed pieces share optional advice with sources, skip and revocable future reminders', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 900 })
    await signUp(page, 'garment-advice', 'Alex Advice')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
    await addClothes(page, { name: 'Synthetic printed tees', count: 3 })
    await page.getByRole('button', { name: /^Synthetic printed tees,/ }).click()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    const privacy = page.getByRole('switch', { name: 'Private', exact: true })
    await expect(privacy).toBeEnabled()
    await expect(privacy).not.toBeChecked()
    await privacy.click()
    await expect(privacy).toBeChecked()
    await page.getByRole('dialog').last().getByRole('button', { name: 'Save changes', exact: true }).click()
    const privateInventory = await convexAs(page)
    await expect.poll(async () => {
      const pieces = (await privateInventory.client.query(api.inventory.list, { householdId: privateInventory.householdId })).textiles.filter((piece) => piece.name === 'Synthetic printed tees')
      return pieces.length === 3 && pieces.every((piece) => piece.private === true)
    }).toBe(true)
    await openAdvanced(page, 'More')
    await privacy.click()
    await expect(privacy).not.toBeChecked()
    await page.getByRole('dialog').last().getByRole('button', { name: 'Save changes', exact: true }).click()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    // Three matching pieces with the same (unrecorded) decoration read once, not once per piece.
    await expect(page.getByText('Decoration not recorded', { exact: false })).toHaveCount(1)
    await expect(page.getByText(/Matching piece \d of \d/)).toHaveCount(0)
    await page.getByRole('button', { name: 'Record print details', exact: true }).click()
    const draft = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Print details', exact: true }) })
    await draft.getByRole('button', { name: 'Select all matching pieces', exact: true }).click()
    await draft.getByLabel('Decoration', { exact: true }).selectOption('printed')
    await draft.getByLabel('Print method', { exact: true }).selectOption('dtg')
    await draft.getByLabel('Manufacturer, if recorded', { exact: true }).fill('Printful')
    await draft.getByLabel('Where you checked these facts', { exact: true }).fill('Synthetic test listing; no owned garment claim')
    await page.keyboard.press('Escape')
    await expect(page.getByText('Discard your changes?', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
    await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
    for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['phone-dark', 390, 1, 'dark'], ['narrow-light-large', 320, 2, 'light'], ['narrow-dark-large', 320, 2, 'dark'], ['wide', 1024, 1, 'light'], ['wide-dark', 1024, 1, 'dark']] as const) {
      await page.setViewportSize({ width, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
      await draft.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
      expect(await draft.evaluate((element) => element.scrollWidth <= element.clientWidth + 1), name).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`garment-print-details-${name}.png`) })
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ colorScheme: 'light' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await draft.getByRole('checkbox', { name: 'I’ve checked these facts for these 3 pieces.', exact: true }).check()
    await draft.getByRole('button', { name: 'Save print details', exact: true }).click()
    await expect(draft).toHaveCount(0)
    await page.reload()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    // The same source recorded for all three pieces reads once.
    await expect(page.getByRole('dialog').last().getByText('Synthetic test listing; no owned garment claim', { exact: false })).toHaveCount(1)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Edit item details', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await planAndStart(page, 3)
    const step = page.locator('section.machine-step')
    await expect(step.getByRole('heading', { name: 'Turn printed clothing inside out (optional)', exact: true })).toBeVisible()
    const source = step.getByRole('button', { name: 'Advice source', exact: true })
    await source.focus()
    await page.keyboard.press('Enter')
    await expect(source).toHaveAttribute('aria-expanded', 'true')
    await expect(step.getByRole('link', { name: 'Printful product care guidance', exact: true })).toBeVisible()
    await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
    for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['phone-dark', 390, 1, 'dark'], ['narrow-light-large', 320, 2, 'light'], ['narrow-dark-large', 320, 2, 'dark'], ['wide', 1024, 1, 'light'], ['wide-dark', 1024, 1, 'dark']] as const) {
      await page.setViewportSize({ width, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
      const overflow = await step.evaluate((element) => [...element.querySelectorAll('*')].filter((child) => child.getBoundingClientRect().right > element.getBoundingClientRect().right + 1).map((child) => ({ tag: child.tagName, text: child.textContent?.slice(0, 80), width: child.getBoundingClientRect().width })))
      expect(await step.evaluate((element) => element.scrollWidth <= element.clientWidth + 1), `${name}: ${JSON.stringify(overflow)}`).toBe(true)
      await source.scrollIntoViewIfNeeded()
      expect((await source.boundingBox())!.height).toBeGreaterThanOrEqual(44)
      await page.screenshot({ path: testInfo.outputPath(`garment-advice-${name}.png`) })
      const reset = step.getByRole('button', { name: 'Hide optional advice', exact: true })
      await reset.scrollIntoViewIfNeeded()
      const bounds = (await reset.boundingBox())!
      const done = (await page.getByRole('button', { name: 'Done', exact: true }).boundingBox())!
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(done.y)
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await step.getByRole('button', { name: 'Hide optional advice', exact: true }).click()
    await expect(step).toContainText('these 3 pieces: hidden · remembered')
    await page.reload()
    // Before any performed step, reload returns to the existing Chemistry entry.
    await page.getByRole('button', { name: 'Start preparation', exact: true }).click()
    await expect(step.getByRole('heading', { name: 'Turn printed clothing inside out (optional)', exact: true })).toBeVisible()
    await expect(step).toContainText('these 3 pieces: hidden · remembered')
    await step.getByRole('button', { name: 'Skip this tip', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(step.getByRole('heading', { name: 'Turn printed clothing inside out (optional)', exact: true })).toHaveCount(0)
    await step.focus()
    await page.keyboard.press('ArrowLeft')
    await step.getByRole('button', { name: 'Advice source', exact: true }).click()
    await expect(step.getByRole('link', { name: 'Printful product care guidance', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Next step', exact: true }).click()
    await finishSession(page)
    const { client, householdId } = await convexAs(page)
    const pieces = (await client.query(api.inventory.list, { householdId })).textiles
    const textileIds = pieces.map((piece) => piece.textileId)
    for (const textileId of textileIds) await client.mutation(api.inventory.updateTextile, { textileId, status: 'dirty' })
    const future = async () => {
      const { planId } = await client.mutation(api.plans.recompute, { householdId, selectedTextileIds: textileIds, clientInputHash: 'advice-check' })
      return (await client.query(api.plans.get, { planId }))!.result.loads[0]!
    }
    expect((await future()).garmentAdvice).toBeUndefined()
    await page.getByRole('button', { name: 'Back to Laundry', exact: true }).click()
    await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
    await page.getByRole('button', { name: /^Synthetic printed tees,/ }).click()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    await page.getByRole('button', { name: 'Reset advice preference', exact: true }).click()
    await expect(page.getByText('shown when supported · default', { exact: false })).toBeVisible()
    expect((await future()).garmentAdvice?.[0]?.textileIds).toHaveLength(3)
  } finally { await page.context().close() }
})
