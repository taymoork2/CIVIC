  await expect(sort(2)).toBeVisible()
  await moreBlack.click()
  await moreBlack.click()
  await expect(hamperRows(page, 'Black trial tee')).toContainText('2 of 2 selected')
  await expect(sort(4)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: testInfo.outputPath('small-wash-phone.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: testInfo.outputPath('small-wash-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
