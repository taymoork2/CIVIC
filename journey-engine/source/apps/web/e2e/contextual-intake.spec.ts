test('silk restricts bleach; dry-clean only skips washing extras while optional iron remains editable', async ({ page }) => {
  const sheet = await begin(page, 'Dress')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Silk', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'White', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(sheet.getByRole('radio', { name: /^Any bleach/ })).toHaveCount(0)
  await expect(sheet.getByRole('radio', { name: /^Non-chlorine/ })).toHaveCount(0)
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await sheet.getByRole('button', { name: 'Dry clean only', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Dry clean only', exact: true }).locator('[data-symbol="dry_clean_p"] path')).toHaveCount(1)
  await page.screenshot({ path: test.info().outputPath('silk-dry-clean-393-light.png'), animations: 'disabled' })
  await sheet.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(sheet.getByRole('heading', { name: 'Any stains?' })).toBeVisible()
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await expect(sheet.getByRole('progressbar')).toHaveAttribute('aria-valuetext', 'Step 10 of 10')
  await sheet.getByRole('button', { name: 'Edit more on the label', exact: true }).click()
  await sheet.getByRole('button', { name: 'Iron, low heat', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Edit more on the label', exact: true })).toContainText('Iron, low heat')
  await page.screenshot({ path: test.info().outputPath('silk-review-393-light.png'), animations: 'disabled' })
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const item = (await client.query(api.inventory.list, { householdId })).textiles[0]!
  expect(item.care).toMatchObject({ material: 'silk', washMethod: 'dry_clean_only', dryMethod: 'unknown', ironHeat: 'low' })
  expect(item.care?.bleach ?? null).toBeNull()
  expect(item.care?.steamPermission ?? null).toBeNull()
})
