import { expect, test, type Page } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, signUp } from './flows'

async function begin(page: Page, kind: string) {
  await page.setViewportSize({ width: 393, height: 852 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await signUp(page, `contextual-intake-${kind.toLowerCase()}`, 'Synthetic Items')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = page.getByRole('dialog')
  await expect(sheet.getByRole('group', { name: 'Clothing', exact: true })).toBeVisible()
  await sheet.getByRole('button', { name: kind, exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  return sheet
}

