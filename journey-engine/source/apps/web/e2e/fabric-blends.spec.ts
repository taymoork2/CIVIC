import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { careLabel, convexAs, createHousehold, signUp } from './flows'

test('blend percentages and named Other fibers survive Back, saving, editing and reload', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'blend', 'Blair Blend')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  let sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'T-shirt', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet.getByLabel('Name', { exact: true }).fill('Blend tee')
  await sheet.getByLabel('Quantity', { exact: true }).fill('2')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Cotton', exact: true }).click()
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveCount(0)
  await sheet.getByRole('checkbox', { name: 'Polyester', exact: true }).click()
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveValue('')
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveAttribute('placeholder', 'e.g. 80')
  await sheet.getByRole('checkbox', { name: 'Polyester', exact: true }).click()
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveCount(0)
  await sheet.getByRole('checkbox', { name: 'Polyester', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Next: color', exact: true })).toBeEnabled()
  await sheet.getByLabel('Cotton percentage', { exact: true }).fill('80')
  await expect(sheet.getByLabel('Polyester percentage', { exact: true })).toHaveValue('20')
  await expect(sheet.getByRole('button', { name: 'Next: color', exact: true })).toBeEnabled()
  await sheet.getByLabel('Polyester percentage', { exact: true }).fill('30')
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveValue('70')
  await expect(sheet.getByRole('alert')).toHaveCount(0)
  await sheet.getByLabel('Polyester percentage', { exact: true }).fill('20')
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await expect(sheet.getByRole('checkbox', { name: 'Cotton', exact: true })).toBeChecked()
  await expect(sheet.getByRole('checkbox', { name: 'Polyester', exact: true })).toBeChecked()
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveValue('80')
  await expect(sheet.getByLabel('Polyester percentage', { exact: true })).toHaveValue('20')
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await sheet.locator('.sheet-scroll').evaluate((scroll) => { scroll.scrollTop = 0 })
    await page.screenshot({ path: test.info().outputPath(`fabric-blend-${theme}.png`) })
  }
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'White', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  await careLabel(sheet, 'Cold', 'Low heat')
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const original = await client.query(api.inventory.list, { householdId })
  expect(original.textiles).toHaveLength(2)
  original.textiles.forEach((piece) => expect(piece.care?.material).toBe('80% cotton, 20% polyester'))
  await page.getByRole('button', { name: /^Blend tee,/ }).click()
  await page.getByRole('tab', { name: 'Care', exact: true }).click()
  await page.getByRole('dialog').getByRole('tab', { name: 'Details', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /^Fabric/ }).click()
  sheet = page.getByRole('dialog')
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveValue('80')
  await expect(sheet.getByLabel('Polyester percentage', { exact: true })).toHaveValue('20')
  await sheet.getByRole('checkbox', { name: 'Polyester', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Other', exact: true }).click()
  await sheet.getByLabel('Other material', { exact: true }).fill('Elastane')
  await sheet.getByLabel('Cotton percentage', { exact: true }).fill('95')
  await sheet.getByLabel('Other percentage', { exact: true }).fill('10')
  await expect(sheet.getByLabel('Cotton percentage', { exact: true })).toHaveValue('90')
  await expect(sheet.getByRole('button', { name: 'Save changes', exact: true })).toBeEnabled()
  await sheet.getByLabel('Other percentage', { exact: true }).fill('5')
  await sheet.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: /^Fabric.*95% cotton, 5% Elastane/ })).toBeVisible()
  await page.reload()
  const edited = await client.query(api.inventory.list, { householdId })
  for (const piece of edited.textiles) {
    const before = original.textiles.find((item) => item.textileId === piece.textileId)!
    expect(piece.care).toEqual({ ...before.care, material: '95% cotton, 5% Elastane' })
    expect(piece.status).toBe(before.status)
  }
})

test('fabric blend controls and named Other remain usable at narrow doubled text', async ({ page }) => {
  test.skip(process.env.WASHCLOSET_E2E_BUILD === 'production', 'Local-only visual fixture')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.goto('/design-preview?screen=closet-add-details&textScale=2')
  const sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('button', { name: 'More fibers', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Other', exact: true }).click()
  await sheet.getByLabel('Other material', { exact: true }).fill('Elastane')
  await sheet.getByLabel('Cotton percentage', { exact: true }).fill('95')
  await sheet.getByLabel('Other percentage', { exact: true }).fill('5')
  await expect(sheet.getByRole('button', { name: 'Next: color', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  for (const input of [sheet.getByLabel('Other material', { exact: true }), sheet.getByLabel('Other percentage', { exact: true })]) {
    await input.scrollIntoViewIfNeeded()
    const box = await input.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  }
  await page.screenshot({ path: test.info().outputPath('fabric-other-320-large.png') })
})
