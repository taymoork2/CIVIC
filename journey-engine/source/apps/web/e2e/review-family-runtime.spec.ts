import { expect, test } from '@playwright/test'

test.skip(process.env.WASHCLOSET_REVIEW_E2E !== '1', 'Run against an isolated linked review server.')
test.afterEach(async ({ page }) => { if (await page.getByRole('button', { name: 'Close app', exact: true }).count()) await page.getByRole('button', { name: 'Close app', exact: true }).click().catch(() => {}) })

test('native saved steps survive actual disconnection, same-run switching and reopening without automatic resend', async ({ page, context }) => {
  test.setTimeout(120000)
  // Reopening resumes the run from its journal; holding that request shows the controls wait for it.
  let delayResume = false, sawResume!: () => void
  const resumingReopenedRun = new Promise<void>(resolve => { sawResume = resolve })
  await page.route('**/api/review/runtime', async route => {
    if (delayResume && route.request().postDataJSON()?.action === 'resume') {
      delayResume = false; sawResume()
      await new Promise(resolve => setTimeout(resolve, 1000))
    }
    await route.continue()
  })
  await page.setViewportSize({ width: 1280, height: 1000 })
  await page.goto('/review?familyDay=1')
  await page.getByRole('button', { name: 'Start 1,000-item run' }).click()
  await expect(page.getByRole('button', { name: 'Disconnect app' })).toBeEnabled()
  const app = page.frameLocator('iframe[title="Synthetic Laundry App"]')
  await expect(app.getByRole('heading', { name: 'Laundry', exact: true })).toBeVisible()
  const run = await app.locator('body').evaluate(() => window.reviewRuntime!.status().run)
  await page.mouse.move(1200, 800); await page.mouse.wheel(0, 900)
  await app.getByRole('button', { name: 'Sort 1000 pieces into loads', exact: true }).click()
  await app.getByRole('button', { name: 'Review next load', exact: true }).click()
  await app.getByRole('button', { name: 'I’m at the laundry room', exact: true }).click()
  await app.getByRole('button', { name: /^Confirm recipe for/ }).click()
  await app.getByRole('button', { name: 'See what goes in', exact: true }).click()
  await app.getByRole('button', { name: /^(Start|Continue) preparation$/ }).click()
  await expect(app.getByText('Step 1 of 4', { exact: true })).toBeVisible()
  await context.setOffline(true)
  await expect.poll(() => app.locator('body').evaluate(() => navigator.onLine)).toBe(false)
  await app.getByRole('button', { name: 'Done · next step', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Saved steps' })).toContainText('actions:recordAction')
  const receipt = await app.locator('body').evaluate(() => window.reviewRuntime!.status().pending[0])
  expect(receipt.args).toMatchObject({ status: 'confirmed', receiptId: expect.any(String), expectedTimelineRevision: expect.any(Number) })
  await context.setOffline(false)
  await expect.poll(() => app.locator('body').evaluate(() => navigator.onLine)).toBe(false)
  await page.getByLabel('Synthetic account').selectOption('member')
  await expect(page.getByRole('region', { name: 'Saved steps' })).toHaveCount(0)
  await page.getByLabel('Synthetic account').selectOption('owner')
  await expect(page.getByRole('region', { name: 'Saved steps' })).toBeVisible()
  await page.getByRole('button', { name: 'Close app', exact: true }).click()
  delayResume = true
  await page.getByRole('button', { name: 'Reopen app', exact: true }).click()
  await resumingReopenedRun
  await expect(page.getByRole('button', { name: 'Reconnect app', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Reconnect app', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Reconnect app', exact: true }).click()
  await expect(app.getByRole('button', { name: 'Send saved step', exact: true })).toBeEnabled()
  expect(await app.locator('body').evaluate(() => window.reviewRuntime!.status().run)).toBe(run)
  expect(await app.locator('body').evaluate(() => window.reviewRuntime!.status().pending[0]!.args)).toEqual(receipt.args)
  await page.mouse.move(1200, 800); await page.mouse.wheel(0, 900)
  await app.getByRole('button', { name: 'Send saved step', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Saved steps' })).toHaveCount(0)
  await expect(app.getByRole('button', { name: 'Send saved step', exact: true })).toHaveCount(0)
  const project = await app.locator('body').evaluate(async () => (await window.reviewPreview!.recording!()).project)
  const actor = await app.locator('body').evaluate(() => window.reviewRuntime!.status().subject)
  const detail = await page.request.post('/api/review/runtime', { headers: { 'x-rehearsal-project': project }, data: { action: 'query', run, actor, name: 'execution:sessionDetail', args: { sessionId: receipt.args.sessionId } } })
  expect(detail.ok()).toBe(true)
  expect((await detail.json()).actions.find((row: { id: string }) => row.id === receipt.args.actionId).status).toBe('confirmed')
  await app.getByRole('button', { name: /^(Start|Continue) preparation$/ }).click()
  await expect(app.getByText('Step 2 of 4', { exact: true })).toBeVisible()
})

