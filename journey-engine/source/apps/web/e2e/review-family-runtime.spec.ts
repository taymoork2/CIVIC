test('device, fold and orientation changes resize the real iframe and keep the same run and selection', async ({ page }) => {
  await page.goto('/review?familyDay=1')
  await page.getByRole('button', { name: 'Start 1,000-item run' }).click()
  await expect(page.getByRole('button', { name: 'Disconnect app' })).toBeEnabled()
  const frame = page.frameLocator('iframe[title="Synthetic Laundry App"]')
  const run = await frame.locator('body').evaluate(() => window.reviewRuntime!.status().run)
  await page.locator('iframe[title="Synthetic Laundry App"]').scrollIntoViewIfNeeded()
  await frame.getByRole('button', { name: /Fewer .*Alex cotton 00/ }).click()
  await expect(frame.getByText('999 of 1000 machine-wash pieces selected across every page.', { exact: true })).toBeVisible()
  for (const [device, width, height] of [['small-phone', 320, 658], ['phone', 393, 852], ['tablet', 768, 1024], ['desktop', 1024, 768], ['iphone-16-pro', 402, 681], ['folded', 360, 764], ['unfolded', 984, 1016]] as const) {
    await page.getByLabel('Preview device').selectOption(device)
    await expect.poll(() => frame.locator('body').evaluate(() => ({ width: innerWidth, height: innerHeight }))).toEqual({ width, height })
    expect(await frame.locator('body').evaluate(() => window.reviewRuntime!.status().run)).toBe(run)
    await expect(frame.getByText('999 of 1000 machine-wash pieces selected across every page.', { exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Rotate viewport' }).click()
  await expect.poll(() => frame.locator('body').evaluate(() => ({ width: innerWidth, height: innerHeight }))).toEqual({ width: 1016, height: 984 })
  await page.getByRole('button', { name: 'Fold viewport', exact: true }).click()
  await expect.poll(() => frame.locator('body').evaluate(() => ({ width: innerWidth, height: innerHeight }))).toEqual({ width: 764, height: 360 })
  await page.getByRole('button', { name: 'Unfold viewport', exact: true }).click()
  await expect.poll(() => frame.locator('body').evaluate(() => ({ width: innerWidth, height: innerHeight }))).toEqual({ width: 1016, height: 984 })
  await page.getByLabel('Preview appearance').selectOption('dark')
  await expect(frame.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('Preview text size').selectOption('2')
  await expect(frame.locator('html')).toHaveCSS('font-size', '32px')
  expect(await frame.locator('body').evaluate(() => window.reviewRuntime!.status().run)).toBe(run)
  await page.getByRole('button', { name: 'Replay this run', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Replay verified:' })).toBeVisible({ timeout: 30000 })
  await expect(frame.getByText('999 of 1000 machine-wash pieces selected across every page.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close app', exact: true }).click()
  await page.getByRole('button', { name: 'Reopen app', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Disconnect app' })).toBeEnabled()
  await expect.poll(() => frame.locator('body').evaluate(() => ({ width: innerWidth, height: innerHeight }))).toEqual({ width: 1016, height: 984 })
  await expect(frame.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(frame.locator('html')).toHaveCSS('font-size', '32px')
})
