import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { careLabel, convexAs, createHousehold, signUp } from './flows'

test.use({ locale: 'en-US' })

test('a multi-color pack saves individual pieces with shared composition and separate dye answers', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'bulk-fabric', 'Casey Colors')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'Underwear', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet.getByLabel('Quantity', { exact: true }).fill('3')
  await sheet.getByLabel('Brand', { exact: true }).fill('Calvin Klein')
  await sheet.getByLabel('Size', { exact: true }).fill('M')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Cotton', exact: true }).check()
  await expect(sheet.getByRole('button', { name: 'More fibers', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await expect(sheet.getByRole('group', { name: 'What’s it made of?', exact: true }).getByRole('checkbox')).toHaveCount(9)
  await expect(sheet.getByRole('group', { name: 'What’s it made of?', exact: true }).getByRole('checkbox', { name: 'Other', exact: true })).toHaveCount(0)
  await sheet.getByRole('checkbox', { name: 'Elastane / spandex', exact: true }).check()
  await expect(sheet.getByRole('checkbox', { name: 'Modal', exact: true })).toBeVisible()
  await sheet.getByRole('button', { name: 'More fibers', exact: true }).click()
  await expect(sheet.getByRole('checkbox', { name: 'Other', exact: true })).toBeVisible()
  await sheet.getByLabel('Cotton percentage', { exact: true }).fill('95')
  await sheet.getByLabel('Elastane / spandex percentage', { exact: true }).fill('5')
  await sheet.getByRole('button', { name: 'More fibers', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Advanced fabric details', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.screenshot({ path: test.info().outputPath('fabric-primary-light.png'), animations: 'disabled' })
  await sheet.getByRole('button', { name: 'Advanced fabric details', exact: true }).click()
  await sheet.getByRole('button', { name: 'Supima', exact: true }).click()
  await sheet.getByRole('button', { name: 'Jersey', exact: true }).click()
  await sheet.getByRole('button', { name: 'Pre-shrunk', exact: true }).click()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`fabric-${theme}.png`), animations: 'disabled' })
  }
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Black', exact: true }).click()
  await sheet.getByRole('button', { name: 'Add another color', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Next: where from', exact: true })).toBeDisabled()
  await expect(sheet.getByRole('group', { name: 'Black', exact: true }).locator('output')).toHaveText('2')
  await sheet.getByRole('radio', { name: 'Blue', exact: true }).click()
  await sheet.getByRole('button', { name: 'Add another color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Green', exact: true }).click()
  await expect(sheet.getByText('3 pieces total', { exact: true })).toBeVisible()
  const black = await sheet.getByRole('button', { name: 'Black', exact: true }).boundingBox()
  const count = await sheet.getByRole('group', { name: 'Black', exact: true }).boundingBox()
  expect(Math.abs((black!.y + black!.height / 2) - (count!.y + count!.height / 2))).toBeLessThan(2)
  await expect(sheet.getByRole('button', { name: 'Less: Green', exact: true })).toBeDisabled()
  for (let index = 0; index < 17; index++) await sheet.getByRole('button', { name: 'More: Green', exact: true }).click()
  await expect(sheet.getByText('20 pieces total', { exact: true })).toBeVisible()
  await expect(sheet.getByRole('button', { name: 'More: Green', exact: true })).toBeDisabled()
  await expect(sheet.getByRole('button', { name: 'Add another color', exact: true })).toBeDisabled()
  for (let index = 0; index < 17; index++) await sheet.getByRole('button', { name: 'Less: Green', exact: true }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await sheet.getByRole('button', { name: 'Advanced fabric details', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Supima', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`bulk-colors-${theme}.png`), animations: 'disabled' })
  }
  await page.setViewportSize({ width: 320, height: 740 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const colorControls = sheet.getByLabel('Colors in this pack').locator('button')
  expect(await colorControls.evaluateAll(nodes => nodes.every(node => {
    const rect = node.getBoundingClientRect()
    return rect.left >= 0 && rect.right <= window.innerWidth + 1 && rect.width >= 44 && rect.height >= 44
  }))).toBe(true)
  await page.screenshot({ path: test.info().outputPath('bulk-colors-320-enlarged.png'), animations: 'disabled' })
  await sheet.getByRole('button', { name: 'Remove Green', exact: true }).click()
  await expect(sheet.getByText('2 pieces total', { exact: true })).toBeVisible()
  await page.evaluate(() => { document.documentElement.style.fontSize = '' })
  await sheet.getByRole('button', { name: 'Add another color', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Green', exact: true }).click()
  await page.setViewportSize({ width: 1024, height: 900 })
  await page.screenshot({ path: test.info().outputPath('bulk-colors-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 393, height: 852 })
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  for (const color of ['Black', 'Blue', 'Green']) await expect(sheet.getByLabel(color, { exact: true })).toHaveValue('unknown')
  await sheet.getByLabel('Black', { exact: true }).selectOption({ label: 'Washed without dye running' })
  await expect(sheet.getByLabel('Blue', { exact: true })).toHaveValue('unknown')
  await sheet.getByLabel('Blue', { exact: true }).selectOption('new')
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  await careLabel(sheet, 'Cold', 'Low heat')
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'Save item', exact: true })).toBeDisabled()
  await sheet.getByRole('checkbox', { name: 'These pieces have the same care instructions', exact: true }).check()
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(sheet.getByRole('heading', { name: 'First items added', exact: true })).toBeVisible()
  const completion = sheet.locator('[data-completion-mark]')
  await expect(completion).toBeVisible()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`first-items-added-${theme}.png`), animations: 'disabled' })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(completion).toHaveCSS('animation-name', 'none')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '32px' })
  await expect(sheet.getByRole('button', { name: 'Done', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('first-items-added-320-enlarged.png'), animations: 'disabled' })
  await page.evaluate(() => { document.documentElement.style.fontSize = '' })
  await page.setViewportSize({ width: 393, height: 852 })
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Milestones', exact: true })).toHaveCount(0)
  await expect(page.getByText('First garment saved', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'First items added', exact: true })).toHaveCount(0)
  await expect(page.locator('[data-sonner-toast]')).toContainText('Saved')
  const { client, householdId } = await convexAs(page)
  const { textiles } = await client.query(api.inventory.list, { householdId })
  expect(textiles).toHaveLength(3)
  expect(new Set(textiles.map((piece) => piece.textileId)).size).toBe(3)
  expect(textiles.map((piece) => [piece.color, piece.dyeRun, piece.firstWash]).sort()).toEqual([
    ['Black', 'fast', false], ['Blue', 'new', true], ['Green', 'unknown', null],
  ])
  for (const piece of textiles) expect(piece).toMatchObject({ identity: { brand: 'Calvin Klein', size: 'M' }, care: { material: '95% cotton, 5% elastane', fabricDetails: { fibers: [{ fiber: 'cotton', details: ['Supima'] }], construction: ['Jersey'], finishes: ['Pre-shrunk'] } } })
  await page.reload()
  await expect(page.getByRole('button', { name: /^Black underwear,/ })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Milestones', exact: true })).toHaveCount(0)
  await expect(page.getByText('First garment saved', { exact: true })).toHaveCount(0)
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`closet-without-milestones-${theme}.png`), animations: 'disabled' })
  }
  await page.getByRole('button', { name: /^Black underwear,/ }).click()
  await expect(sheet).toBeVisible()
  await page.reload()
  await expect(sheet).toBeVisible()
  await sheet.getByRole('tab', { name: 'Details', exact: true }).click()
  await sheet.getByRole('button', { name: /^Fabric/ }).click()
  const edit = page.getByRole('dialog').last()
  await expect(edit.getByRole('button', { name: 'Supima', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await edit.getByRole('button', { name: 'Supima', exact: true }).click()
  await edit.getByRole('button', { name: 'Pima', exact: true }).click()
  await edit.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect.poll(async () => (await client.query(api.inventory.list, { householdId })).textiles.find((piece) => piece.color === 'Black')?.care?.fabricDetails?.fibers?.[0]?.details).toEqual(['Pima'])
  expect((await client.query(api.inventory.list, { householdId })).textiles.find((piece) => piece.color === 'Blue')?.care?.fabricDetails?.fibers?.[0]?.details).toEqual(['Supima'])
})
