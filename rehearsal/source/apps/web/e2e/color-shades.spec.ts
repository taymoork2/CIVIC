import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { careLabel, convexAs, createHousehold, signUp } from './flows'

test('color shades show the selected hue, retain drafts and keep medium red in Bright sorting', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'color-shades', 'Casey Color')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = page.getByRole('dialog')
  await sheet.getByRole('button', { name: 'T-shirt', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet.getByLabel('Name', { exact: true }).fill('Shade tee')
  await sheet.getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  const colors = sheet.getByRole('radiogroup', { name: 'What color?', exact: true })
  const shades = sheet.getByRole('radiogroup', { name: 'How light or dark?', exact: true })
  await colors.getByRole('radio', { name: 'Red', exact: true }).click()
  await expect(shades.getByRole('radio', { name: 'Medium', exact: true })).toBeChecked()
  await expect(sheet.getByRole('status')).toHaveText('Medium red, such as cherry red.')
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`color-red-medium-${theme}.png`), animations: 'disabled' })
  }
  for (const color of ['Red', 'Blue', 'Gray', 'Pink', 'Green', 'Brown']) {
    await colors.getByRole('radio', { name: color, exact: true }).click()
    const fills = []
    for (const shade of ['Light', 'Medium', 'Dark']) {
      const choice = shades.getByRole('radio', { name: shade, exact: true })
      await choice.click()
      await expect(choice).toBeChecked()
      await expect(sheet.getByRole('status')).toContainText(`${shade} ${color.toLowerCase()},`)
      const fill = await choice.locator('[aria-hidden="true"]').evaluate((swatch) => getComputedStyle(swatch).backgroundColor)
      expect(await colors.getByRole('radio', { name: color, exact: true }).locator('[style]').evaluate((swatch) => getComputedStyle(swatch).backgroundColor)).toBe(fill)
      fills.push(fill)
    }
    expect(new Set(fills).size).toBe(3)
    await shades.getByRole('radio', { name: 'Not sure', exact: true }).click()
    await expect(sheet.getByRole('status')).toHaveCount(0)
  }
  await colors.getByRole('radio', { name: 'Red', exact: true }).click()
  await expect(shades.getByRole('radio', { name: 'Medium', exact: true })).toBeChecked()
  await shades.getByRole('radio', { name: 'Light', exact: true }).click()
  await sheet.getByRole('button', { name: 'Back', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: color', exact: true }).click()
  await expect(shades.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  await expect(sheet.getByRole('status')).toHaveText('Light red, such as coral.')
  await colors.getByRole('radio', { name: 'Red', exact: true }).click()
  await expect(shades.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  for (const color of ['White', 'Cream', 'Black', 'Navy', 'Not sure', 'Mixed']) {
    await colors.getByRole('radio', { name: color, exact: true }).click()
    await expect(shades).toHaveCount(0)
  }
  await sheet.getByRole('radiogroup', { name: 'Mostly light or mostly dark?', exact: true }).getByRole('radio', { name: 'Mostly dark', exact: true }).click()
  await colors.getByRole('radio', { name: 'Red', exact: true }).click()
  await expect(shades.getByRole('radio', { name: 'Medium', exact: true })).toBeChecked()
  await shades.getByRole('radio', { name: 'Medium', exact: true }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect(shades.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  await page.keyboard.press('ArrowRight')
  await expect(shades.getByRole('radio', { name: 'Medium', exact: true })).toBeChecked()
  await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet.getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: care label', exact: true }).click()
  await careLabel(sheet, 'Cold', 'Low heat')
  await sheet.getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet.getByRole('button', { name: 'Next: review', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save item', exact: true }).click()
  await sheet.getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const { textiles } = await client.query(api.inventory.list, { householdId })
  expect(textiles).toHaveLength(1)
  expect(textiles[0]).toMatchObject({ name: 'Shade tee', color: 'Red', colorGroup: 'saturated', dyeRun: 'fast' })
  await page.reload()
  const reloaded = await client.query(api.inventory.list, { householdId })
  expect(reloaded.textiles[0]).toMatchObject({ color: 'Red', colorGroup: 'saturated', dyeRun: 'fast' })
})

test('color shade swatches wrap at narrow doubled text', async ({ page }) => {
  test.skip(process.env.WASHCLOSET_E2E_BUILD === 'production', 'Local-only visual fixture')
  await page.setViewportSize({ width: 320, height: 852 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/design-preview?screen=closet-add-color&textScale=2')
  const sheet = page.getByRole('dialog')
  await sheet.getByRole('radiogroup', { name: 'What color?', exact: true }).getByRole('radio', { name: 'Red', exact: true }).click()
  const shades = sheet.getByRole('radiogroup', { name: 'How light or dark?', exact: true })
  for (const shade of ['Light', 'Medium', 'Dark', 'Not sure']) {
    const choice = shades.getByRole('radio', { name: shade, exact: true })
    await choice.scrollIntoViewIfNeeded()
    await choice.click()
    const box = await choice.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(320)
    expect(box!.height).toBeGreaterThanOrEqual(44)
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await shades.getByRole('radio', { name: 'Light', exact: true }).click()
  await expect(sheet.getByRole('status')).toHaveText('Light red, such as coral.')
  await page.screenshot({ path: test.info().outputPath('color-red-light-320-large.png'), animations: 'disabled' })
})
