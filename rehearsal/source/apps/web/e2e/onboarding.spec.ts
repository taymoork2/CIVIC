for (const submit of ['button', 'keyboard'] as const) {
  test(`setup creates an invite by ${submit}, then closes to a restored clothes prompt`, async ({ page }) => {
    await page.setViewportSize({ width: 393, height: 852 })
    await page.emulateMedia({ colorScheme: 'dark' })
    await startSetup(page, `onboarding-invite-${submit}`)
    await page.getByRole('button', { name: 'Continue', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'What’s next?', exact: true })).toBeVisible()
    const beforeInvite = await page.locator('.account-page').boundingBox()
    await page.getByRole('button', { name: /^Invite your household/ }).click()
    const invite = page.getByRole('dialog')
    await invite.evaluate((dialog) => { dialog.dataset.inviteDrawer = 'original' })
    await invite.getByLabel('Name', { exact: true }).fill('Sam')
    await invite.getByLabel('Name', { exact: true }).focus()
    if (submit === 'keyboard') await invite.getByLabel('Name', { exact: true }).press('Enter')
    else await invite.getByRole('button', { name: 'Make invite link', exact: true }).click()
    await expect(invite.getByRole('heading', { name: 'Invite Sam', exact: true })).toBeVisible()
    await expect(invite.getByRole('button', { name: 'Share invite link', exact: true })).toBeVisible()
    await expect(invite).toHaveAttribute('data-invite-drawer', 'original')
    await invite.getByRole('button', { name: 'Copy link', exact: true }).click()
    await expect(page.getByText('Invite link copied', { exact: true })).toBeVisible()
    await invite.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Add clothes?', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Add clothes?', exact: true })).toBeFocused()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect.poll(async () => (await page.locator('.account-page').boundingBox())?.y).toBe(beforeInvite!.y)
    await expect.poll(() => page.evaluate(() => ({ scrollY: window.scrollY, height: window.innerHeight, pageHeight: document.querySelector('.account-page')!.getBoundingClientRect().height, htmlOverflow: document.documentElement.style.overflowY, bodyOverflow: document.body.style.overflowY }))).toEqual({ scrollY: 0, height: 852, pageHeight: 852, htmlOverflow: '', bodyOverflow: '' })
    await expect(page.getByText('Invite link copied', { exact: true })).toBeHidden()
    await page.screenshot({ path: test.info().outputPath('invite-closed.png') })
    await expect(page.getByRole('button', { name: /^Invite your household/ })).toHaveCount(0)
    await page.getByRole('button', { name: /^Add clothes/ }).click()
    const intake = page.getByRole('dialog')
    await expect(intake.getByRole('heading', { name: 'What is it?', exact: true })).toBeVisible()
    await expect(intake.getByRole('button', { name: 'Later', exact: true })).toHaveCount(0)
    await expect(intake.getByRole('button', { name: 'Close', exact: true })).toHaveCount(1)
    await intake.getByRole('button', { name: 'Close', exact: true }).click()
    const { client } = await convexAs(page)
    expect((await client.query(api.households.onboardingStatus, {})).households[0]!.guidance).toMatchObject({ stage: 'clothes', status: 'started' })
  })
}

