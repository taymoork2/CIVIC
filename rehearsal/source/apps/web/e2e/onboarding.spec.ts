import { expect, test, type Page } from '@playwright/test'
import { api } from '../src/api'
import { careLabel, convexAs, createHousehold, inviteNewPerson, joinWithCode, signUp } from './flows'

async function startSetup(page: Page, who: string) {
  await signUp(page, who, 'Onboarding Test')
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Create a household/ }).click()
  await page.getByRole('button', { name: 'Create household', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Set up', exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toHaveText('Household created')
  await expect(page.getByRole('button', { name: 'Finish later', exact: true })).toHaveCount(0)
  await expect(page.getByText('What would help today?', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Your first garment|Invite your household/ })).toHaveCount(0)
  await page.getByRole('button', { name: /Where you wash/ }).click()
  await page.getByRole('radio', { name: 'Shared laundry room', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

