test('joining a household skips owner setup and offers an optional closet', async ({ browser, page }) => {
  await signUp(page, 'onboarding-owner', 'Owner')
  await createHousehold(page)
  const code = await inviteNewPerson(page, 'New member')
  const context = await browser.newContext()
  try {
    const member = await context.newPage()
    await signUp(member, 'onboarding-member', 'New member')
    await joinWithCode(member, code)
    await expect(member.getByRole('navigation', { name: 'Primary navigation' })).toBeVisible()
    await member.goto('/setup')
    await expect(member.getByRole('heading', { name: 'Add clothes?', exact: true })).toBeVisible()
    await expect(member.getByRole('button', { name: /Where you wash|Invite your household/ })).toHaveCount(0)
  } finally { await context.close() }
})
