test('one onboarding intake saves ready-to-wear and needs-washing clothes without appliance or product facts', async ({ page }) => {
  await startSetup(page, 'onboarding-hamper')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Add clothes/ })).toHaveCount(1)
  await page.getByRole('button', { name: /^Add clothes/ }).click()
  const intake = page.getByRole('dialog')
  await expect(intake).toBeVisible()
  await expect(intake.getByRole('button', { name: 'Later', exact: true })).toHaveCount(0)
  for (const destination of ['Ready to wear', 'Needs washing'] as const) {
    await intake.getByRole('button', { name: 'T-shirt', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: details', exact: true }).click()
    await intake.getByLabel('Name', { exact: true }).fill(destination)
    await intake.getByRole('button', { name: 'Next: fabric', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: color', exact: true }).click()
    await intake.getByRole('radio', { name: 'White', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: where from', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: dye', exact: true }).click()
    await intake.getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: care label', exact: true }).click()
    await careLabel(intake, 'Cold', 'Low heat')
    await intake.getByRole('radio', { name: 'No stains', exact: true }).click()
    await intake.getByRole('button', { name: 'Next: review', exact: true }).click()
    await intake.getByRole('radio', { name: destination, exact: true }).click()
    await expect(intake.getByRole('radiogroup', { name: 'How dirty?', exact: true })).toHaveCount(destination === 'Needs washing' ? 1 : 0)
    await intake.getByRole('button', { name: 'Save item', exact: true }).click()
    await expect(intake.getByRole('status')).toContainText('added')
    await intake.getByRole('button', { name: destination === 'Ready to wear' ? /^Add something else/ : 'Done' }).click()
  }
  const { client, householdId } = await convexAs(page)
  const inventory = await client.query(api.inventory.list, { householdId })
  expect(inventory.textiles.map((piece) => [piece.name, piece.status])).toEqual([['Ready to wear', 'clean'], ['Needs washing', 'dirty']])
  expect(inventory.machines).toHaveLength(0)
  expect(inventory.supplies).toHaveLength(0)
  expect((await client.query(api.households.onboardingStatus, {})).households[0]!.guidance).toMatchObject({ stage: 'clothes', status: 'started' })
})

