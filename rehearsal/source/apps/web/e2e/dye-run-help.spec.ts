test('dye help opens on tap at phone width and enlarged text without changing the answer', async ({ page }) => {
  test.skip(process.env.WASHCLOSET_E2E_BUILD === 'production', 'Local-only visual fixture')
  for (const [width, scale, colorScheme] of [[393, 1, 'light'], [393, 1, 'dark'], [320, 2, 'dark']] as const) {
    await page.emulateMedia({ reducedMotion: 'reduce', colorScheme })
    await page.setViewportSize({ width, height: 852 })
    await page.goto(`/design-preview?screen=closet-add-color&textScale=${scale}`)
    const sheet = page.getByRole('dialog')
    await sheet.getByRole('button', { name: 'Next: where from', exact: true }).click()
    await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
    const selected = sheet.getByRole('radio', { name: 'New, not washed yet', exact: true })
    const help = sheet.getByRole('button', { name: 'What does “Could the dye run?” mean?', exact: true })
    await expect(selected).toBeChecked()
    await expect(sheet.getByRole('radio', { name: 'Washed without dye running', exact: true })).toBeVisible()
    expect(await help.evaluate(element => !!(element.compareDocumentPosition(document.querySelector('[role="radiogroup"][aria-label="Could the dye run?"]')!) & Node.DOCUMENT_POSITION_PRECEDING))).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`dye-${width}-${scale}-${colorScheme}.png`), animations: 'disabled' })
    await help.click()
    const guidance = page.getByText('Dye runs when it colors the wash water or transfers to other items.', { exact: true })
    await expect(guidance).toBeVisible()
    await expect(page.getByText(/Fading alone doesn’t confirm dye running/)).toBeVisible()
    await expect(page.getByText(/Fading alone doesn’t confirm dye running/)).toContainText('choose “Not sure”')
    await guidance.evaluate(element => element.scrollIntoView({ block: 'start' }))
    await expect(selected).toBeChecked()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`dye-help-${width}-${scale}-${colorScheme}.png`), animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(guidance).not.toBeVisible()
    await expect(help).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(guidance).toBeVisible()
    await page.keyboard.press('Escape')
    await sheet.getByRole('radio', { name: 'Not sure', exact: true }).click()
    await sheet.getByRole('button', { name: 'Back', exact: true }).click()
    await sheet.getByRole('button', { name: 'Next: dye', exact: true }).click()
    await expect(sheet.getByRole('radio', { name: 'Not sure', exact: true })).toBeChecked()
  }
})

test('existing garment dye edit shares the help and preserves its answer through save and reload', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'dye-help', 'Dye Test')
  await createHousehold(page)
  const { client, householdId } = await convexAs(page)
  await client.mutation(api.inventory.createTextiles, { householdId, name: 'Dye tee', quantity: 1, kind: 'shirt', status: 'clean', color: 'Blue', colorGroup: 'medium', dyeRun: 'fast' })
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: /^Dye tee,/ }).click()
  const record = page.getByRole('dialog').first()
  await record.getByRole('tab', { name: 'Care', exact: true }).click()
  await record.getByRole('button', { name: /^Dye:/ }).click()
  const editor = page.getByRole('dialog').last()
  await expect(editor.getByRole('radio', { name: 'Washed without dye running', exact: true })).toBeChecked()
  await editor.getByRole('button', { name: 'What does “Could the dye run?” mean?', exact: true }).click()
  await expect(page.getByText(/Past washes don’t guarantee/)).toBeVisible()
  await page.keyboard.press('Escape')
  await editor.getByRole('radio', { name: 'Dye has run before', exact: true }).click()
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click()
  expect((await client.query(api.inventory.list, { householdId })).textiles[0]!.dyeRun).toBe('bleeds')
  await page.reload()
  await record.getByRole('tab', { name: 'Care', exact: true }).click()
  await expect(record.getByRole('button', { name: /^Dye:/ })).toContainText('Dye has run before')
})
