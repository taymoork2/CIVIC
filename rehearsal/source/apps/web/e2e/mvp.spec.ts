import { expect, test } from '@playwright/test'
import type { Id } from '@convex/_generated/dataModel'

import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, answerCards, convexAs, createHousehold, finishSession, freshPage, inviteNewPerson, joinWithCode, openHousehold, planAndStart, signUp } from './flows'

test('AE1/AE5: a fresh account completes washing and drying, with readiness and history after reload', async ({ browser }, testInfo) => {
  let page = await freshPage(browser)
  await page.setViewportSize({ width: 390, height: 844 })
  await signUp(page, 'solo', 'Sam Solo')
  await createHousehold(page)
  await addProductAndWasher(page)
  await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, price: '1.50', minutes: '45', heat: { 'Low heat': 'Delicates' } })
  await addClothes(page, { name: 'Trial white tee', count: 2 })
  await planAndStart(page, 2)
  const sessionUrl = page.url()
  await page.screenshot({ path: testInfo.outputPath('machine-phone.png') })
  // Close the page while a preparation tap is offline, then recover the same tap after reconnect.
  const account = await convexAs(page)
  const sessionId = new URL(sessionUrl).pathname.split('/').at(-1)!
  const before = await account.client.query(api.execution.sessionDetail, { sessionId: sessionId as Id<'sessions'> })
  const first = before.actions.find((action) => action.status === 'pending')!
  await page.context().setOffline(true)
  await page.getByRole('button', { name: /^Done · next step/ }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('washcloset:private:pending-steps') ?? '[]').length)).toBe(1)
  const context = page.context()
  await page.close()
  await context.setOffline(false)
  page = await context.newPage()
  await page.goto(sessionUrl)
  await expect(page.getByRole('heading', { name: 'Saved steps need a check', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Send saved step', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Saved steps need a check', exact: true })).toHaveCount(0)
  const recovered = await account.client.query(api.execution.sessionDetail, { sessionId: before.sessionId })
  expect(recovered.actions.find((action) => action.id === first.id)?.status).toBe('confirmed')
  await page.getByRole('button', { name: /^(Start|Continue) preparation$/ }).click()
  const stages = await finishSession(page)
  expect(stages).toContain('Press Start')
  expect(stages).toContain('Load into a dryer')
  expect(stages).toContain('Put away')
  await page.goto(sessionUrl)
  await expect(page.getByRole('heading', { name: /, done\.$|^Load complete$/ })).toBeVisible()
  await page.getByRole('link', { name: 'Back to Laundry' }).first().click()
  await page.getByRole('navigation').getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Trial white tee, White, 2 pieces, Ready to wear', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Care overview', exact: true }).getByRole('link', { name: '2 Ready, 0 Hamper, 0 Washing', exact: true })).toBeVisible()
  const { client, householdId } = await convexAs(page)
  const inventory = await client.query(api.inventory.list, { householdId })
  expect(inventory.textiles.filter((item) => item.name === 'Trial white tee')).toHaveLength(2)
  expect(inventory.textiles.filter((item) => item.name === 'Trial white tee').every((item) => item.status === 'clean' && item.washCount === 1)).toBe(true)
  await page.getByRole('navigation').getByRole('link', { name: 'Me', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Laundry history', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Trial white tee/ })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: /Trial white tee/ }).click()
  // Opened from Me, the load remembers where it came from and Back returns there.
  await expect(page).toHaveURL(`${sessionUrl}?from=me`)
  await expect(page.getByRole('heading', { name: /, done\.$|^Load complete$/ })).toBeVisible()
  await expect(page.getByRole('region', { name: 'This load', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to Me' }).or(page.getByRole('link', { name: 'Back to Me' })).first().click()
  await expect(page.getByRole('heading', { name: 'Laundry history', exact: true })).toBeVisible()
  await page.context().close()
})

test('AE2/AE4: unread care labels block starting; changes in another tab invalidate the plan', async ({ page }) => {
  await signUp(page, 'gaps', 'Gia Gaps')
  await createHousehold(page)
  await addProductAndWasher(page)
  const { client, householdId } = await convexAs(page)
  // Model a legacy/imported garment whose label has never been read. Add clothes itself requires answers.
  const textileIds = await client.mutation(api.inventory.createTextiles, { householdId, name: 'Mystery sweater', quantity: 1, kind: 'sweater', color: 'White', colorGroup: 'white', firstWash: false })
  await page.getByRole('navigation').getByRole('link', { name: /^Laundry/ }).click()
  await page.getByRole('button', { name: /^Sort 1 piece into loads$/ }).click()
  await expect(page.getByRole('button', { name: 'Mystery sweater. Check care label', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Confirm recipe for / })).toHaveCount(0)
  await answerCards(page)
  await page.getByRole('button', { name: 'I’m at the laundry room', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Confirm recipe for / })).toBeEnabled()
  const other = await page.context().newPage()
  await other.goto('/closet')
  const secondDevice = await convexAs(other)
  // A separately authenticated client changes the saved label while the first device reviews its recipe.
  await secondDevice.client.mutation(api.inventory.answerTagQuestions, { textileIds, washMethod: 'machine', cycle: 'normal', maxTemperatureC: 40, dryMethod: 'tumble_dry', dryHeat: 'low' })
  await expect(page.getByRole('button', { name: 'Something changed, tap to update the loads', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Confirm recipe for / })).toHaveCount(0)
  await page.getByRole('button', { name: 'Something changed, tap to update the loads', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Whites load' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Something changed, tap to update the loads', exact: true })).toHaveCount(0)
  // Back at the room, the washer picked before the update is still the one: only its recipe is confirmed again.
  await page.getByRole('button', { name: 'I’m at the laundry room', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Confirm recipe for Laundry room washer/ })).toBeEnabled()
})

test('AE3: members share live progress; outsiders and removed members lose access', async ({ browser }) => {
  const owner = await freshPage(browser)
  await signUp(owner, 'owner', 'Olive Owner')
  await createHousehold(owner)
  await addProductAndWasher(owner)
  await addClothes(owner, { name: 'White shirt', kind: 'shirt' })
  const code = await inviteNewPerson(owner, 'Max')
  const member = await freshPage(browser)
  await signUp(member, 'member', 'Max Member')
  await joinWithCode(member, code)
  await expect(member.getByRole('navigation', { name: 'Primary navigation' })).toBeVisible()
  const sessionUrl = await planAndStart(owner, 1)
  await member.goto(sessionUrl)
  await member.getByRole('button', { name: /^(Start|Continue) preparation$/ }).click()
  await expect(member.locator('.machine-step-title')).toHaveText('Put the clothes in')
  await owner.getByRole('button', { name: 'Done · next step', exact: true }).click()
  await expect(member.locator('.machine-step-title')).not.toHaveText('Put the clothes in')
  const stage = await member.locator('.machine-step-title').textContent()
  await member.reload()
  await expect(member.locator('.machine-step-title')).toHaveText(stage!)
  const outsider = await freshPage(browser)
  await signUp(outsider, 'outsider', 'Oscar Outsider')
  await createHousehold(outsider)
  await outsider.goto(sessionUrl)
  await expect(outsider.locator('.machine-step')).toHaveCount(0)
  await expect(outsider.getByRole('heading', { name: 'This isn’t available to you', exact: true })).toBeVisible()
  await owner.getByRole('link', { name: 'Back to Laundry' }).first().click()
  await openHousehold(owner, 'People')
  await owner.locator('li', { hasText: 'Max Member' }).getByRole('button').click()
  await owner.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true }).click()
  await owner.getByRole('dialog').getByRole('button', { name: 'Remove access', exact: true }).click()
  await expect(member.getByRole('heading', { name: 'Your household', exact: true })).toBeVisible()
  await expect(member.locator('.machine-step')).toHaveCount(0)
  expect(await member.evaluate(() => Object.keys(localStorage).filter((key) => key.startsWith('washcloset:private:')))).toEqual([])
  await Promise.all([owner.context().close(), member.context().close(), outsider.context().close()])
})
