import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addBottle, addClothes, addMachines, addProductAndWasher, convexAs, createHousehold, finishSession, freshPage, openHousehold, signUp, openAdvanced } from './flows'

// Disposable accounts and synthetic label facts; not a real product recommendation.
test('exact-pack chemistry, measured soak recovery and wash assessment work on a phone-sized page', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  await page.setViewportSize({ width: 390, height: 844 })
  await signUp(page, 'chemistry', 'Chris Chemistry')
  await createHousehold(page)
  await addProductAndWasher(page)
  await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates' } })
  await addClothes(page, { name: 'Chemistry cotton tee' })
  const { client, householdId } = await convexAs(page)
  const inventory = await client.query(api.inventory.list, { householdId })
  const shirt = inventory.textiles[0]!, detergent = inventory.supplies[0]!
  await client.mutation(api.inventory.setCare, { textileId: shirt.textileId, material: 'cotton', washMethod: 'machine', cycle: 'normal', maxTemperatureC: 30, restrictions: [], provenance: { source: 'synthetic label', confidence: 'observed' } })
  await client.mutation(api.inventory.saveRule, { supplyId: detergent.supplyId, dose: { amount: 30, unit: 'ml' }, stage: 'wash', placement: 'detergent_compartment', timing: 'Synthetic wash directions', provenance: { source: 'synthetic label', confidence: 'observed' } })
  await openHousehold(page, 'Products')
  await addBottle(page, 'Synthetic soak v1', [], 'Booster')
  await page.getByRole('button', { name: /^Synthetic soak v1/ }).click()
  const bottle = page.getByRole('dialog')
  await bottle.getByRole('button', { name: 'Edit details', exact: true }).click()
  await bottle.getByRole('tab', { name: 'Contents', exact: true }).click()
  await bottle.getByRole('group', { name: 'Bleach', exact: true }).getByRole('button', { name: 'None', exact: true }).click()
  await openAdvanced(bottle)
  await expect(bottle.getByLabel('Lipase', { exact: true })).toHaveValue('unknown')
  await bottle.getByLabel('Lipase', { exact: true }).selectOption('absent')
  await bottle.getByLabel('Lipase', { exact: true }).selectOption('present')
  await bottle.getByLabel('Exact variant, market and pack code').fill('Synthetic v1 / test market / test-code')
  await bottle.getByLabel('Read from (pack or manufacturer URL)').fill('Synthetic manufacturer ingredient record')
  await expect(bottle).toContainText('Lipase')
  await bottle.getByRole('tab', { name: 'Directions', exact: true }).click()
  await bottle.getByLabel('Do not use on these materials', { exact: true }).fill('wool, silk')
  await bottle.getByRole('tab', { name: 'Pretreatment', exact: true }).click()
  await bottle.getByRole('checkbox', { name: 'Label gives a measured pretreatment', exact: true }).check()
  await bottle.getByLabel('Treatment type on the label').selectOption('lipase')
  await bottle.getByRole('checkbox', { name: 'Oil or grease', exact: true }).check()
  await bottle.getByRole('checkbox', { name: 'Label supports a container soak', exact: true }).check()
  for (const [label, value] of [['Label water volume (liters)', '2'], ['Minimum soak time (minutes)', '1'], ['Maximum soak time (minutes)', '3'], ['Maximum water temperature (°C)', '30'], ['After soaking: removal, rinse and transfer instructions', 'Synthetic transfer directions'], ['Pretreatment dose (mL)', '10'], ['Pretreatment directions', 'Synthetic soak directions'], ['Materials the label permits', 'cotton']]) await bottle.getByLabel(label!, { exact: true }).fill(value!)
  await bottle.getByRole('tab', { name: 'Warnings', exact: true }).click()
  await expect(bottle.getByLabel('Do not use on these materials', { exact: true })).toHaveValue('wool, silk')
  await bottle.getByRole('tab', { name: 'Pretreatment', exact: true }).click()
  await expect(bottle.getByLabel('Materials the label permits', { exact: true })).toHaveValue('cotton')
  await bottle.getByRole('checkbox', { name: 'I’ve checked the pack', exact: true }).check()
  await bottle.getByRole('button', { name: 'Save', exact: true }).click()
  await bottle.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(bottle).toHaveCount(0)
  const treatment = (await client.query(api.inventory.list, { householdId })).supplies.find((entry) => entry.name === 'Synthetic soak v1')!
  expect(treatment.safety?.lipase?.status).toBe('present')
  expect(treatment.safety?.pretreatment?.soak?.waterLitres).toBe(2)
  expect(treatment.safety?.incompatibleMaterials).toEqual(['silk', 'wool'])
  expect(treatment.safety?.pretreatment?.safeMaterials).toEqual(['cotton'])
  await client.mutation(api.closet.flagDirty, { textileIds: [shirt.textileId], reasons: ['food'], soilLevel: 'normal', stainReport: { kind: 'oil_grease', priorTreatmentAttempts: [] } })
  await page.goto(`/laundry?item=${shirt.textileId}`)
  await page.getByRole('button', { name: 'Edit stains and notes', exact: true }).click()
  await page.locator('summary', { hasText: 'Odor or residue keeps coming back?' }).click()
  await page.getByLabel('What do you notice?').selectOption('oily')
  await page.getByLabel('When does it appear?').selectOption('after_wearing')
  await page.getByLabel('Has it happened before?').selectOption('yes')
  await page.getByLabel('Previous wash, additives or machine issues (optional)').fill('Synthetic wash history')
  await page.getByRole('button', { name: 'Save care details', exact: true }).click()
  await expect(page.getByText('Care saved for 1 item', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  const recompute = () => client.mutation(api.plans.recompute, { householdId, selectedTextileIds: [shirt.textileId], pretreatmentChoices: [{ textileId: shirt.textileId, supplyId: treatment.supplyId }], clientInputHash: 'chemistry-browser' })
  await client.mutation(api.inventory.updateSupply, { supplyId: treatment.supplyId, safety: { ...treatment.safety!, incompatibleSupplyIds: [detergent.supplyId] } })
  const blocked = await recompute()
  expect((await client.query(api.plans.get, { planId: blocked.planId }))?.loadStates.every((load) => !load.startable)).toBe(true)
  await client.mutation(api.inventory.updateSupply, { supplyId: treatment.supplyId, safety: treatment.safety! })
  const planned = await recompute(), plan = (await client.query(api.plans.get, { planId: planned.planId }))!
  expect(plan.result.status).toBe('ready')
  const load = plan.result.loads[0]!
  await client.mutation(api.plans.confirmRecipe, { planId: planned.planId, loadId: load.id, machineId: inventory.machines[0]!.machineId })
  const { sessionId } = await client.mutation(api.execution.start, { planId: planned.planId, loadId: load.id, idempotencyKey: 'chemistry-browser' })
  await page.goto(`/session/${sessionId}`)
  await page.getByRole('button', { name: 'Start preparation', exact: true }).click()
  await page.getByLabel('Measured water (liters)').fill('4')
  await page.getByLabel('Measured water temperature (°C)').fill('20')
  await expect(page.locator('.machine-step')).toContainText('Add 20 ml for 4 L')
  await page.getByRole('button', { name: 'Start measured soak', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Soaking', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.locator('.machine-step')).toContainText('4 L · 20°C')
  await expect(page.locator('.machine-step')).toContainText('Synthetic transfer directions')
  await page.screenshot({ path: testInfo.outputPath('chemistry-soaking-phone.png'), fullPage: true })
  const detail = await client.query(api.execution.sessionDetail, { sessionId }), soak = detail.actions.find((action) => action.kind === 'treatment')!
  expect(soak.kind === 'treatment' && soak.soakStarted?.amount).toBe(20)
  // Backend fake-time tests prove limits; do not pretend physical time passed in this test.
  await client.mutation(api.actions.recordAction, { sessionId, actionId: soak.id, status: 'missed' })
  await expect(page.getByRole('button', { name: 'Done · next step', exact: true })).toBeVisible()
  await finishSession(page)
  const record = (await client.query(api.sessions.washRecordsForTextile, { textileId: shirt.textileId }))[0]!
  expect(record.soaks).toMatchObject([{ waterLitres: 4, amount: 20, status: 'missed' }])
  expect(record.observation?.recurring).toBe(true)
  expect(record.activityContext).toMatchObject({ version: 2, independentWashId: sessionId, quantity: 1,
    garment: { textileId: shirt.textileId }, washer: { telemetry: false } })
  expect(record.activityContext?.products.find((entry) => entry.supplyId === treatment.supplyId)?.context?.safety?.lipase)
    .toEqual(treatment.safety?.lipase)
  expect(record.drying.outcome).not.toBe('queued')
  expect((await client.query(api.inventory.list, { householdId })).textiles[0]?.status).toBe('clean')
  await page.goto(`/closet?item=${shirt.textileId}`)
  await page.getByRole('tab', { name: 'History', exact: true }).click()
  await page.getByRole('button', { name: 'How did a wash turn out?', exact: true }).click()
  await page.getByLabel('When did you check?').selectOption('after_wearing')
  await page.getByRole('button', { name: 'Record result', exact: true }).click()
  await page.getByLabel('What changed?').selectOption('worse')
  await page.getByLabel('Notes (optional)', { exact: true }).fill('Synthetic outcome, not a physical wash')
  await page.getByRole('button', { name: 'Save assessment', exact: true }).click()
  await expect(page.getByText('Assessment saved.', { exact: true })).toBeVisible()
  // Assessments are private records of their own, attached to the wash record.
  const [washRecord] = await client.query(api.sessions.washRecordsForTextile, { textileId: shirt.textileId })
  expect((await client.query(api.outcomeAssessments.forRecord, { recordId: washRecord!._id }))[0]?.result).toBe('worse')
  await page.screenshot({ path: testInfo.outputPath('chemistry-assessment-phone.png'), fullPage: true })
  await page.context().close()
})
