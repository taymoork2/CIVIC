import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { convexAs, createHousehold, signUp } from './flows'

test('drying answers stay visible, can be cleared and save natural drying in intake and edits', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await signUp(page, 'drying-label', 'Synthetic Drying')
  await createHousehold(page)
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: 'Add clothes', exact: true }).click()
  const sheet = () => page.getByRole('dialog').last()
  await sheet().getByRole('button', { name: 'T-shirt', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: details', exact: true }).click()
  await sheet().getByLabel('Name', { exact: true }).fill('Natural drying tee')
  await sheet().getByRole('button', { name: 'Next: fabric', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: color', exact: true }).click()
  await sheet().getByRole('radio', { name: 'White', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: where from', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: dye', exact: true }).click()
  await sheet().getByRole('radio', { name: 'Washed without dye running', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: care label', exact: true }).click()
  await sheet().getByRole('button', { name: 'Cold', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  await sheet().getByRole('radio', { name: /^Do not bleach/ }).click()
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  await expect(sheet().getByRole('heading', { name: 'How does it dry?', exact: true })).toBeVisible()
  const unknown = () => sheet().getByRole('radio', { name: 'Tag doesn’t say', exact: true })
  await expect(unknown()).toBeInViewport()
  for (const name of ['Line dry', 'Dry flat', 'Drip dry']) await expect(sheet().getByRole('radio', { name, exact: true })).toBeInViewport()
  await unknown().click()
  await unknown().click()
  await expect(unknown()).toHaveAttribute('aria-checked', 'false')
  await expect(sheet().getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
  await sheet().getByRole('radio', { name: 'Line dry', exact: true }).click()
  await expect(sheet().locator('[role="radio"][aria-checked="true"]')).toHaveCount(1)
  await sheet().getByRole('radio', { name: 'Line dry', exact: true }).click()
  await expect(sheet().getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
  await unknown().click()
  for (const name of ['Line dry', 'Dry flat', 'Drip dry']) await expect(sheet().getByRole('radio', { name, exact: true })).toBeVisible()
  await sheet().getByRole('radio', { name: 'Dry flat', exact: true }).click()
  for (const theme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme: theme })
    await page.screenshot({ path: test.info().outputPath(`drying-label-${theme}.png`), animations: 'disabled' })
  }
  await sheet().getByRole('button', { name: 'Next', exact: true }).click()
  await sheet().getByRole('radio', { name: 'No stains', exact: true }).click()
  await sheet().getByRole('button', { name: 'Next: review', exact: true }).click()
  await sheet().getByRole('button', { name: 'Save item', exact: true }).click()
  await sheet().getByRole('button', { name: 'Done', exact: true }).click()
  const { client, householdId } = await convexAs(page)
  const care = async () => (await client.query(api.inventory.list, { householdId })).textiles[0]!.care
  expect(await care()).toMatchObject({ dryMethod: 'dry_flat' })
  await page.getByRole('button', { name: /^Natural drying tee,/ }).click()
  await sheet().getByRole('button', { name: /^Drying: Dry flat/ }).click()
  await unknown().click()
  await expect(sheet().getByRole('radio', { name: 'Dry flat', exact: true })).toBeVisible()
  await sheet().getByRole('radio', { name: 'Line dry', exact: true }).click()
  await sheet().getByRole('button', { name: 'Save', exact: true }).click()
  expect(await care()).toMatchObject({ dryMethod: 'line_dry' })
  await page.reload()
  await expect(page.getByRole('dialog').getByRole('button', { name: /^Drying: Line dry/ })).toBeVisible()
})
