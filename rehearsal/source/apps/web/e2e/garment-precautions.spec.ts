import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addProductAndWasher, answerCards, convexAs, createHousehold, freshPage, signUp, openAdvanced } from './flows'

test('construction facts stay piece-scoped, label-first and optional through reload and preparation', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 900 })
    await signUp(page, 'garment-precautions', 'Alex Precautions')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addClothes(page, { name: 'Synthetic matching shirts', count: 2 })
    await page.getByRole('button', { name: /^Synthetic matching shirts,/ }).click()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    await page.getByRole('button', { name: 'Record construction details', exact: true }).click()
    const draft = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Construction details', exact: true }) })
    await expect(draft.getByRole('button', { name: 'Save construction details', exact: true })).toBeDisabled()
    await draft.getByRole('checkbox', { name: 'Synthetic matching shirts · matching piece 1', exact: true }).check()
    await draft.getByLabel('Construction feature', { exact: true }).selectOption({ label: 'Zippers' })
    await draft.getByLabel('Zippers present?', { exact: true }).selectOption('present')
    await draft.getByLabel('Where you checked zippers', { exact: true }).fill('Synthetic observed zipper on selected piece only')
    await draft.getByLabel('Construction feature', { exact: true }).selectOption({ label: 'Delicate trim (such as lace, beads or sequins)' })
    await draft.getByLabel('Delicate trim (such as lace, beads or sequins) present?', { exact: true }).selectOption('present')
    await draft.getByLabel('Where you checked delicate trim (such as lace, beads or sequins)', { exact: true }).fill('Synthetic observed trim; no real garment claim')
    await page.keyboard.press('Escape')
    await expect(page.getByText('Discard your changes?', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
    await draft.getByLabel('Construction feature', { exact: true }).selectOption({ label: 'Zippers · present' })
    await expect(draft.getByLabel('Where you checked zippers', { exact: true })).toHaveValue('Synthetic observed zipper on selected piece only')
    await page.setViewportSize({ width: 320, height: 900 })
    await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '32px' })
    await page.screenshot({ path: testInfo.outputPath('construction-details-narrow-dark-large.png') })
    const fit = await draft.evaluate((element) => ({ width: element.clientWidth, scroll: element.scrollWidth,
      overflow: [...element.querySelectorAll<HTMLElement>('*')].filter((node) => node.getBoundingClientRect().right > element.getBoundingClientRect().right + 1).map((node) => ({ tag: node.tagName, text: node.textContent?.slice(0, 100), width: node.clientWidth, scroll: node.scrollWidth, className: node.className })).slice(0, 12) }))
    await testInfo.attach('construction-fit.json', { body: JSON.stringify(fit), contentType: 'application/json' })
    expect(fit.scroll).toBeLessThanOrEqual(fit.width + 1)
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await draft.getByRole('checkbox', { name: 'I’ve checked these construction facts for this piece.', exact: true }).check()
    await draft.getByRole('button', { name: 'Save construction details', exact: true }).click()
    await expect(draft).toHaveCount(0)
    await page.reload()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
    await openAdvanced(page, 'More')
    await expect(page.getByRole('dialog').last().getByText('Zippers: present · observed · Source: Synthetic observed zipper on selected piece only', { exact: true })).toBeVisible()
    await expect(page.getByRole('dialog').last().getByText('Zippers: not recorded or unclear', { exact: true })).toHaveCount(1)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Edit item details', exact: true })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const { client, householdId } = await convexAs(page)
    const pieces = (await client.query(api.inventory.list, { householdId })).textiles
    const adorned = pieces.find((piece) => piece.decoration?.construction?.zipper?.presence === 'present')!
    const unknown = pieces.find((piece) => piece.textileId !== adorned.textileId)!
    const instructions = { source: 'Synthetic exact label', preparation: ['Leave pocket zippers open'], washing: [], beforeDrying: [], drying: [], afterDrying: [], ironing: [] }
    await client.mutation(api.inventory.setCareInstructions, { textileId: adorned.textileId, instructions, expectedInstructions: null })
    const { planId } = await client.mutation(api.plans.recompute, { householdId, selectedTextileIds: pieces.map((piece) => piece.textileId), clientInputHash: 'construction-case' })
    const plan = (await client.query(api.plans.get, { planId }))!
    expect(plan.result.loads[0]!.garmentAdvice?.map((tip) => tip.tipId)).toEqual(['protect_delicate_trim'])
    expect(plan.result.loads[0]!.garmentAdvice?.[0]?.textileIds).toEqual([adorned.textileId])
    expect(unknown.decoration).toBeUndefined()
    await page.getByRole('navigation').getByRole('link', { name: /^Laundry/ }).click()
    await page.getByRole('button', { name: 'Load options' }).click()
    await page.getByRole('button', { name: 'Sort again', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Whites load', exact: true })).toBeVisible()
    await answerCards(page)
    await page.getByRole('button', { name: 'I’m at the laundry room', exact: true }).click()
    await page.getByRole('button', { name: /^Confirm recipe for / }).click()
    await page.getByRole('button', { name: 'See what goes in', exact: true }).click()
    await page.getByRole('button', { name: 'Start preparation', exact: true }).click()
    const step = page.locator('section.machine-step')
    await expect(step.getByRole('heading', { name: 'Follow the label before washing', exact: true })).toBeVisible()
    await expect(step).toContainText('Leave pocket zippers open')
    await expect(step.getByRole('button', { name: 'Skip this tip', exact: true })).toHaveCount(0)
    await page.locator('[data-slot="task-footer"]').getByRole('button', { name: 'Done · next step', exact: true }).click()
    await expect(step.getByRole('heading', { name: 'Consider a mesh bag for recorded delicate trim (optional)', exact: true })).toBeVisible()
    await step.getByRole('button', { name: 'Advice source', exact: true }).click()
    await expect(step.getByRole('link', { name: 'Whirlpool general laundry guidance', exact: true })).toBeVisible()
    await expect(step).toContainText('does not establish that the trim is washable')
    await step.getByRole('button', { name: 'Hide optional advice', exact: true }).click()
    await expect(step).toContainText('this piece: hidden · remembered')
    await step.getByRole('button', { name: 'Skip this tip', exact: true }).click()
    await expect(step.getByRole('heading', { name: 'Consider a mesh bag for recorded delicate trim (optional)', exact: true })).toHaveCount(0)
    const inventory = (await client.query(api.inventory.list, { householdId })).textiles
    expect(inventory.find((piece) => piece.textileId === unknown.textileId)!.adviceReminder).toBeUndefined()
    expect(inventory.find((piece) => piece.textileId === adorned.textileId)!.adviceReminder?.enabled).toBe(false)
  } finally { await page.context().close() }
})
