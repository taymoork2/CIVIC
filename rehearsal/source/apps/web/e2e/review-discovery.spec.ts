import { expect, test } from '@playwright/test'

test.use({ trace: 'off', viewport: { width: 1440, height: 1000 } })
test.skip(process.env.REHEARSAL_DISCOVERY_E2E !== '1', 'Run against a disposable Rehearsal host and app sources.')
test('existing HTML and React screens become playable through onboarding, with branches, return state and captures', async ({ page }) => {
  const requests: string[] = [], captures: { message: string; context: { screen: string; state: { fields: { label: string; value: string }[] } } }[] = []
  page.on('request', (request) => { if (request.method() === 'POST' && !request.url().includes('/api/review/')) requests.push(request.url()) })
  page.on('response', async (response) => { if (response.url().endsWith('/api/review/capture') && response.ok()) captures.push(await response.json()) })
  await page.goto('/review')
  await page.locator('.rh-project-trigger').click()
  await page.getByRole('button', { name: 'Connect existing app' }).click()
  await page.getByLabel('App folder', { exact: true }).fill(process.env.REHEARSAL_DISCOVERY_APP!)
  await page.getByLabel('Name for an unconfigured app').fill('Connected notes')
  await page.getByRole('button', { name: 'Discover screens' }).click()
  await expect(page.getByRole('heading', { name: 'Choose screens and paths' })).toBeVisible()
  await expect(page.getByLabel('Include Account', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Include Compose', { exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Generate preview' }).click()
  await expect(page.getByRole('heading', { name: 'Connected notes is ready' })).toBeVisible()
  await page.getByRole('button', { name: 'Open project', exact: true }).click()
  await expect(page.locator('.rh-project-trigger')).toHaveText('Connected notes', { timeout: 60_000 })
  const index = await (await page.request.get('/api/review/index')).json()
  const compose = index.scenarios.find((row: { label: string }) => row.label === 'Compose')
  const archive = index.scenarios.find((row: { label: string }) => row.label === 'Archive')
  const counter = index.scenarios.find((row: { component: string }) => row.component.endsWith('Counter.jsx'))
  expect(archive.branchOf).toBeTruthy()
  await page.goto('/review?scenario=' + compose.id)
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Live Compose"]')
  await expect(frame.getByRole('heading', { name: 'Compose', exact: true })).toBeVisible()
  await frame.getByRole('button', { name: 'Save note' }).click()
  await expect(frame.getByRole('heading', { name: 'Compose', exact: true })).toBeVisible()
  expect(captures).toHaveLength(0)
  await frame.getByLabel('Title', { exact: true }).fill('My retained note')
  await frame.getByRole('link', { name: 'Back home' }).click()
  await expect(frame.getByRole('heading', { name: 'Notes', exact: true })).toBeVisible()
  await frame.getByRole('link', { name: 'Browse archive' }).click()
  await expect(frame.getByRole('heading', { name: 'Archive' })).toBeVisible()
  await frame.getByRole('link', { name: 'Back home' }).click()
  await frame.getByRole('link', { name: 'Write note' }).click()
  await expect(frame.getByLabel('Title', { exact: true })).toHaveValue('My retained note')
  await frame.getByRole('button', { name: 'Save note' }).click()
  await expect(frame.getByRole('heading', { name: 'Saved', exact: true })).toBeVisible()
  await expect.poll(() => captures.length).toBe(5)
  expect(captures.every((row) => row.message.startsWith('Synthetic navigation'))).toBe(true)
  await expect(page.getByText('Synthetic navigation · state carried by Rehearsal · app behavior unverified')).toBeVisible()
  expect(captures.filter((row) => row.context.screen === compose.id).every((row) => row.context.state.fields.some((field) => field.label === 'Title' && field.value === 'My retained note'))).toBe(true)
  await page.goto('/review?scenario=' + counter.id)
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const react = page.frameLocator('iframe[title^="Live "]')
  await expect(react.getByRole('button', { name: 'Count 0' })).toBeVisible()
  await react.getByRole('button', { name: 'Count 0' }).click()
  await expect(react.getByRole('button', { name: 'Count 1' })).toBeVisible()
  expect(requests).toEqual([])
  await page.getByRole('button', { name: 'Coverage', exact: false }).click()
  await expect(page.getByRole('button').filter({ hasText: /Account/ })).toBeVisible()
})
