import { expect, test } from '@playwright/test'
import { api } from '../src/api'
import { addClothes, addMachines, addProductAndWasher, convexAs, createHousehold, finishSession, freshPage, planAndStart, signUp, topDialog } from './flows'

test('one item is selected automatically, while settings and acceptance remain explicit', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' })
  await signUp(page, 'single-preferences', 'Synthetic Preferences')
  await createHousehold(page)
  const { client, householdId } = await convexAs(page)
  await client.mutation(api.inventory.createTextiles, { householdId, name: 'Blue preference tee', kind: 'shirt', quantity: 1, status: 'clean', material: 'cotton', tag: { washMethod: 'machine', cycle: 'normal', maxTemperatureC: 30, dryMethod: 'do_not_tumble_dry' } })
  await page.getByRole('navigation').getByRole('link', { name: 'Closet', exact: true }).click()
  await page.getByRole('button', { name: /^Blue preference tee,/ }).click()
  const record = topDialog(page)
  await record.getByRole('button', { name: 'Edit item details', exact: true }).click()
  await record.getByRole('tab', { name: 'Care', exact: true }).click()
  await record.getByRole('button', { name: 'Wash & dry preferences', exact: true }).click()
  const sheet = page.getByRole('dialog').last()
  const save = sheet.getByRole('button', { name: 'Save preferences', exact: true })
  await expect(save).toBeDisabled()
  await expect(sheet.getByRole('button', { name: 'Follow care label', exact: true })).toHaveCount(0)
  await expect(sheet.getByText('Blue preference tee', { exact: true })).toBeVisible()
  await expect(sheet.getByText(/0 selected/)).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('preferences-single-initial-dark.png'), animations: 'disabled' })
  await sheet.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Keep editing/ })).toHaveCount(0)
  await record.getByRole('button', { name: 'Wash & dry preferences', exact: true }).click()
  await sheet.getByRole('checkbox', { name: 'Wash settings', exact: true }).check()
  await expect(sheet.getByLabel('Wash method', { exact: true })).toHaveValue('machine')
  await expect(sheet.getByLabel('Wash cycle', { exact: true })).toHaveValue('normal')
  await expect(sheet.getByLabel('Water limit (°C)', { exact: true })).toHaveValue('30')
  await sheet.getByLabel('Water limit (°C)', { exact: true }).fill('35')
  await sheet.getByRole('tab', { name: 'Dry', exact: true }).click()
  await expect(sheet.getByRole('checkbox', { name: 'Wash settings', exact: true })).not.toBeVisible()
  await sheet.getByRole('checkbox', { name: 'Drying settings', exact: true }).check()
  await expect(sheet.getByLabel('Drying method', { exact: true })).toHaveValue('')
  await sheet.getByRole('checkbox', { name: 'I accept possible wear or damage to the selected items.', exact: true }).check()
  await expect(save).toBeDisabled()
  await sheet.getByRole('checkbox', { name: 'Drying settings', exact: true }).uncheck()
  await sheet.getByRole('tab', { name: 'Wash', exact: true }).click()
  await expect(sheet.getByLabel('Water limit (°C)', { exact: true })).toHaveValue('35')
  const acceptance = sheet.getByRole('checkbox', { name: 'I accept possible wear or damage to the selected items.', exact: true })
  await expect(save).toBeDisabled()
  await acceptance.check()
  await expect(save).toBeEnabled()
  await sheet.getByLabel('Water limit (°C)', { exact: true }).fill('96')
  await expect(acceptance).not.toBeChecked()
  await acceptance.check()
  await expect(save).toBeDisabled()
  await sheet.getByLabel('Water limit (°C)', { exact: true }).fill('30')
  await acceptance.check()
  await save.click()
  let item = (await client.query(api.inventory.list, { householdId })).textiles[0]!
  expect(item.personalRoutine).toMatchObject({ scope: 'once', settings: { wash: { maximumTemperatureC: 30 } } })
  expect(item.care).toMatchObject({ maxTemperatureC: 30, dryMethod: 'do_not_tumble_dry' })
  await record.getByRole('button', { name: 'Wash & dry preferences', exact: true }).click()
  await sheet.getByRole('button', { name: 'Follow care label', exact: true }).click()
  item = (await client.query(api.inventory.list, { householdId })).textiles[0]!
  expect(item.personalRoutine).toBeUndefined()
})

test('a selected multipack routine preserves labels through reload, washing, drying and expiry', async ({ browser }, testInfo) => {
  const page = await freshPage(browser)
  try {
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await signUp(page, 'personal-routine', 'Robin Routine')
    await createHousehold(page)
    await addProductAndWasher(page)
    await addMachines(page, { kind: 'Dryer', name: 'Laundry room dryer', count: 1, minutes: '45', heat: { 'Low heat': 'Delicates', 'High heat': 'Hot' } })
    await addClothes(page, { name: 'Replaceable tees', count: 3, wash: 'Hand wash', dryer: 'Do not tumble dry' })
    await page.getByRole('button', { name: /^Replaceable tees,/ }).click()
    await page.getByRole('button', { name: 'Edit item details', exact: true }).click()
    await topDialog(page).getByRole('tab', { name: 'Care', exact: true }).click()
    await page.getByRole('button', { name: 'Wash & dry preferences', exact: true }).click()
    const routine = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Wash & dry preferences', exact: true }) })
    await expect(routine.getByRole('button', { name: 'Save preferences', exact: true })).toBeDisabled()
    await routine.getByRole('checkbox', { name: 'Replaceable tees · piece 1', exact: true }).check()
    await routine.getByRole('checkbox', { name: 'Replaceable tees · piece 2', exact: true }).check()
    await expect(routine.getByText('2 pieces selected', { exact: true })).toBeVisible()
    await routine.getByRole('checkbox', { name: 'Wash settings', exact: true }).check()
    await expect(routine.getByLabel('Wash method', { exact: true })).toHaveValue('hand_wash')
    await routine.getByLabel('Wash method', { exact: true }).selectOption('machine')
    await routine.getByLabel('Wash cycle', { exact: true }).selectOption('normal')
    await routine.getByLabel('Water limit (°C)', { exact: true }).fill('40')
    await routine.getByRole('tab', { name: 'Dry', exact: true }).click()
    await routine.getByRole('checkbox', { name: 'Drying settings', exact: true }).check()
    await expect(routine.getByLabel('Drying method', { exact: true })).toHaveValue('')
    await routine.getByLabel('Drying method', { exact: true }).selectOption('tumble')
    await routine.getByLabel('Tumble heat limit', { exact: true }).selectOption('high')
    await routine.getByRole('tab', { name: 'Wash', exact: true }).click()
    await expect(routine.getByLabel('Water limit (°C)', { exact: true })).toHaveValue('40')
    await routine.getByRole('tab', { name: 'Dry', exact: true }).click()
    await expect(routine.getByLabel('Drying method', { exact: true })).toHaveValue('tumble')
    await expect(routine.getByLabel('Tumble heat limit', { exact: true })).toHaveValue('high')
    await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath('routine-dry-phone.png') })
    await routine.getByRole('tab', { name: 'Wash', exact: true }).click()
    await routine.getByRole('checkbox', { name: 'I accept possible wear or damage to the selected items.', exact: true }).check()
    for (const [name, width, scale, theme] of [['phone', 390, 1, 'light'], ['narrow-dark-large', 320, 2, 'dark']] as const) {
      await page.setViewportSize({ width, height: 900 })
      await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' })
      await page.evaluate((scale) => { document.documentElement.style.fontSize = `${16 * scale}px` }, scale)
      await routine.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = 0 })
      await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
      expect(await routine.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
      const bounds = (await routine.boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(-1)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width + 1)
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(901)
      await page.screenshot({ path: testInfo.outputPath(`routine-${name}.png`) })
      await routine.locator('.sheet-scroll').evaluate((element) => { element.scrollTop = element.scrollHeight })
      await page.screenshot({ path: testInfo.outputPath(`routine-${name}-acceptance.png`) })
    }
    await page.setViewportSize({ width: 390, height: 900 })
    await page.emulateMedia({ colorScheme: 'light' })
    await page.evaluate(() => { document.documentElement.style.fontSize = '16px' })
    await routine.getByRole('button', { name: 'Save preferences', exact: true }).click()
    await page.reload()
    await page.getByRole('tab', { name: 'Care', exact: true }).click()
    await expect(page.getByText('Replaceable tees: Wash & dry preferences · this wash only', { exact: true })).toHaveCount(2)
    await page.keyboard.press('Escape')
    await planAndStart(page, 2)
    await finishSession(page)
    const { client, householdId } = await convexAs(page)
    const { textiles } = await client.query(api.inventory.list, { householdId })
    expect(textiles).toHaveLength(3)
    expect(textiles.every((piece) => piece.care?.washMethod === 'hand_wash' && piece.care.dryMethod === 'do_not_tumble_dry' && piece.personalRoutine === undefined)).toBe(true)
    const records = await Promise.all(textiles.map((piece) => client.query(api.sessions.washRecordsForTextile, { textileId: piece.textileId })))
    const washed = records.flat()
    expect(washed).toHaveLength(2)
    for (const record of washed) {
      expect(record.activityContext?.garment?.personalRoutine).toMatchObject({ scope: 'once', settings: { wash: { method: 'machine', maximumTemperatureC: 40 }, dry: { method: 'tumble', heat: 'high' } } })
      expect(record.drying).toMatchObject({ heat: 'high', scope: 'routine' })
    }
    expect(textiles.filter((piece) => piece.status === 'dirty')).toHaveLength(1)
  } finally { await page.context().close() }
})
