import { expect, test } from '@playwright/test'

test.use({ trace: 'off', viewport: { width: 1440, height: 1000 } })
test.skip(process.env.REHEARSAL_PICKER_E2E !== '1', 'Run on a disposable Rehearsal host, not the owner preview.')

test('onboarding creates, plays and switches projects while keeping saved reviews separate', async ({ page }) => {
  const newName = `My new project ${Date.now()}`
  let captures = 0
  page.on('response', (response) => { if (response.url().endsWith('/api/review/capture') && response.ok()) captures++ })
  await page.goto('/review')
  let before = await (await page.request.get('/api/review/index')).json()
  if (before.project.name !== 'Notebook') {
    await page.locator('.rh-project-trigger').click()
    await page.getByRole('button').filter({ hasText: /^NotebookRunnable preview/ }).click()
    await expect(page.locator('.rh-project-trigger')).toHaveText('Notebook', { timeout: 60_000 })
    before = await (await page.request.get('/api/review/index')).json()
  }
  await page.getByRole('button', { name: 'Notebook', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Your projects' })).toBeVisible()
  await page.getByRole('button', { name: 'Connect existing app' }).click()
  await page.getByLabel('App folder', { exact: true }).fill('/this-folder-does-not-exist')
  await page.getByRole('button', { name: 'Discover screens', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('App folder was not found on this host')
  await page.getByLabel('App folder', { exact: true }).fill(process.env.REHEARSAL_PICKER_APP!)
  await page.getByLabel('Name for an unconfigured app').fill('Source only')
  await page.getByRole('button', { name: 'Discover screens', exact: true }).click()
  await page.getByRole('button', { name: 'Keep inventory only', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Source only is ready' })).toBeVisible()
  await expect(page.getByText('Your source inventory is connected.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Open project', exact: true }).click()
  await expect(page.locator('.rh-project-trigger')).toHaveText('Source only', { timeout: 60_000 })
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeDisabled()
  await page.locator('.rh-project-trigger').click()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name').fill(newName)
  await page.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${newName} is ready` })).toBeVisible()
  await page.screenshot({ path: process.env.REHEARSAL_PICKER_EVIDENCE + '/onboarding-ready.png' })
  await page.getByRole('button', { name: 'Open project', exact: true }).click()
  await expect(page.locator('.rh-project-trigger')).toHaveText(newName, { timeout: 60_000 })
  const created = await (await page.request.get('/api/review/index')).json()
  expect(created.project.key).not.toBe(before.project.key)
  await page.goto('/review?scenario=demo.edit')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Live Compose note"]')
  await frame.getByLabel('Title', { exact: true }).fill('A project created without the CLI')
  await frame.getByRole('button', { name: 'Review first', exact: true }).click()
  await expect(frame.getByRole('heading', { name: 'Review your draft' })).toBeVisible()
  await frame.getByRole('button', { name: 'Back to draft' }).click()
  await expect(frame.getByLabel('Title', { exact: true })).toHaveValue('A project created without the CLI')
  await frame.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(frame.getByRole('heading', { name: 'Note saved' })).toBeVisible()
  await expect.poll(() => captures).toBe(3)
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Comment on selection' }).click()
  await page.getByLabel('What should change?').fill('Saved in the new project only.')
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  await expect(page.getByText('Review saved with its target and frozen evidence.', { exact: true })).toBeVisible()
  const reviews = await (await page.request.get('/api/review/feedback')).json()
  expect(reviews).toHaveLength(1)
  await page.locator('.rh-project-trigger').click()
  await page.getByLabel('End the current preview run when switching.', { exact: false }).check()
  await page.getByRole('button').filter({ hasText: /^NotebookRunnable preview/ }).click()
  await expect(page.locator('.rh-project-trigger')).toHaveText('Notebook', { timeout: 60_000 })
  expect((await (await page.request.get('/api/review/index')).json()).project.key).toBe(before.project.key)
  expect(await (await page.request.get('/api/review/feedback')).json()).toEqual([])
  const stale = await page.request.post('/api/review/projects', { headers: { 'x-rehearsal-project': created.project.key }, data: { action: 'select', key: created.project.key } })
  expect(stale.status()).toBe(409)
  await page.locator('.rh-project-trigger').click()
  await page.getByRole('button').filter({ hasText: `${newName}Runnable preview` }).click()
  await expect(page.locator('.rh-project-trigger')).toHaveText(newName, { timeout: 60_000 })
  expect(await (await page.request.get('/api/review/feedback')).json()).toHaveLength(1)
})

test('picker fits a phone viewport, traps keyboard focus and returns it when dismissed', async ({ page }) => {
  await page.setViewportSize({ width: 393, height: 852 })
  await page.goto('/review')
  await page.locator('.rh-project-trigger').click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await expect(page.getByLabel('Project name')).toBeFocused()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(393)
  await page.screenshot({ path: process.env.REHEARSAL_PICKER_EVIDENCE + '/onboarding-phone.png' })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.rh-project-trigger')).toBeFocused()
})
