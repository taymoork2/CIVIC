import { expect, test } from '@playwright/test'

test.use({ trace: 'off', viewport: { width: 393, height: 852 } })
test.skip(process.env.WASHCLOSET_REVIEW_E2E !== '1', 'Run against an isolated linked review server.')
test.beforeEach(async ({ page }) => {
  await page.route('**/*', (route) => new URL(route.request().url()).origin === new URL(process.env.WASHCLOSET_E2E_BASE_URL!).origin ? route.continue() : route.abort())
})

test('family size and stage changes require reset; 1000-item selection survives paging and partial put-away', async ({ page }) => {
  await page.goto('/review-frame.html?scenario=family.drying')
  await page.getByText('Simulation settings', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Family of five' })).toBeVisible()
  await page.getByText('Simulation settings', { exact: true }).click()
  await expect(page.getByRole('checkbox')).toHaveCount(40)
  await page.getByRole('searchbox', { name: 'Search drying check' }).fill('0000')
  await page.getByRole('checkbox').uncheck()
  await page.getByRole('searchbox', { name: 'Search drying check' }).fill('')
  await page.getByRole('button', { name: 'Next 40' }).click()
  await expect(page.getByText('Groups 41–80 of 1000 · 1000 pieces')).toBeVisible()
  await page.getByRole('button', { name: 'Put away 999 · keep 1 drying' }).click()
  await expect(page.getByText('999 of 999 pieces selected across every page.')).toBeVisible()
  await page.getByRole('button', { name: 'Put away 999 pieces' }).click()
  await expect(page.getByText('1 piece drying', { exact: true })).toBeVisible()
  await page.getByText('Simulation settings', { exact: true }).click()
  await page.getByLabel('Family size').selectOption('100')
  await expect(page.getByLabel('Family size')).toHaveValue('1000')
  await page.getByRole('button', { name: 'Keep current run' }).click()
  await expect(page.getByText('1 piece drying', { exact: true })).toBeVisible()
  await page.getByLabel('Family size').selectOption('100')
  await page.getByRole('button', { name: 'Restart simulation' }).click()
  await expect(page.getByLabel('Family size')).toHaveValue('100')
  await page.getByText('Simulation settings', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Put away 100 dry pieces' })).toBeVisible()
  expect(await page.evaluate(() => window.reviewPreview!.config.simulation)).toEqual({ pieces: 100, stage: 'drying' })
})

test('each preset renders the real presenter at 100, 500 and 1000 items without contacting a backend', async ({ page }) => {
  for (const pieces of [100, 500, 1000]) for (const stage of ['planning', 'washing', 'drying', 'putaway']) {
    await page.goto(`/review-frame.html?scenario=family.${stage}&familySize=${pieces}`)
    await page.getByText('Simulation settings', { exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Family of five' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Preview unavailable' })).toHaveCount(0)
    await expect(page.getByLabel('Family size')).toHaveValue(String(pieces))
    await page.getByText('Simulation settings', { exact: true }).click()
    if (stage === 'washing') await expect(page.getByText(`Load 1 of ${pieces / 20} · 20 items. Only this completed load transfers to drying.`)).toBeVisible()
    if (stage === 'drying') await expect(page.getByRole('checkbox')).toHaveCount(40)
    if (stage === 'putaway') await expect(page.getByRole('button', { name: `Put away ${pieces} pieces`, exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

test('a completed load transfers only its original twenty items into drying', async ({ page }) => {
  await page.goto('/review-frame.html?scenario=family.washing&familySize=500')
  await page.getByRole('button', { name: /Washer.*done|Washer.*finished|Wash.*done/i }).click()
  await expect(page.getByRole('button', { name: 'Move to drying queue', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Move to drying queue', exact: true }).click()
  await expect(page.getByLabel('Family care progress')).toContainText('480 awaiting wash · 20 in drying · 0 put away')
  const transferred = await page.evaluate(() => window.reviewPreview!.data().textiles.filter((item) => item.status === 'hanging').map((item) => item.textileId))
  expect(transferred).toEqual(Array.from({ length: 20 }, (_, index) => `preview-family-item-${index}`))
  await expect(page.getByRole('heading', { name: 'Preview unavailable' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Wash next load' }).click()
  await expect(page.getByText('Load 2 of 25 · 20 items. Only this completed load transfers to drying.')).toBeVisible()
  await page.getByRole('button', { name: 'View drying queue' }).click()
  await expect(page.getByLabel('Family care progress')).toContainText('480 awaiting wash · 20 in drying · 0 put away')
})

test('canvas reviews retain the family preset and an agent can retrieve its brief', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/review?scenario=family.drying&familySize=500')
  await page.getByRole('button', { name: 'Play', exact: true }).click()
  const frame = page.frameLocator('iframe[title="Live Family · drying check"]')
  await frame.getByText('Simulation settings', { exact: true }).click()
  await expect(frame.getByLabel('Family size')).toHaveValue('500')
  await frame.getByText('Simulation settings', { exact: true }).click()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Comment on selection' }).click()
  await page.getByLabel('What should change?').fill('QA: preserve the family preset in this review.')
  await page.getByRole('button', { name: 'Save review', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Download agent brief' })).toBeVisible()
  const saved = (await (await page.request.get('/api/review/feedback')).json()).findLast((row: { message: string }) => row.message === 'QA: preserve the family preset in this review.')
  expect(saved.context.simulation).toEqual({ pieces: 500, stage: 'drying' })
  expect(saved.reproduction).toContain('familySize=500&familyStage=drying')
  expect(await (await page.request.get(`/api/review/feedback/${saved.id}/handoff`)).text()).toContain('family-preview.tsx')
  await page.unrouteAll({ behavior: 'wait' })
})

test('all five loads retain their items through washing, partial drying and put-away', async ({ page }) => {
  await page.goto('/review-frame.html?scenario=family.planning&familySize=100')
  for (let load = 0; load < 5; load++) {
    await page.getByRole('button', { name: 'Wash next load' }).click()
    await expect(page.getByText(`Load ${load + 1} of 5 · 20 items. Only this completed load transfers to drying.`)).toBeVisible()
    await page.getByRole('button', { name: /Washer.*done|Washer.*finished|Wash.*done/i }).click()
    await page.getByRole('button', { name: 'Move to drying queue', exact: true }).click()
    await expect(page.getByLabel('Family care progress')).toContainText(`${80 - load * 20} awaiting wash · ${(load + 1) * 20} in drying · 0 put away`)
    await expect(page.getByRole('button', { name: new RegExp(`item ${String(load * 20).padStart(4, '0')},`) })).toBeVisible()
    await page.getByRole('button', { name: 'Hang 20 pieces to dry', exact: true }).click()
  }
  await expect(page.getByRole('button', { name: 'Wash next load' })).toHaveCount(0)
  await page.getByRole('button', { name: /Check when dry$/ }).first().click()
  await page.getByRole('checkbox').first().uncheck()
  await page.getByRole('button', { name: 'Put away 19 · keep 1 drying', exact: true }).click()
  await page.getByRole('button', { name: 'Put away 19 pieces', exact: true }).click()
  await expect(page.getByLabel('Family care progress')).toContainText('0 awaiting wash · 81 in drying · 19 put away')
  for (const count of [1, 20, 20, 20, 20]) {
    await page.getByRole('button', { name: /Check when dry$/ }).first().click()
    await page.getByRole('checkbox').first().check()
    await page.getByRole('button', { name: `Put away ${count} dry ${count === 1 ? 'piece' : 'pieces'}`, exact: true }).click()
    await page.getByRole('button', { name: `Put away ${count} ${count === 1 ? 'piece' : 'pieces'}`, exact: true }).click()
  }
  await expect(page.getByLabel('Family care progress')).toContainText('0 awaiting wash · 0 in drying · 100 put away')
  const final = await page.evaluate(() => window.reviewPreview!.data().textiles.map((item) => ({ id: item.textileId, status: item.status, washes: item.washCount })))
  expect(final).toEqual(Array.from({ length: 100 }, (_, index) => ({ id: `preview-family-item-${index}`, status: 'clean', washes: 1 })))
})

test('failed wash or drying actions preserve the current items and selected inputs', async ({ page }) => {
  await page.goto('/review-frame.html?scenario=family.washing&familySize=500&condition=save-error')
  await page.getByRole('button', { name: /Washer.*done|Washer.*finished|Wash.*done/i }).click()
  await expect(page.getByText('Synthetic wash unavailable in this condition; the current load is retained.')).toBeVisible()
  await expect(page.getByLabel('Family care progress')).toContainText('500 awaiting wash · 0 in drying · 0 put away')
  await page.goto('/review-frame.html?scenario=family.drying&familySize=100&condition=save-error')
  await page.getByRole('checkbox').first().uncheck()
  await page.getByRole('button', { name: 'Put away 99 · keep 1 drying', exact: true }).click()
  await expect(page.getByText('Synthetic drying unavailable in this condition; all items and selections are retained.')).toBeVisible()
  await expect(page.getByRole('checkbox').first()).not.toBeChecked()
  await expect(page.getByLabel('Family care progress')).toContainText('0 awaiting wash · 100 in drying · 0 put away')
})

