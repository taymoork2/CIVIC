// Converts Lucide icon nodes (ISC) into ONE 24-unit path `d` string each and writes src/control-icons.ts.
// Usage: node scripts/vendor-lucide.mjs [path/to/lucide-icon-nodes.json]
//   (a { "icon-name": [[tag, attrs], ...] } map, e.g. from lucide-static's icon-nodes or `lucide/dist/esm/icons`).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/** Our name -> Lucide name. Names we already draw (plus, trash, clock, signout, people, drop, wind, ...) are not repeated here. */
export const wanted = {
  chevronRight: 'chevron-right', chevronLeft: 'chevron-left', chevronDown: 'chevron-down',
  x: 'x', arrowLeft: 'arrow-left', check: 'check', circleCheck: 'circle-check', minus: 'minus',
  search: 'search', funnel: 'funnel', sliders: 'sliders-horizontal', ellipsis: 'ellipsis',
  swap: 'arrow-left-right', skip: 'skip-forward', help: 'circle-question-mark', alert: 'circle-alert',
  offline: 'cloud-off', history: 'rotate-ccw-clock', signpost: 'signpost', bug: 'bug',
  chat: 'message-circle-more', lightbulb: 'lightbulb', cloud: 'cloud', utensils: 'utensils',
  flower: 'flower-2', leaf: 'leaf', pen: 'pen-tool', shieldCheck: 'shield-check', sparkles: 'sparkles',
  waves: 'waves-horizontal',
}

const n = (v) => +(+v).toFixed(3)
const num = (a, k, d = 0) => (a[k] === undefined ? d : +a[k])

const NUM = String.raw`-?(?:\d+\.?\d*|\.\d+)`
/** A path's leading relative `m x y …` is absolute (the pen starts at 0 0); implicit pairs after it stay relative, as `l`. Pieces joined later must not inherit the pen. */
function absoluteStart(d) {
  const m = d.trim().match(new RegExp(`^m\\s*(${NUM})[\\s,]*(${NUM})([\\s\\S]*)$`))
  if (!m) return d.trim()
  const rest = m[3].trim()
  return `M${m[1]} ${m[2]}` + (rest === '' ? '' : /^[-.\d]/.test(rest) ? 'l' + rest : rest)
}

function shape(tag, a) {
  switch (tag) {
    case 'path': return absoluteStart(a.d)
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
    case 'polyline': case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(Number)
      let d = `M${p[0]} ${p[1]}`
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`
      return tag === 'polygon' ? d + 'Z' : d
    }
    case 'circle': { const r = num(a, 'r'), cx = num(a, 'cx'), cy = num(a, 'cy'); return `M${n(cx - r)} ${n(cy)}a${r} ${r} 0 1 0 ${n(2 * r)} 0a${r} ${r} 0 1 0 ${n(-2 * r)} 0Z` }
    case 'ellipse': { const rx = num(a, 'rx'), ry = num(a, 'ry'), cx = num(a, 'cx'), cy = num(a, 'cy'); return `M${n(cx - rx)} ${n(cy)}a${rx} ${ry} 0 1 0 ${n(2 * rx)} 0a${rx} ${ry} 0 1 0 ${n(-2 * rx)} 0Z` }
    case 'rect': {
      const x = num(a, 'x'), y = num(a, 'y'), w = num(a, 'width'), h = num(a, 'height')
      const rx = Math.min(num(a, 'rx', num(a, 'ry')), w / 2), ry = Math.min(num(a, 'ry', rx), h / 2)
      if (!rx && !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`
    }
    default: throw new Error('unsupported tag ' + tag)
  }
}

export const toPath = (nodes) => nodes.map(([tag, attrs]) => shape(tag, attrs)).join('')

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const nodes = JSON.parse(readFileSync(process.argv[2] ?? (console.error('usage: node vendor-lucide.mjs <lucide-static icon-nodes.json>'), process.exit(1)), 'utf8'))
  const lines = Object.entries(wanted).map(([ours, theirs]) => {
    if (!nodes[theirs]) throw new Error('no Lucide icon ' + theirs)
    return `  ${ours}: '${toPath(nodes[theirs])}', // ${theirs}`
  })
  const out = `// Generated by scripts/vendor-lucide.mjs from Lucide (ISC, see ../LICENSE-lucide). Do not edit by hand.
// Each icon is one path on a 24-unit grid, drawn with stroke and no fill.
export const lucidePaths = {
${lines.join('\n')}
} as const
`
  writeFileSync(new URL('../src/lucide-paths.ts', import.meta.url), out)
  console.log(`wrote ${lines.length} icons`)
}
