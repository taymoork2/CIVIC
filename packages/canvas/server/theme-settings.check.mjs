import assert from 'node:assert/strict'
import { mkdtemp, realpath } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { startCanvas } from './canvas-host.mjs'
import { canvasRoot } from './canvas-root.mjs'
import { moduleReviewAdapter } from './module-adapter.mjs'

async function workspace(t, options = {}) {
  const store = await realpath(await mkdtemp(join(tmpdir(), 'civic-theme-')))
  const server = await startCanvas({ project: join(canvasRoot, 'examples/notebook/civic.project.json'), store, port: 0, logLevel: 'silent' })
  t.after(() => server.close())
  const browser = await moduleReviewAdapter.launchFixtureBrowser()
  t.after(() => browser.close())
  const context = await browser.newContext({ colorScheme: 'light', ...options })
  return { context, origin: `http://127.0.0.1:${server.httpServer.address().port}` }
}

test('shell appearance follows system changes, persists explicit choices and synchronizes browser tabs', { timeout: 90000 }, async t => {
  const { context, origin } = await workspace(t)
  const tab = await context.newPage()
  await tab.goto(origin + '/review')
  await tab.waitForLoadState('networkidle')
  assert.equal(await tab.locator('html').getAttribute('data-civic-theme'), 'light')
  await tab.emulateMedia({ colorScheme: 'dark' })
  await tab.waitForFunction(() => document.documentElement.dataset.civicTheme === 'dark')
  await tab.keyboard.press('Control+,')
  const modal = tab.getByRole('dialog', { name: 'CIVIC settings', exact: true })
  await modal.getByRole('button', { name: 'Light', exact: true }).click()
  await tab.waitForFunction(() => document.documentElement.dataset.civicTheme === 'light')
  await tab.emulateMedia({ colorScheme: 'light' })
  await tab.emulateMedia({ colorScheme: 'dark' })
  assert.equal(await tab.locator('html').getAttribute('data-civic-theme'), 'light')
  await tab.keyboard.press('Escape')
  await tab.reload()
  await tab.waitForLoadState('networkidle')
  assert.equal(await tab.locator('html').getAttribute('data-civic-theme'), 'light')
  const other = await context.newPage()
  await other.goto(origin + '/review')
  await other.waitForLoadState('networkidle')
  await tab.keyboard.press('Control+,')
  await modal.getByRole('button', { name: 'Dark', exact: true }).click()
  await other.waitForFunction(() => document.documentElement.dataset.civicTheme === 'dark')
  await modal.getByRole('button', { name: 'System', exact: true }).click()
  await other.waitForFunction(() => document.documentElement.dataset.civicTheme === 'light')
  assert.equal(await tab.locator('html').getAttribute('data-civic-theme'), 'dark')
})

test('settings stays compact and keyboard accessible at desktop and narrow widths', { timeout: 90000 }, async t => {
  const { context, origin } = await workspace(t)
  for (const width of [1280, 768, 390]) {
    const tab = await context.newPage()
    await tab.setViewportSize({ width, height: 844 })
    await tab.goto(origin + '/review')
    await tab.waitForLoadState('networkidle')
    await tab.getByRole('button', { name: 'Open details', exact: true }).click()
    await tab.getByRole('menuitem', { name: /CIVIC settings/ }).click()
    const modal = tab.getByRole('dialog', { name: 'CIVIC settings', exact: true })
    const box = await modal.boundingBox()
    assert.ok(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= width && box.y + box.height <= 844 && box.height < 520)
    assert.equal(await modal.evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await modal.getByRole('button', { name: 'Dark', exact: true }).click()
    assert.equal(await modal.getByRole('button', { name: 'Dark', exact: true }).getAttribute('aria-pressed'), 'true')
    assert.equal(await modal.evaluate(element => getComputedStyle(element).colorScheme), 'dark')
    if (width === 390) for (const button of await modal.getByRole('button').all()) assert.ok((await button.boundingBox()).height >= 44)
    if (width === 390) for (const section of await modal.getByRole('tab').all()) assert.ok((await section.boundingBox()).height >= 44)
    await modal.getByRole('tab', { name: 'Shortcuts', exact: true }).click()
    await modal.getByRole('table', { name: 'Keyboard shortcuts' }).waitFor()
    assert.match(await modal.innerText(), /Fit app/)
    await modal.getByRole('tab', { name: 'About', exact: true }).click()
    assert.match(await modal.getByRole('tabpanel', { name: 'About', exact: true }).innerText(), /Browser/)
    assert.match(await modal.getByRole('tabpanel', { name: 'About', exact: true }).innerText(), /React 19/)
    assert.equal(await modal.evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await tab.keyboard.press('Escape')
    await modal.waitFor({ state: 'detached' })
    await tab.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Open details')
    await tab.getByRole('button', { name: 'Search this project', exact: true }).click()
    await tab.getByPlaceholder('Search Notebook…').fill('CIVIC settings')
    await tab.getByRole('option', { name: /CIVIC settings/ }).click()
    await modal.waitFor()
    await tab.keyboard.press('Escape')
    assert.equal(await tab.locator('.rh-brand').evaluate(element => element.scrollWidth <= element.clientWidth), true)
    await tab.close()
  }
})

