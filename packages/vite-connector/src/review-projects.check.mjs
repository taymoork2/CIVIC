test('opening an isolated workspace uses its own credentials and keeps the local selection', async t => {
  const { base, host, root, current } = await fixture(), isolated = join(base, 'isolated')
  await mkdir(isolated)
  const remote = await projectPicker(isolated, current); await remote.select(current.key)
  delete process.env.CIVIC_PROJECT; delete process.env.CIVIC_APP_ROOT
  const secretFolder = join(isolated, '.review-data/projects', current.key); await mkdir(secretFolder, { recursive: true })
  await writeFile(join(secretFolder, 'access-key'), 'test-only-secret')
  const requests = []
  const server = createServer(async (req, res) => {
    requests.push({ url: req.url, method: req.method, authorization: req.headers.authorization, project: req.headers['x-rehearsal-project'] })
    res.setHeader('content-type', 'application/json')
    res.end(JSON.stringify(req.method === 'POST' ? { key: current.key } : { project: { key: current.key } }))
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); t.after(() => server.close())
  const origin = `http://127.0.0.1:${server.address().port}`
  const picker = await projectPicker(host, current, { workspaces: [{ store: isolated, origin, name: 'Isolated' }] })
  await assert.rejects(picker.select('../secret', origin), /Unknown saved connection/)
  assert.equal(requests.length, 0)
  const result = await picker.select(current.key, origin)
  assert.equal(result.redirect, origin + '/review')
  assert.ok(!JSON.stringify(result).includes('test-only-secret'))
  assert.equal(requests[0].authorization, 'Bearer test-only-secret'); assert.equal(requests[0].project, current.key)
  assert.equal((await picker.list()).active, current.key)
  assert.equal(current.root, root)
})
